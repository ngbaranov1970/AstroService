<script setup>
// Эмблема из макета B_1: солнце с лучами, два кольца, внутри полумесяц.
// Показывают её все четыре шага онбординга — одна и та же, статичная.
// Данных не принимает; размер и цвет задаёт родитель классами (w-… и text-…).

// Лучи: 12 штрихов через каждые 30°. Вертикальные длиннее — так на макете,
// они задают ось эмблемы. angle — поворот вокруг центра, tip — насколько
// далеко от центра начинается штрих (меньше значение = длиннее луч)
const RAYS = Array.from({ length: 12 }, (_, index) => {
  const angle = index * 30
  const isVertical = angle === 0 || angle === 180
  return { angle, tip: isVertical ? 6 : 16 }
})
</script>

<template>
  <!-- viewBox — своя система координат картинки: рисуем в квадрате 200×200,
       а на экране SVG растянется до ширины, заданной классом снаружи.
       currentColor — «цвет текста этого элемента»: цвет задаётся классом
       text-gold на родителе, и один и тот же SVG подойдёт под любую тему.
       aria-hidden — украшение, экранному диктору читать нечего -->
  <svg viewBox="0 0 200 200" fill="none" aria-hidden="true">
    <!-- Лучи. transform="rotate(угол центр-x центр-y)" поворачивает штрих
         вокруг центра эмблемы — рисуем один вертикальный, остальные это он же
         под другим углом -->
    <line
      v-for="ray in RAYS"
      :key="ray.angle"
      x1="100"
      :y1="ray.tip"
      x2="100"
      y2="32"
      :transform="`rotate(${ray.angle} 100 100)`"
      stroke="currentColor"
      stroke-width="1.2"
      opacity="0.5"
    />

    <!-- Два кольца: внешнее еле видно, внутреннее ярче -->
    <circle cx="100" cy="100" r="60" stroke="currentColor" stroke-width="1" opacity="0.35" />
    <circle cx="100" cy="100" r="52" stroke="currentColor" stroke-width="1.4" />

    <!-- Указатели на кольце сверху и снизу: сверху вершиной вверх, снизу вниз -->
    <path d="M100 43 L106 55 L94 55 Z" fill="currentColor" />
    <path d="M100 157 L94 145 L106 145 Z" fill="currentColor" />

    <!-- Полумесяц. Маска — трафарет: белое в ней видно, чёрное вырезано.
         Круг месяца белый, а сдвинутый влево круг чёрный — он и выедает
         серп. Так дырка получается настоящей: под ней виден фон страницы,
         какого бы цвета он ни стал -->
    <mask id="sun-emblem-crescent">
      <rect width="200" height="200" fill="black" />
      <circle cx="104" cy="100" r="30" fill="white" />
      <circle cx="92" cy="95" r="29" fill="black" />
    </mask>
    <rect width="200" height="200" fill="currentColor" mask="url(#sun-emblem-crescent)" />

    <!-- Точка слева от месяца -->
    <circle cx="70" cy="106" r="3" fill="currentColor" />

    <!-- Две звёздочки-искры по углам. Q — квадратичная кривая: рисует луч,
         подтянутый к центру звезды, отчего она выходит с вогнутыми боками -->
    <path
      d="M42 28 Q43 44 58 46 Q43 48 42 64 Q41 48 26 46 Q41 44 42 28 Z"
      fill="currentColor"
      opacity="0.8"
    />
    <path
      d="M161 146 Q162 157 173 158 Q162 159 161 170 Q160 159 149 158 Q160 157 161 146 Z"
      fill="currentColor"
      opacity="0.8"
    />
  </svg>
</template>
