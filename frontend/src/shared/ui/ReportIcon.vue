<script setup>
// Иконка плитки разбора: колесо, два кольца, ромб в квадрате или месяц.
// Показывает её ReportTile, имя иконки берётся из реестра features/report/reportTypes.js.
// Размер и цвет задаёт родитель классами (w-8 h-8 text-gold) — сам компонент
// рисует только штрихи.

defineProps({
  // Незнакомое имя рисуется колесом: бэкенд может прислать тип, которого фронт
  // ещё не знает, и пустое место в плитке выглядело бы поломкой
  name: { type: String, default: 'natal' },
})

// Деления колеса: 12 штрихов через 30°, по числу знаков зодиака
const SPOKES = Array.from({ length: 12 }, (_, index) => index * 30)
</script>

<template>
  <!-- Общие для всех вариантов настройки штриха вынесены на сам <svg>: вложенные
       фигуры наследуют stroke и толщину, поэтому в каждой группе их не повторяем.
       fill="none" — фигуры не заливаем, у нас всё контурное -->
  <svg
    viewBox="0 0 48 48"
    fill="none"
    stroke="currentColor"
    stroke-width="1.2"
    aria-hidden="true"
  >
    <!-- Совместимость: два пересекающихся кольца -->
    <g v-if="name === 'pair'">
      <circle cx="18" cy="24" r="11" />
      <circle cx="30" cy="24" r="11" />
    </g>

    <!-- Матрица Судьбы: ромб, вписанный в квадрат, и точка в центре -->
    <g v-else-if="name === 'matrix'">
      <!-- rect с rx — прямоугольник со скруглением углов -->
      <rect x="8" y="8" width="32" height="32" rx="1" opacity="0.45" />
      <path d="M24 9 L39 24 L24 39 L9 24 Z" />
      <circle cx="24" cy="24" r="1.6" fill="currentColor" stroke="none" />
    </g>

    <!-- Восточный гороскоп: месяц и звёздочка.
         A в пути — дуга: A rx ry поворот большая-дуга направление конец-x конец-y.
         Серп получается из двух дуг разного радиуса между одними и теми же
         концами: широкая рисует спинку, узкая возвращается и подрезает живот -->
    <g v-else-if="name === 'eastern'">
      <path d="M30 11 A13 13 0 1 0 30 37 A10.5 10.5 0 1 1 30 11 Z" />
      <circle cx="34" cy="16" r="1.6" fill="currentColor" stroke="none" />
    </g>

    <!-- Натальная карта (и всё незнакомое): колесо с делениями -->
    <g v-else>
      <circle cx="24" cy="24" r="20" opacity="0.45" />
      <circle cx="24" cy="24" r="13" />
      <!-- Один штрих между кольцами, повёрнутый вокруг центра 12 раз.
           :key нужен v-for, чтобы Vue отличал элементы списка друг от друга -->
      <line
        v-for="angle in SPOKES"
        :key="angle"
        x1="24"
        y1="4"
        x2="24"
        y2="11"
        :transform="`rotate(${angle} 24 24)`"
        opacity="0.55"
      />
    </g>
  </svg>
</template>
