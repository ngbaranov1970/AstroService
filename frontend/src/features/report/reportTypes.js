// Чем дополняем описание незнакомого типа. Пустых полей быть не должно:
// плитка обязана нарисоваться, даже когда фронт про тип ничего не знает
const FALLBACK = Object.freeze({
  // В хвост списка: где место новому продукту, знает человек, а не сервер
  order: 99,
  icon: 'natal',
  tileTitle: null,
  tileNote: null,
  shape: 'narrow',
  onHome: true,
  comingSoon: false,
})

/** Как показывать разбор этого типа. Незнакомый тип описывается нейтрально:
 *  бэкенд может выпустить новый продукт до релиза фронта, и лучше показать
 *  простую плитку, чем уронить экран. */
export function describe(type) {
  // Спред разворачивает поля обоих объектов, при совпадении побеждает правый —
  // как {**FALLBACK, **REPORT_TYPES[type]} в Python
  return { type, ...FALLBACK, ...REPORT_TYPES[type] }
}
