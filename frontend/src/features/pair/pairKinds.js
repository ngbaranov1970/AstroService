// Подписи типов связи для человека. Показывают их экран сборки пары (кнопки
// выбора) и список пар (метка под именами) — отсюда отдельный модуль, а не
// константа внутри экрана: разъехавшиеся слова про одно и то же читаются как
// два разных продукта.
//
// Сами значения ('romance', 'family') живут в PAIR_KIND (shared/api/endpoints),
// потому что уезжают на сервер. Здесь только слова.

import { PAIR_KIND } from '@/shared/api/endpoints'

// Порядок массива — порядок кнопок на экране сборки
export const KINDS = Object.freeze([
  { value: PAIR_KIND.ROMANCE, label: 'Романтика', hint: 'Пара, влюблённость, брак' },
  { value: PAIR_KIND.FAMILY, label: 'Семья', hint: 'Родители, дети, брат или сестра' },
])

/** Короткая подпись типа связи. Незнакомое значение (сервер завёл третий вид,
 *  фронт ещё не знает) не должно оставлять на экране пустоту. */
export function kindLabel(kind) {
  return KINDS.find((item) => item.value === kind)?.label ?? 'Связь'
}
