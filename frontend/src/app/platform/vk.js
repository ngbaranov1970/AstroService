// Адаптер платформы VK: единственное место во фронте, где зовётся vk-bridge.
// Остальной код работает с контрактом (init/obtainToken/openExternal/...),
// поэтому тот же фронт поедет в Telegram и веб — там будут свои адаптеры.

import bridge from '@vkontakte/vk-bridge'

import { launchGoal } from '@/app/entry'

// Параметры запуска, снятые при старте: sign и все vk_*. Читаются один раз —
// внутри приложения адрес меняет роутер, и вернуться к исходному нельзя
let launchParams = null

// Наш фон из токенов дизайна. Дублируем строкой: bridge принимает цвет
// значением, CSS-переменную он прочитать не может
const BG = '#171310'

// Сколько ждём ответа клиента VK на окно подписки или разрешения.
// Своё ограничение нужно потому, что клиент может не ответить вовсе: тогда
// промис не выполняется и не отклоняется, catch не срабатывает, и кнопка для
// человека выглядит просто сломанной (проверено на стенде 27.08.2026)
const BRIDGE_TIMEOUT_MS = 15000

// Отдельный срок для вызовов на старте: за ними стоит монтирование Vue, и
// каждая секунда ожидания — секунда пустого экрана. Ждать столько же, сколько
// окна подписки, нельзя: 15 секунд темноты человек читает как «сломалось»
const STARTUP_TIMEOUT_MS = 3000

/** Позвать метод Bridge, но не ждать дольше timeoutMs.
 *  Promise.race берёт несколько промисов и отдаёт результат того, кто
 *  финишировал первым; второй участник здесь — таймер, отклоняющий гонку.
 *  Значение параметра по умолчанию (= BRIDGE_TIMEOUT_MS) работает как в Python:
 *  вызов из двух аргументов получает его сам. */
function sendWithTimeout(method, params, timeoutMs = BRIDGE_TIMEOUT_MS) {
  return Promise.race([
    bridge.send(method, params),
    // Конструктор промиса получает две функции: первой его завершают успехом,
    // второй — ошибкой. Успех таймеру не нужен, поэтому первая не названа
    new Promise((_, reject) => {
      setTimeout(() => reject(new Error('VK не ответил')), timeoutMs)
    }),
  ])
}

/** Снять параметры запуска из адреса; null, если открыто не из VK.
 *  VK кладёт их в query-строку iframe, а роутер у нас hash-овый и
 *  location.search не трогает — значит параметры доживают до авторизации. */
function readLaunchParams() {
  const search = new URLSearchParams(window.location.search)
  // Object.fromEntries собирает объект из пар [ключ, значение] — обратная
  // операция к Object.entries, примерно как dict(pairs) в Python
  const params = Object.fromEntries(search.entries())
  // Подпись — признак того, что это запуск мини-приложения. Нет её —
  // страницу открыли напрямую в браузере, и авторизовать некого
  return params.sign ? params : null
}

export const vkPlatform = {
  name: 'vk',

  /** Инициализация клиента VK. Зовётся из main.js ДО монтирования Vue. */
  async init() {
    launchParams = readLaunchParams()
    // VKWebAppInit — сигнал «приложение загрузилось, убирай прелоадер». Без
    // него страница видна, но накрыта крутилкой VK, и тапы уходят сквозь неё.
    // Ответа ждём не дольше STARTUP_TIMEOUT_MS: в мобильном клиенте его может
    // не прийти вовсе, а за этим await стоит mount() — молчание моста держало
    // телефон на пустом фоне навсегда, десктоп при этом работал (01.09.2026)
    await sendWithTimeout('VKWebAppInit', {}, STARTUP_TIMEOUT_MS)
  },

  /** Есть ли чем авторизоваться на этой платформе. */
  canAuth() {
    return launchParams !== null
  },

  /** Обменять параметры запуска на сессию: {token, expires_in, user}.
   *  http передаётся аргументом, чтобы адаптер не зависел от api-слоя.
   *  Бросает ApiError: 401 — подпись не принята, 503 — вход из VK не настроен
   *  в окружении (пустой VK_SECURE_KEY на бэкенде). */
  async obtainToken(http) {
    if (!launchParams) {
      throw new Error('Приложение открыто не из VK — параметров запуска нет')
    }
    // anonymous: true — этому запросу не нужен заголовок с токеном, и его 401
    // не должен запускать перевыпуск: перевыпуск и есть этот запрос.
    // entry — плитка меню сообщества, с которой открыли приложение (или null):
    // бэкенд пишет её в событие app_opened, чтобы видеть, какая плитка работает
    return await http.post(
      '/auth/vk',
      { params: launchParams, entry: launchGoal },
      { anonymous: true },
    )
  },

  /** Открыть внешнюю ссылку (оплата) в браузере поверх приложения.
   *  Оплата обязана уходить наружу: цифровые товары внутри Mini App
   *  разрешены только за «голоса», а на iOS запрещены вовсе. */
  openExternal(url) {
    // window.open в клиенте VK на iOS не открывает ничего и молчит: WKWebView
    // не передаёт клиенту запрос на новое окно, кнопка выглядит сломанной.
    // Переход по настоящей ссылке клиент перехватывает и открывает браузер,
    // поэтому ссылку заводим сами и сразу «нажимаем» — она живёт один клик.
    // Метода Bridge для внешних адресов нет (vk-bridge 3.0.2)
    const link = document.createElement('a')
    link.href = url
    // _blank — открыть в новом окне, а не вместо приложения
    link.target = '_blank'
    // noopener — открытая вкладка не получит ссылку на наше окно (window.opener)
    link.rel = 'noopener'
    // Клик засчитывается только по ссылке, лежащей в документе, — вставляем
    // её в конец страницы и убираем сразу после нажатия
    document.body.appendChild(link)
    link.click()
    link.remove()
  },

  /** Подписка на кнопку «назад». Возвращает функцию отписки.
   *  У VK своей кнопки нет: на Android аппаратную обрабатывает сам клиент,
   *  на iOS её нет вовсе. Метод существует ради общего контракта — в
   *  Telegram он подпишется на BackButton, и экраны переписывать не придётся. */
  onBack() {
    return () => {}
  },

  /** Покрасить шапку и статус-бар под наш фон.
   *  Без этого над приложением висит белая полоса — на тёмном макете заметно. */
  async setHeaderColor() {
    try {
      await sendWithTimeout(
        'VKWebAppSetViewSettings',
        {
          // light — светлые значки на тёмном фоне (часы, батарея)
          status_bar_style: 'light',
          action_bar_color: BG,
        },
        STARTUP_TIMEOUT_MS,
      )
    } catch {
      // На desktop_web метода нет, и это не ошибка: шапку там рисует сама VK.
      // Сюда же приходит таймаут: этот вызов стоит на пути к mount(), и ждать
      // молчащий клиент дольше положенного значит держать пустой экран.
      // catch без переменной — «поймать и не смотреть что», нужен для тишины
    }
  },

  /** Работают ли здесь окна VK «подписаться» и «разрешить сообщения».
   *
   *  isEmbedded() смотрит на сам контейнер: страницу могли открыть не как
   *  Mini App, а во встроенном браузере VK (переход по ссылке из сообщения).
   *  Библиотека там на странице есть, а отвечать её запросам некому — send
   *  уходит в никуда и висит вечно. Отсюда проверка до, а не таймаут после. */
  supportsGroup() {
    return bridge.isEmbedded()
  },

  /** Открыть окно VK «Подписаться на сообщество».
   *  Бросает и при отказе человека, и при молчании клиента: для нас это
   *  одно и то же — подписки не случилось. */
  async joinGroup(groupId) {
    await sendWithTimeout('VKWebAppJoinGroup', { group_id: groupId })
  },

  /** Открыть окно VK «Разрешить сообществу писать»; true — разрешение дано.
   *
   *  Ответ VK — объект вида {result: true}. Пришло что угодно другое —
   *  считаем, что разрешения нет: поднять у себя флаг «нам можно писать» по
   *  неясному ответу нельзя, рассылка потом упрётся в отказ API. */
  async allowMessages(groupId) {
    const answer = await sendWithTimeout('VKWebAppAllowMessagesFromGroup', {
      group_id: groupId,
    })
    // ?. — обратись к полю, если объект не null; Boolean() приводит к true/false
    return Boolean(answer?.result)
  },

  /** Закрыть мини-приложение (вернуться в VK). */
  async close() {
    try {
      await bridge.send('VKWebAppClose', { status: 'success' })
    } catch {
      // В desktop_web и в обычном браузере закрывать нечего
    }
  },
}
