#!/usr/bin/env bash
# Ежедневная рассылка гороскопа дня. Ставится в cron на сервере, см. docs/progress.md.
set -euo pipefail

# PATH в cron короче интерактивного (обычно /usr/bin:/bin) — docker найдётся,
# но задаём явно, чтобы поведение не зависело от настроек демона.
PATH=/usr/local/bin:/usr/bin:/bin

# Корень проекта — от места самого скрипта: у cron рабочий каталог свой,
# и относительный путь до docker-compose.yml не нашёлся бы.
PROJECT_DIR=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
cd "$PROJECT_DIR"

echo "$(date '+%F %T') рассылка: запуск${*:+ (}${*}${*:+)}"

# exec, а не run: письма шлёт живой контейнер. `run` поднял бы второй с тем же
# кодом и рассылка прошла бы, но лёгший api — это и есть повод не рассылать,
# а увидеть отказ в логе.
#
# Аргументы прокидываются насквозь: тем же скриптом делается ручная проверка
# охвата (deploy/broadcast.sh --dry-run) и досылка за прошлый день (--date).
if docker compose exec -T api python scripts/broadcast_cli.py "$@"; then
	echo "$(date '+%F %T') ok"
else
	# Код возврата CLI: 1 — поста за сегодня нет либо вызов VK оборвался.
	# Отказы отдельным адресатам сюда не попадают, они в строке итога выше.
	echo "$(date '+%F %T') FAIL: рассылка не прошла, причина строкой выше" >&2
	exit 1
fi
