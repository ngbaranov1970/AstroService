# Периоды гороскопа: ключ -> подпись на кнопке.
# Ключи совпадают с теми, что понимают period_key() и PERIOD_PROMPTS
# в services/ — это один общий «язык» всех слоёв приложения.
PERIODS: dict[str, str] = {
    "day": "На день",
    "week": "На неделю",
    "month": "На месяц",
    "year": "На год",
}


def sign_button_label(sign: str) -> str:
    """Подпись кнопки знака: «♈ Овен».

    Единственная функция в модуле — и то лишь для того, чтобы формат
    кнопки был определён один раз, а не собирался f-строкой
    в каждой клавиатуре.
    """
    name, emoji, _ = SIGNS[sign]
    return f"{emoji} {name}"


