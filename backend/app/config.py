"""Настройки backend: чтение backend/.env через pydantic-settings.

Два принципа, по которым сделан этот файл:

1. Описываем ТОЛЬКО те переменные, которые уже используются: ключ DeepSeek,
   Postgres, секреты стенда, ключи VK. ЮKassa появится здесь тогда же, когда
   появится читающий её код, — иначе обязательное поле без значения роняет
   валидацию на пустом месте.

2. Настройки создаются лениво, через get_settings(), а не как переменная
   уровня модуля. Разница принципиальная: `settings = Settings()` в теле
   модуля означает, что ЛЮБОЙ импорт app.config без заполненного .env
   падает с ValidationError — включая pytest, alembic и скрипты из
   scripts/, которым ключ DeepSeek вообще не нужен. При ленивом варианте
   ошибка возникает только у того кода, который реально полез за ключом.
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from pydantic import SecretStr, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

# Каталог backend/ — на уровень выше пакета app/.
# Путь абсолютный намеренно: pydantic-settings ищет относительный env_file
# от текущего рабочего каталога, а pytest, alembic и scripts/natal_cli.py
# запускаются из разных мест. Тот же приём — в astro_core/geo.py для cities.txt.
BASE_DIR = Path(__file__).resolve().parent.parent


class Settings(BaseSettings):
    """Значения берутся из переменных окружения, затем из backend/.env.

    Окружение имеет приоритет над файлом — так в Docker Compose и на VPS
    секреты передаются напрямую, без монтирования .env внутрь контейнера.
    """

    model_config = SettingsConfigDict(
        env_file=BASE_DIR / ".env",
        env_file_encoding="utf-8",
        # Лишние переменные в .env (служебные, чужие, закомментированные
        # наспех) не должны ронять запуск — иначе каждый новый ключ в файле
        # требует правки этого класса.
        extra="ignore",
    )

    # --- Обязательное ---------------------------------------------------
    # SecretStr вместо str: значение не попадёт в repr(), в traceback
    # и в логи FastAPI при ошибке. Читать через .get_secret_value().
    deepseek_api_key: SecretStr

    # Строка подключения к Postgres в формате SQLAlchemy. Без дефолта
    # намеренно: дефолт вида "...@localhost/astro" означает, что забытая
    # переменная на сервере не роняет запуск, а тихо уводит приложение на
    # локальную базу, которой там нет (или, хуже, есть чужая). Обязательное
    # поле падает сразу и с понятным текстом.
    #
    # Драйвер обязателен в схеме: "postgresql+asyncpg://", а не просто
    # "postgresql://" — иначе SQLAlchemy подставит синхронный psycopg
    # и create_async_engine упадёт с невнятной InvalidRequestError.
    database_url: str

    # --- С безопасными дефолтами ----------------------------------------
    # Логировать ли каждый SQL-запрос (echo движка SQLAlchemy). Отдельный
    # флаг, а не debug: debug влияет на выдачу ошибок наружу, а поток SQL
    # в консоли нужен точечно и мешает даже в dev.
    db_echo: bool = False

    # Режим окружения: "dev" | "prod". Влияет на подробность ошибок и на то,
    # отдаём ли мы /docs наружу.
    app_env: str = "dev"
    debug: bool = False

    # Порог логирования: DEBUG | INFO | WARNING | ERROR. Отдельная настройка,
    # а не производная от debug: на сервере иногда нужно поднять подробность
    # логов на полчаса, не включая при этом подробные ошибки наружу.
    # INFO по умолчанию — видно вызовы LLM и падения, но без мусора.
    log_level: str = "INFO"

    # --- Веб-стенд для обкатки промптов ----------------------------------
    # Секрет из ссылки для тестеров: /?t=<этот секрет>. Открыл по такой
    # ссылке — текущему пользователю (тому, что в cookie) ставится
    # is_tester, а значит открывается полный разбор без оплаты и снимаются
    # лимиты бесплатных генераций.
    #
    # Дефолт None означает «механизм выключен»: без секрета тестером не
    # станет никто. Обратный дефолт («не задан — пускаем всех») превратил бы
    # забытую переменную в открытую дверь к платным разборам за наши деньги.
    web_tester_token: SecretStr | None = None

    # HTTP Basic Auth на /admin. В админке лежат даты и места рождения живых
    # людей, то есть персональные данные, — в открытый интернет её нельзя.
    admin_user: str = "admin"
    # Пароль без дефолта и nullable по той же логике, что и секрет выше:
    # пароль не задан — админка отвечает 503 и не пускает никого. Забытая
    # переменная должна закрывать дверь, а не распахивать.
    admin_password: SecretStr | None = None

    # --- VK Mini App ------------------------------------------------------
    # Идентификатор приложения из настроек VK. Нужен не для проверки подписи
    # (её достаточно ключа ниже), а чтобы сверить vk_app_id из параметров
    # запуска: расхождение означает, что ключ и приложение разъехались —
    # ошибка конфигурации, которую иначе видно только по «подпись неверна».
    vk_app_id: int | None = None

    # «Защищённый ключ» приложения (Разработка → Ключи доступа) — им VK
    # подписывает параметры запуска, им же мы проверяем подпись. Не задан —
    # VK-ветка выключена целиком, тот же дефолт-«закрыто», что у секретов
    # стенда выше.
    vk_secure_key: SecretStr | None = None

    # Ключ, которым подписываются НАШИ сессионные JWT (?s=... в адресе).
    # Отдельный от vk_secure_key намеренно: у них разные роли и разные
    # владельцы — тем проверяем чужие утверждения о личности, этим
    # подписываем свои. Смена ключа разлогинивает всех разом.
    session_secret: SecretStr | None = None

    @field_validator(
        "web_tester_token",
        "admin_password",
        "vk_app_id",
        "vk_secure_key",
        "session_secret",
        mode="before",
    )
    @classmethod
    def _blank_is_unset(cls, v: str | None) -> str | None:
        """Пустая строка = переменная не задана.

        Без этого `ADMIN_PASSWORD=` (пустое значение в .env, который compose
        отдаёт контейнеру через env_file) превращается в SecretStr(""), а
        проверка в web/deps.py смотрит `is None` — и админка пускает по
        пустому паролю вместо 503. Проверено на живом стенде.

        Для vk_app_id причина другая: `VK_APP_ID=` роняет валидацию на
        int(""), то есть приложение не стартует вовсе.
        """
        return None if isinstance(v, str) and not v.strip() else v

    @property
    def is_prod(self) -> bool:
        return self.app_env == "prod"

    @property
    def vk_enabled(self) -> bool:
        """Настроена ли VK-ветка: проверить подпись И выпустить свою сессию.

        Полконфигурации хуже, чем никакой: с ключом VK, но без session_secret
        подпись сойдётся, а JWT выпустить не из чего — человек упрётся в
        ошибку уже после успешного входа.
        """
        return self.vk_secure_key is not None and self.session_secret is not None


@lru_cache
def get_settings() -> Settings:
    """Единственная точка доступа к настройкам.

    lru_cache даёт два эффекта: .env парсится один раз за процесс, и объект
    настроек везде один и тот же. В тестах кеш сбрасывается вызовом
    get_settings.cache_clear() — например, после monkeypatch переменных.
    """
    return Settings()
