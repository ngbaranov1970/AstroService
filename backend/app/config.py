"""Настройки backend: чтение backend/.env через pydantic-settings.

Два принципа, по которым сделан этот файл:

1. Описываем ТОЛЬКО те переменные, которые уже используются: ключ DeepSeek,
   Postgres, пароль админки, ключи VK и ЮKassa. Настройка заводится вместе
   с читающим её кодом, не раньше, — иначе обязательное поле без значения
   роняет валидацию на пустом месте.

2. Настройки создаются лениво, через get_settings(), а не как переменная
   уровня модуля. Разница принципиальная: `settings = Settings()` в теле
   модуля означает, что ЛЮБОЙ импорт app.config без заполненного .env
   падает с ValidationError — включая pytest, alembic и скрипты из
   scripts/, которым ключ DeepSeek вообще не нужен. При ленивом варианте
   ошибка возникает только у того кода, который реально полез за ключом.
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from pydantic import SecretStr, field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict

# Каталог backend/ — на уровень выше пакета app/.
# Путь абсолютный намеренно: pydantic-settings ищет относительный env_file
# от текущего рабочего каталога, а pytest, alembic и scripts/natal_cli.py
# запускаются из разных мест. Тот же приём — в astro_core/geo.py для cities.txt.
BASE_DIR = Path(__file__).resolve().parent.parent


class Settings(BaseSettings):
    """Значения берутся из переменных окружения, затем из backend/.env.

    Окружение имеет приоритет над файлом — так в Docker Compose и на VPS
    секреты передаются напрямую, без монтирования .env внутрь контейнера.
    """

    model_config = SettingsConfigDict(
        env_file=BASE_DIR / ".env",
        env_file_encoding="utf-8",
        # Лишние переменные в .env (служебные, чужие, закомментированные
        # наспех) не должны ронять запуск — иначе каждый новый ключ в файле
        # требует правки этого класса.
        extra="ignore",
    )

    # --- Обязательное ---------------------------------------------------
    # SecretStr вместо str: значение не попадёт в repr(), в traceback
    # и в логи FastAPI при ошибке. Читать через .get_secret_value().
    deepseek_api_key: SecretStr

    # Строка подключения к Postgres в формате SQLAlchemy. Без дефолта
    # намеренно: дефолт вида "...@localhost/astro" означает, что забытая
    # переменная на сервере не роняет запуск, а тихо уводит приложение на
    # локальную базу, которой там нет (или, хуже, есть чужая). Обязательное
    # поле падает сразу и с понятным текстом.
    #
    # Драйвер обязателен в схеме: "postgresql+asyncpg://", а не просто
    # "postgresql://" — иначе SQLAlchemy подставит синхронный psycopg
    # и create_async_engine упадёт с невнятной InvalidRequestError.
    database_url: str

    # --- С безопасными дефолтами ----------------------------------------
    # Логировать ли каждый SQL-запрос (echo движка SQLAlchemy). Отдельный
    # флаг, а не debug: debug влияет на выдачу ошибок наружу, а поток SQL
    # в консоли нужен точечно и мешает даже в dev.
    db_echo: bool = False

    # Режим окружения: "dev" | "prod". Влияет на подробность ошибок и на то,
    # отдаём ли мы /docs наружу.
    app_env: str = "dev"
    debug: bool = False

    # Порог логирования: DEBUG | INFO | WARNING | ERROR. Отдельная настройка,
    # а не производная от debug: на сервере иногда нужно поднять подробность
    # логов на полчаса, не включая при этом подробные ошибки наружу.
    # INFO по умолчанию — видно вызовы LLM и падения, но без мусора.
    log_level: str = "INFO"

    # --- Потолок расходов на DeepSeek -------------------------------------
    # Сколько НЕОПЛАЧЕННЫХ генераций разрешено всему сервису за последние
    # сутки. С отключённым личным счётчиком (free_natal_limit ниже) это
    # единственная защита от трат: холодный трафик берёт бесплатные разборы
    # пачками, и остановить его больше нечему.
    #
    # 3000 — это около 250 ₽ в сутки: по ценам DeepSeek от 2026-08-16
    # бесплатный разбор обходится в 6 копеек. Прежние 200 останавливали
    # сервис на 13 ₽ — меньше, чем стоит один отказ живому человеку.
    #
    # Пустое значение (DAILY_GENERATION_LIMIT=) не стартует: приводить его
    # к «потолка нет», как сделано для необязательных секретов, нельзя —
    # забытая переменная открывала бы траты на DeepSeek без предела.
    daily_generation_limit: int = 3000

    # Сколько бесплатных разборов даётся ОДНОМУ человеку; 0 — не ограничивать.
    # Ноль по умолчанию с 01.09.2026: бесплатный разбор — вход в воронку, и
    # счётчик отказывал ровно тому, кто дошёл до третьей карты, то есть
    # ближе всех к покупке. Траты держит daily_generation_limit выше.
    free_natal_limit: int = 0

    # --- Админка ----------------------------------------------------------
    # HTTP Basic Auth на /admin. В админке лежат даты и места рождения живых
    # людей, то есть персональные данные, — в открытый интернет её нельзя.
    admin_user: str = "admin"
    # Пароль без дефолта и nullable по той же логике, что и секрет выше:
    # пароль не задан — админка отвечает 503 и не пускает никого. Забытая
    # переменная должна закрывать дверь, а не распахивать.
    admin_password: SecretStr | None = None

    # --- VK Mini App ------------------------------------------------------
    # Идентификатор приложения из настроек VK. Нужен не для проверки подписи
    # (её достаточно ключа ниже), а чтобы сверить vk_app_id из параметров
    # запуска: расхождение означает, что ключ и приложение разъехались —
    # ошибка конфигурации, которую иначе видно только по «подпись неверна».
    vk_app_id: int | None = None

    # «Защищённый ключ» приложения (Разработка → Ключи доступа) — им VK
    # подписывает параметры запуска, им же мы проверяем подпись. Не задан —
    # VK-ветка выключена целиком, тот же дефолт-«закрыто», что у пароля
    # админки выше.
    vk_secure_key: SecretStr | None = None

    # Ключ, которым подписываются НАШИ сессионные JWT (?s=... в адресе).
    # Отдельный от vk_secure_key намеренно: у них разные роли и разные
    # владельцы — тем проверяем чужие утверждения о личности, этим
    # подписываем свои. Смена ключа разлогинивает всех разом.
    session_secret: SecretStr | None = None

    # Числовой идентификатор нашего сообщества VK. Не задан — блок подписки в
    # приложении не рисуется: `VKWebAppJoinGroup` без group_id не вызывается,
    # и кнопка молча ничего не делала бы. Через сообщество идут все продажи,
    # раз внутри Mini App их нет (docs/astro-context.md).
    vk_group_id: int | None = None

    # --- Сообщения от сообщества VK ---------------------------------------
    # Ключ доступа сообщества (Управление → Работа с API → Ключи доступа),
    # строка вида "vk1.a...". Им мы ДЕЙСТВУЕМ от имени группы: шлём
    # messages.send. Не путать с vk_secure_key выше — тем мы, наоборот,
    # проверяем чужие утверждения о личности, и подписывать им запросы к API
    # нельзя. Права ключа выданы точечно: без «Сообщения» отправка вернёт
    # ошибку 15, а не откажет на нашей стороне.
    vk_group_secure_key: SecretStr | None = None

    # Секретный ключ Callback API из настроек сервера в кабинете сообщества.
    # VK кладёт его в поле `secret` каждого события, мы сверяем и молча
    # отбрасываем чужое: адрес /vk/callback открыт всему интернету, подписи
    # у события нет, и этот ключ — единственное, что отличает VK от любого,
    # кто узнал адрес.
    vk_callback_secret: SecretStr | None = None

    # Строка, которую кабинет требует вернуть на событие type=confirmation
    # (у нас "e4164fb0"). Не секрет: она одноразовая по смыслу — VK шлёт
    # confirmation только при нажатии «Подтвердить». Хранится в настройках,
    # потому что своя строка у каждого сервера и у каждого сообщества.
    vk_callback_confirmation: str | None = None

    # --- ЮKassa -----------------------------------------------------------
    # Идентификатор магазина и секретный ключ из личного кабинета: вместе они
    # HTTP Basic Auth к api.yookassa.ru. shop_id строкой, хотя значение
    # числовое, — оно идёт в заголовок как есть, а int только отнимал бы
    # ведущие нули, если их однажды добавят.
    yookassa_shop_id: str | None = None
    yookassa_secret_key: SecretStr | None = None

    # Внешний адрес сайта («https://astrozvezdochet.ru»), от которого строятся
    # return_url для ЮKassa и ссылка /pay/<token>. Обе обязаны быть
    # абсолютными: из Mini App человек уходит платить во внешний браузер, а
    # туда путь без домена не годится. Дефолта нет намеренно — зашитый
    # адрес прода увёл бы платежи с локальной машины на боевой магазин.
    public_base_url: str | None = None

    # Откуда раздаётся Vue-фронт («https://astrozvezdochet.ru/app/»), куда
    # уводит человека страница возврата с оплаты. Пусто — возврат идёт
    # относительным путём /app/ на том же домене, что и сама страница.
    # Отдельная настройка нужна в разработке: Jinja-страницы отвечают на
    # 127.0.0.1:8000, а фронт живёт на dev-сервере Vite, и там же его /app/.
    app_base_url: str | None = None

    @field_validator(
        "admin_password",
        "vk_app_id",
        "vk_secure_key",
        "vk_group_id",
        "vk_group_secure_key",
        "vk_callback_secret",
        "vk_callback_confirmation",
        "session_secret",
        "yookassa_shop_id",
        "yookassa_secret_key",
        "public_base_url",
        "app_base_url",
        mode="before",
    )
    @classmethod
    def _blank_is_unset(cls, v: str | None) -> str | None:
        """Пустая строка = переменная не задана.

        Без этого `ADMIN_PASSWORD=` (пустое значение в .env, который compose
        отдаёт контейнеру через env_file) превращается в SecretStr(""), а
        проверка в web/deps.py смотрит `is None` — и админка пускает по
        пустому паролю вместо 503.

        Для vk_app_id причина другая: `VK_APP_ID=` роняет валидацию на
        int(""), то есть приложение не стартует вовсе.
        """
        return None if isinstance(v, str) and not v.strip() else v

    @property
    def is_prod(self) -> bool:
        return self.app_env == "prod"

    @property
    def vk_enabled(self) -> bool:
        """Настроена ли VK-ветка: проверить подпись И выпустить свою сессию.

        Полконфигурации хуже, чем никакой: с ключом VK, но без session_secret
        подпись сойдётся, а JWT выпустить не из чего — человек упрётся в
        ошибку уже после успешного входа.
        """
        return self.vk_secure_key is not None and self.session_secret is not None

    @property
    def vk_callback_enabled(self) -> bool:
        """Готов ли адрес /vk/callback принимать события сообщества.

        Нужны обе половины: строка подтверждения — чтобы кабинет вообще
        принял сервер, секрет — чтобы отличить события VK от чужих. Без
        секрета обработчик отвечает 503 и не подтверждается: подтверждённый
        адрес без проверки — открытая ручка, которой можно наотписывать
        людей от рассылки.
        """
        return (
            self.vk_callback_secret is not None
            and self.vk_callback_confirmation is not None
        )

    @property
    def vk_messaging_enabled(self) -> bool:
        """Можно ли слать сообщения от имени сообщества.

        Одного ключа мало: адресат в messages.send задаётся идентификатором
        пользователя VK, а группу, от чьего имени идёт письмо, мы проверяем
        по vk_group_id — событие Callback от чужого сообщества с нашим
        секретом иначе попало бы в ту же рассылку.
        """
        return self.vk_group_secure_key is not None and self.vk_group_id is not None

    @property
    def payments_enabled(self) -> bool:
        """Можно ли принимать деньги: нужны оба ключа И адрес возврата.

        Требование public_base_url здесь не формальность: без него платёж
        создастся, а вернуться человеку будет некуда — и это выяснится уже
        после того, как он заплатил.
        """
        return (
            self.yookassa_shop_id is not None
            and self.yookassa_secret_key is not None
            and self.public_base_url is not None
        )


@lru_cache
def get_settings() -> Settings:
    """Единственная точка доступа к настройкам.

    lru_cache даёт два эффекта: .env парсится один раз за процесс, и объект
    настроек везде один и тот же. В тестах кеш сбрасывается вызовом
    get_settings.cache_clear() — например, после monkeypatch переменных.
    """
    return Settings()
