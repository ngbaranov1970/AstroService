"""Настройка логирования — одна на весь процесс.

Правило разделения: **настраивает логи только точка входа** (app/main.py,
скрипты в scripts/), а обычные модули просто пишут:

    import logging
    logger = logging.getLogger(__name__)
    logger.info("что произошло")

Почему так: если бы `services/reports.py` настраивал логирование сам, то
бот, pytest и alembic, импортирующие его, получили бы наш формат и наш
уровень поверх своих. Библиотека сообщает о событиях, приложение решает,
куда и как их писать.

Имя файла `logging_setup`, а не `logging`, намеренно: модуль-тёзка
стандартной библиотеки внутри пакета — источник путаницы на ровном месте.
"""

import logging

from app.config import get_settings

# Формат строки лога. Пример вывода:
#   2026-07-29 21:04:11 INFO     app.llm.client: DeepSeek ответил за 41.2 с
#
# levelname выровнен по ширине 8 — чтобы сообщения начинались на одном
# уровне и лог читался колонками, а не рваным краем.
LOG_FORMAT = "%(asctime)s %(levelname)-8s %(name)s: %(message)s"
DATE_FORMAT = "%Y-%m-%d %H:%M:%S"

# Библиотеки, у которых INFO слишком болтлив. httpx на каждый запрос пишет
# «HTTP Request: POST https://api.deepseek.com/... "200 OK"» — то же самое
# событие, которое мы логируем сами, но подробнее и полезнее (с токенами и
# длительностью). Два сообщения об одном факте только засоряют лог.
NOISY_LIBRARIES = ("httpx", "httpcore")


def setup_logging(level: str | None = None) -> None:
    """Настроить вывод логов в консоль.

    level: порог («INFO», «DEBUG», …). None — взять из настроек (LOG_LEVEL).
    Параметр нужен скриптам, которые запускаются вне приложения и хотят
    свою подробность, не трогая .env.

    Вызов повторно безопасен: `basicConfig` ничего не делает, если у
    корневого логгера уже есть обработчик. Без этой особенности второй
    вызов (например, из `create_app()` в каждом тесте) добавил бы второй
    обработчик, и каждая строка печаталась бы дважды.
    """
    resolved = (level or get_settings().log_level).upper()

    logging.basicConfig(
        level=resolved,
        format=LOG_FORMAT,
        datefmt=DATE_FORMAT,
    )

    # Шумные библиотеки приглушаем, но только пока мы не в DEBUG: если
    # человек осознанно попросил максимум подробностей, он хочет видеть и
    # сырые HTTP-запросы тоже.
    if resolved != "DEBUG":
        for name in NOISY_LIBRARIES:
            logging.getLogger(name).setLevel(logging.WARNING)

    # SQLAlchemy здесь намеренно не трогаем: у неё свой выключатель —
    # настройка DB_ECHO, которая включает печать каждого SQL-запроса.
