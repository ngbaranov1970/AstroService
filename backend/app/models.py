"""Таблицы базы данных.

Все модели наследуются от Base из app/db.py — его metadata и есть «схема,
как её видит код»: с ней Alembic сравнивает реальную базу.

Общие соглашения по этому файлу:

* Первичный ключ — bigint. Идентификаторы наружу не светятся: доступ к
  чужому отчёту закрывается проверкой владения в сервисах, а не тем, что
  id трудно угадать. Где понадобится безопасная публичная ссылка (страница
  оплаты), заведём отдельный несекретный токен.

* Все моменты времени — TIMESTAMPTZ (DateTime(timezone=True)) и всегда UTC.
  Исключение — дата и время рождения: они по своей природе локальные,
  и хранятся вместе с именем зоны отдельным полем, иначе теряются
  исторические смещения, ради которых сделан astro_core/geo.py.

* Значения по умолчанию задаются на стороне сервера (server_default), а не
  только в Python. Питоновский default работает лишь тогда, когда строку
  вставляет ORM; server_default действует ещё и для миграций (он заполняет
  колонку в существующих строках) и для запросов руками из psql.
"""

from __future__ import annotations

import enum
import secrets
from datetime import datetime

from sqlalchemy import (
    BigInteger,
    Boolean,
    DateTime,
    Float,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    func,
)
from sqlalchemy import (
    Enum as SAEnum,
)
from sqlalchemy import (
    # Под именем sql_text, потому что в Report есть колонка text (текст
    # разбора) — она затенила бы функцию внутри тела класса.
    text as sql_text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db import Base


class Platform(str, enum.Enum):
    """Откуда пришёл пользователь.

    str-миксин нужен, чтобы значение можно было сравнивать со строкой и
    без потерь класть в JSON: Platform.TG == "tg" истинно.

    В базе это НЕ нативный PG-тип ENUM, а varchar с CHECK-ограничением
    (см. native_enum=False ниже). Причина практическая: добавление значения
    в нативный enum — это ALTER TYPE, который Alembic не умеет генерировать
    автоматически и который в старых версиях Postgres нельзя выполнить
    внутри транзакции миграции. CHECK правится обычным DDL.
    """

    TG = "tg"
    VK = "vk"
    WEB = "web"


class User(Base):
    """Пользователь — одна учётная запись на одной платформе.

    Регистрации в сервисе нет: пользователь появляется в момент первого
    касания (написал боту / открыл Mini App) и опознаётся парой
    «платформа + идентификатор в ней».

    Один и тот же человек в Telegram и во ВКонтакте — это ДВЕ строки.
    Связать их можно только по добровольному действию (ввёл один и тот же
    код в обоих каналах); до появления такой функции честнее считать их
    разными пользователями, чем угадывать по совпадению имени.

    Чего здесь намеренно нет:

    * счётчика бесплатных разборов. Продуктов несколько (натальная карта,
      Матрица Судьбы), бесплатная приманка — у каждого своя, и одно число
      их не различает. Лимит считается запросом к reports по (user_id, type),
      а пороги живут в конфиге: их правка не должна требовать миграции;

    * признака администратора. Администраторов полтора человека, их список
      в .env дешевле колонки, которую надо чем-то заполнять в проде.
    """

    __tablename__ = "users"

    __table_args__ = (
        # Ключевое ограничение таблицы: уникальна ПАРА, а не external_id сам
        # по себе. Идентификатор 12345 в Telegram и 12345 во ВКонтакте —
        # разные люди, и без платформы в ключе они схлопнулись бы в одного.
        UniqueConstraint("platform", "external_id"),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)

    # --- Идентичность ----------------------------------------------------
    platform: Mapped[Platform] = mapped_column(
        SAEnum(
            Platform,
            name="platform",
            native_enum=False,  # varchar + CHECK вместо нативного PG ENUM
            create_constraint=True,  # в SQLAlchemy 2 CHECK по умолчанию НЕ создаётся
            length=8,
            # Без values_callable SQLAlchemy пишет в базу ИМЕНА членов
            # перечисления ("TG"), а не значения ("tg"). В базу должно
            # попадать то же, что уходит в JSON и в логи.
            values_callable=lambda cls: [m.value for m in cls],
        ),
        nullable=False,
    )

    # Строка, хотя и в Telegram, и во ВКонтакте это числа: веб-пользователь
    # придёт с идентификатором другой природы, а менять тип колонки на живой
    # базе дороже, чем сразу писать varchar.
    external_id: Mapped[str] = mapped_column(String(64), nullable=False)

    # --- Профиль ---------------------------------------------------------
    # Имя, которое человек ввёл САМ. Идёт в текст разбора и в обращение.
    name: Mapped[str | None] = mapped_column(String(64))

    # @username в Telegram / имя аккаунта во ВКонтакте — только для поддержки
    # и админки. Отдельно от name намеренно: человек переименовался в мессен-
    # джере — это не повод менять имя в его натальной карте, и наоборот.
    platform_username: Mapped[str | None] = mapped_column(String(64))

    # Метка канала привлечения, проставляется ОДИН раз при первом касании:
    # payload из deep-link Telegram (t.me/bot?start=vk_post_12), vk_ref или
    # utm из launch params, utm с сайта. Значения придумываем сами
    # ("vk_ads_may", "bot_old_base"). NULL — «не знаем», это честнее, чем
    # записывать всех безымянных в "direct".
    #
    # Живёт в users, а не только в events, потому что канал — неизменное
    # свойство пользователя, и отчёт «какой канал приводит платящих» должен
    # быть джойном с orders, а не разбором JSONB в таблице-потоке.
    source: Mapped[str | None] = mapped_column(String(64))

    # Тестировщику полный разбор открыт без оплаты — нужно для обкатки
    # в закрытой группе до запуска платежей.
    is_tester: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=False, server_default=sql_text("false")
    )

    # --- Рассылки --------------------------------------------------------
    # Выбор ПОЛЬЗОВАТЕЛЯ: отписался от рассылки, но сервисом пользуется.
    subscribed: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=True, server_default=sql_text("true")
    )

    # Разрешил сообществу VK писать ему (VKWebAppAllowMessagesFromGroup).
    # Ведём сами, потому что через API список разрешивших не отдаётся вовсе
    # (docs/vk-moderation.md) — не записали в момент нажатия, потеряли
    # навсегда. NULL — не разрешал или отозвал разрешение.
    vk_messages_allowed_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True)
    )

    # Техническая невозможность доставки: человек заблокировал бота.
    # Узнать об этом заранее нельзя — Telegram сообщает только в ответ на
    # попытку отправки (403 Forbidden), ВКонтакте — ошибкой 901. Поэтому
    # факт запоминаем: иначе каждая рассылка снова стучится в мёртвые чаты,
    # съедая лимит ~30 сообщений в секунду, из-за которого живые получают
    # её позже.
    #
    # Время, а не bool: «когда заблокировали» — это метрика оттока, по ней
    # видно, после какой именно рассылки люди уходили. Вернулся и написал
    # сам — сбрасываем в NULL.
    bot_blocked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    # --- Активность ------------------------------------------------------
    # Последнее действие: сообщение боту, нажатие кнопки, открытие Mini App.
    # Нужен для трёх вещей: живой размер базы, реактивация («не заходил
    # 30 дней, но карта посчитана»), сегментация рассылок.
    #
    # Осознанная денормализация: то же самое даёт MAX(ts) по events, но
    # events — таблица-поток, и считать по ней максимум для каждого
    # пользователя на каждой рассылке со временем становится дорого.
    #
    # Обновляется НЕ на каждое действие, а не чаще раза в 6 часов (порог —
    # константа в сервисе пользователей). Все вопросы к этому полю живут на
    # масштабе дней и недель, там шесть часов неотличимы от нуля, зато
    # записей в базу на два порядка меньше.
    last_seen_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    # --- Удаление данных -------------------------------------------------
    # Означает не «пользователя нет», а «персональные данные стёрты по его
    # просьбе»: обнуляем name, каскадом сносим charts (там дата и место
    # рождения), строку users оставляем.
    #
    # Так сделано ровно из-за уникальной пары выше: если удалить строку,
    # вернувшийся человек придёт с тем же (platform, external_id) и упрётся
    # в конфликт — а регистрации у нас нет, отказать ему не в чем. Плюс
    # сохраняется история воронки. Вернулся — снимаем отметку.
    deleted_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    @property
    def is_deleted(self) -> bool:
        return self.deleted_at is not None

    @property
    def is_reachable(self) -> bool:
        """Можно ли отправить этому пользователю рассылку.

        Три условия разной природы: согласие (subscribed), техническая
        доставляемость (bot_blocked_at) и наличие самого пользователя
        (deleted_at). Собраны в одном месте, чтобы рассылка не забыла
        какое-нибудь из них.
        """
        return self.subscribed and self.bot_blocked_at is None and not self.is_deleted

    # Карты пользователя. lazy="raise_on_sql" — защита от главной ловушки
    # async-ORM: обычный relationship при первом обращении молча уходит в базу,
    # а в async это запрещено и падает MissingGreenlet где-нибудь в шаблоне
    # ответа. С этим режимом доступ разрешён, только если связь уже загружена
    # явно (selectinload), иначе — понятная ошибка сразу, а не под нагрузкой.
    #
    # passive_deletes=True: удаление строки users не тянет charts в память,
    # чтобы гасить их по одной — за каскад отвечает сама база (ondelete ниже).
    charts: Mapped[list[Chart]] = relationship(
        back_populates="user",
        cascade="all, delete-orphan",
        passive_deletes=True,
        lazy="raise_on_sql",
    )

    # Заказы, в отличие от карт, каскадом НЕ удаляются: нет ни cascade,
    # ни delete-orphan — за это отвечает ondelete="RESTRICT" в orders.
    # То есть пользователя со списанными деньгами база просто не даст
    # удалить, и это правильно (см. комментарий в Order.user_id).
    orders: Mapped[list[Order]] = relationship(back_populates="user", lazy="raise_on_sql")

    def __repr__(self) -> str:
        return f"<User id={self.id} {self.platform.value}:{self.external_id}>"


class Chart(Base):
    """Расчёт по конкретным данным рождения: входные данные + результат.

    Одна строка — это «дата, время и место» плюс всё, что из них посчитано.
    Разделение с reports принципиальное: расчёт детерминирован и вечен
    (Солнце в момент рождения не переедет), а текст разбора зависит от
    версии промпта и модели и живёт отдельно.

    Персональные данные (когда и где родился) сосредоточены именно здесь —
    поэтому «удалить мои данные» = снести charts, а строку users оставить.

    Про кеш между пользователями: карта принадлежит пользователю, и два
    человека с совпадающими данными рождения получат две строки и два
    похода в LLM. Это осознанно: совпадение с точностью до минуты и города
    практически не встречается, а глобально общая карта не давала бы
    удалить данные одного человека, не задев другого.
    """

    __tablename__ = "charts"

    __table_args__ = (
        # Тот же пользователь, те же данные рождения → та же строка.
        # Без этого «посчитай ещё раз» плодило бы дубли карт, а вместе
        # с ними и дубли отчётов — то есть лишние деньги за DeepSeek.
        UniqueConstraint("user_id", "input_hash"),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)

    # Публичный адрес карты: попадает в ссылку /r/<token>, по которой человек
    # открывает свой разбор. Приём и причина те же, что у Order.token ниже:
    # по последовательному id можно подставить соседнее число и прочитать
    # чужую дату и место рождения, а это персональные данные. 24 случайных
    # байта перебором не подобрать.
    #
    # Почему токен на карте, а не на отчёте: страница /r/ показывает карту
    # вместе с текстом, а текстов у одной карты со временем станет несколько
    # (бесплатный, полный, совместимость) — все они откроются по одному
    # адресу, и второй токен не понадобится.
    #
    # Ссылку можно переслать: кто её знает, тот видит разбор. Для тестового
    # стенда это осознанно (тестер показывает разбор подруге); когда появится
    # оплата, сюда добавится проверка владения.
    token: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        unique=True,
        default=lambda: secrets.token_urlsafe(24),
    )

    # Чья это карта — необязательное имя, как его ввёл пользователь.
    #
    # Расчёту не нужно, нужно людям: у одного тестера бывает карта своя и
    # мужа, и в списке их надо различать. В админке это первая колонка —
    # без неё сравниваются «карта №3» и «карта №7» вместо Маши и Пети.
    #
    # В промпт НЕ идёт: обращение по имени сбивает разбор в псевдоличную
    # переписку, а нам нужен текст про карту.
    person_name: Mapped[str | None] = mapped_column(String(64))

    user_id: Mapped[int] = mapped_column(
        BigInteger,
        # ondelete="CASCADE" — правило внутри Postgres: удалили пользователя,
        # база сама снесла его карты. Работает и когда строку удаляют мимо
        # ORM, руками из psql.
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
    )

    # --- Входные данные --------------------------------------------------
    # Локальное время рождения, БЕЗ таймзоны — то самое исключение из общего
    # правила «всё в UTC». Человек родился «11 мая в 17:20 по местным
    # часам»; в UTC это переводится только вместе с зоной и датой (декретное
    # время, отменённые переводы стрелок), чем и занимается astro_core/geo.
    # Хранить сразу UTC значило бы выбросить исходные показания часов
    # и потерять возможность пересчитать карту, если tzdata уточнится.
    birth_local: Mapped[datetime] = mapped_column(DateTime(timezone=False), nullable=False)

    # Время рождения знают далеко не все. Без него нельзя считать дома,
    # Асцендент и MC — а это половина натальной карты. Договорённость:
    # при False в birth_local лежит 12:00, дома в разбор не идут, промпт
    # обязан об этом знать. Флаг входит в input_hash: «12:00 точно» и
    # «время неизвестно» — разные карты, хотя расчёт совпадает.
    time_known: Mapped[bool] = mapped_column(
        Boolean, nullable=False, default=True, server_default=sql_text("true")
    )

    # Название места так, как его увидел пользователь при выборе города.
    # Для расчёта не используется (считаем по координатам) — нужно, чтобы
    # показать карту и дать человеку заметить, что он выбрал не тот Ростов.
    place_name: Mapped[str] = mapped_column(String(128), nullable=False)

    lat: Mapped[float] = mapped_column(Float, nullable=False)
    lon: Mapped[float] = mapped_column(Float, nullable=False)

    # Имя зоны IANA ("Europe/Moscow"), а не смещение: смещение зависит от
    # даты, имя — нет. Ровно то, что возвращает astro_core/geo.py.
    tz: Mapped[str] = mapped_column(String(64), nullable=False)

    # Отпечаток входных данных (sha256 в hex) для быстрого поиска дубля:
    # искать по паре (user_id, input_hash) дешевле и надёжнее, чем
    # сравнивать пять полей, где два — числа с плавающей точкой.
    # Что именно попадает в хеш, решает сервис (app/services/charts.py) —
    # он единственный источник правды, чтобы правило не разъехалось.
    input_hash: Mapped[str] = mapped_column(String(64), nullable=False)

    # --- Результат -------------------------------------------------------
    # JSONB, а не JSON: Postgres хранит его разобранным, умеет индексировать
    # и искать по ключам. Стоимость — потеря порядка ключей, которая нам
    # безразлична.
    #
    # Контейнер под ВСЕ виды расчёта по этим данным рождения:
    # {"natal": {...}}, позже добавятся "matrix" и "eastern". Входные данные
    # у них общие, поэтому это одна строка с несколькими ключами, а не три
    # таблицы.
    calc: Mapped[dict] = mapped_column(JSONB, nullable=False)

    # Версия расчётного ядра. Обновление kerykeion, pyswisseph или tzdata
    # может сдвинуть цифры на доли минуты; по этому полю видно, какие карты
    # посчитаны чем, и можно выборочно пересчитать старые, не трогая свежие.
    calc_version: Mapped[str] = mapped_column(String(32), nullable=False)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    user: Mapped[User] = relationship(back_populates="charts", lazy="raise_on_sql")
    reports: Mapped[list[Report]] = relationship(
        back_populates="chart",
        cascade="all, delete-orphan",
        passive_deletes=True,
        lazy="raise_on_sql",
    )

    # passive_deletes=True без cascade: удаляя карту, SQLAlchemy по умолчанию
    # сам загрузил бы все её заказы и занулил им chart_id по одному. Здесь
    # это лишняя работа — то же самое делает ondelete="SET NULL" в базе.
    orders: Mapped[list[Order]] = relationship(
        back_populates="chart",
        passive_deletes=True,
        lazy="raise_on_sql",
    )

    def __repr__(self) -> str:
        return f"<Chart id={self.id} user_id={self.user_id} {self.birth_local:%Y-%m-%d %H:%M} {self.place_name}>"


class ReportType(str, enum.Enum):
    """Вид разбора. Одновременно продукт (что покупают) и ключ кеша.

    FREE_NATAL — бесплатная приманка, короткий разбор натальной карты.
    FULL_NATAL — платный полный разбор посекционно.
    MATRIX, EASTERN — заготовки под Матрицу Судьбы и восточный гороскоп;
    заведены сразу, чтобы добавление продукта не требовало правки CHECK.
    """

    FREE_NATAL = "free_natal"
    FULL_NATAL = "full_natal"
    MATRIX = "matrix"
    EASTERN = "eastern"


class Report(Base):
    """Готовый текст разбора, написанный нейросетью.

    Одна строка — один текст. Таблица нужна для двух вещей.

    ПЕРВОЕ: не платить за один и тот же текст дважды.

    Маша получила бесплатный разбор утром, а вечером снова открыла бота.
    Если генерировать заново — мы опять платим DeepSeek, Маша опять ждёт
    полминуты, и текст приходит ДРУГОЙ (нейросеть каждый раз пишет
    по-новому), из-за чего выглядит, будто мы что-то напутали. Поэтому
    сначала ищем текст здесь и, если он есть, отдаём его.

    Ищем по «адресу» из трёх частей — это и есть UniqueConstraint ниже:

        chart_id       — чья карта
        type           — какой продукт (бесплатный разбор, полный, …)
        prompt_version — по какой инструкции написан ("free_natal_v1")

    UNIQUE говорит базе: с таким адресом может быть только одна строка.
    Дубли становятся невозможны физически, а не «по договорённости».

    Версия промпта в адресе — чтобы правки инструкции не ломали старое.
    Переписал промпт потеплее, сменил VERSION на v2 → адрес новый → в базе
    его нет → текст генерируется заново, уже по новой инструкции. При этом
    старый (v1) остаётся лежать рядом, и два варианта можно сравнить.

    ВТОРОЕ: копить материал.

    Кроме текста пишем «паспорт» генерации — модель, temperature, токены:

    * токены это счёт от DeepSeek: сложив их, узнаём, во сколько нам
      обходится один разбор, и сколько бесплатных мы можем себе позволить;
    * temperature и модель нужны, когда на текст пожалуются: без них
      непонятно, при каких настройках получилась ерунда;
    * сами тексты — будущая выборка для пост-фильтра. Чтобы он ловил
      запреты модерации VK, надо сперва увидеть на сотнях реальных
      разборов, где именно нейросеть срывается. Эти сотни накапливаются
      здесь сами, пока идёт обкатка в Telegram.

    Оговорка: раз адрес уникален, повторная генерация с той же версией
    промпта строку ПЕРЕЗАПИШЕТ — история попыток не хранится. Нужно
    сравнивать варианты — заводится новая VERSION, для того она и есть.
    """

    __tablename__ = "reports"

    __table_args__ = (
        UniqueConstraint("chart_id", "type", "prompt_version"),
        # Под проверку лимита бесплатных генераций: COUNT по (user_id, type)
        # выполняется перед каждым разбором. Внешний ключ сам по себе индекс
        # в Postgres НЕ создаёт — без этой строки был бы полный проход по
        # таблице. Имя задаёт соглашение из app/db.py, поэтому None.
        Index(None, "user_id", "type"),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)

    chart_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("charts.id", ondelete="CASCADE"), nullable=False
    )

    # Денормализация: владельца видно и через chart.user_id. Дублируем,
    # потому что главный частый вопрос — «сколько бесплатных разборов этого
    # типа человек уже получил», и он должен быть одним COUNT по
    # (user_id, type), а не джойном с charts на каждое сообщение боту.
    user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )

    type: Mapped[ReportType] = mapped_column(
        SAEnum(
            ReportType,
            name="report_type",
            native_enum=False,
            create_constraint=True,
            length=16,
            values_callable=lambda cls: [m.value for m in cls],
        ),
        nullable=False,
    )

    # Строка вида "free_natal_v1" — константа VERSION из модуля промпта.
    prompt_version: Mapped[str] = mapped_column(String(32), nullable=False)

    # Text, а не String(N): у полного разбора нет осмысленного предела длины,
    # а в Postgres varchar(N) и text хранятся одинаково — ограничение сверху
    # ничего не экономит, зато однажды обрежет текст.
    text: Mapped[str] = mapped_column(Text, nullable=False)

    # --- Чем сгенерировано (корпус) --------------------------------------
    model: Mapped[str] = mapped_column(String(64), nullable=False)
    temperature: Mapped[float] = mapped_column(Float, nullable=False)

    # Токены из LLMResult.usage: prompt_tokens и completion_tokens — это
    # прямая себестоимость разбора; cached — сколько из промпта DeepSeek
    # отдал из своего кеша (стабильный SYSTEM ради этого и сделан), по нему
    # видно, что кеширование действительно работает.
    tokens_prompt: Mapped[int] = mapped_column(Integer, nullable=False)
    tokens_completion: Mapped[int] = mapped_column(Integer, nullable=False)
    tokens_cached: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0, server_default=sql_text("0")
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    chart: Mapped[Chart] = relationship(back_populates="reports", lazy="raise_on_sql")

    def __repr__(self) -> str:
        return f"<Report id={self.id} chart_id={self.chart_id} {self.type.value}/{self.prompt_version}>"


class OrderStatus(str, enum.Enum):
    """Жизненный путь заказа. Переходы только вперёд, назад дороги нет.

        PENDING  — заказ создан, платёж в ЮKassa заведён, человек ушёл платить
        PAID     — деньги получены, отчёт разблокирован
        CANCELED — не заплатил: закрыл вкладку, банк отказал, истёк срок
        REFUNDED — деньги вернули по обращению

    Про REFUNDED: он заведён сразу, хотя возвратов мы пока не делаем. Строка
    в enum ничего не стоит, а её отсутствие в тот день, когда придёт первый
    возврат, означало бы миграцию под давлением.

    Чего здесь нет: WAITING_FOR_CAPTURE. У ЮKassa это состояние «деньги
    захолдированы, подтвердите списание» — оно нужно магазинам, которые
    сначала проверяют товар на складе. У нас товар — текст, он есть всегда,
    поэтому платёж создаётся с capture=true и подтверждается автоматически.
    """

    PENDING = "pending"
    PAID = "paid"
    CANCELED = "canceled"
    REFUNDED = "refunded"


class Order(Base):
    """Заказ: намерение купить конкретный отчёт и след того, чем оно кончилось.

    Зачем отдельная таблица, если можно было бы поставить в reports галочку
    «оплачено»: заказов на один и тот же отчёт может быть несколько (первый
    раз не прошла карта, второй прошёл), и каждый из них — денежный факт,
    который надо уметь показать при разборе спора. Галочка хранит только
    последний исход и не отвечает на вопрос «а сколько он вообще платил».

    Как устроен путь оплаты (напоминание, почему поля именно такие):

    1. Человек жмёт «купить» в Mini App или в боте. Оплата ВНУТРИ Mini App
       запрещена (цифровые товары там продаются только за «голоса» с большой
       комиссией, на iOS — вообще нельзя), поэтому мы создаём строку здесь
       и даём ссылку на сайт: /pay/<token>.
    2. Страница оплаты на сайте по token находит заказ и отправляет человека
       в ЮKassa (URL, который та вернула, лежит в confirmation_url).
    3. ЮKassa стучится в наш вебхук: «платёж <provider_payment_id> успешен».
       Мы находим заказ по этому id, ставим PAID и paid_at — отчёт открыт.

    Обратите внимание: разблокировку даёт именно вебхук, а не возвращение
    человека на страницу «спасибо». Возврат с сайта банка — это просто
    редирект, его легко не дождаться (закрыл вкладку) и так же легко
    подделать, открыв нужный адрес руками.

    Про «комплект за 890 ₽»: сейчас один заказ = один отчёт. Когда появится
    комплект из нескольких разборов, это будет не JSON-массив в этой строке,
    а отдельная таблица позиций заказа — денежные данные должны оставаться
    проверяемыми внешними ключами, а не свободным JSON.
    """

    __tablename__ = "orders"

    __table_args__ = (
        # «Мои покупки» в профиле и админский вопрос «кто из этих людей
        # платил» — оба запроса идут по паре (user_id, status).
        Index(None, "user_id", "status"),
        # Ждущий оплаты заказ на один товар может быть только один. Два
        # одновременных нажатия «купить» иначе заводят два заказа и два
        # платежа в ЮKassa: оплатят один, второй останется висеть.
        # Индекс ЧАСТИЧНЫЙ (только pending), потому что оплаченных и
        # отменённых заказов на ту же тройку бывает сколько угодно — это
        # история покупок, и запрещать её нельзя.
        Index(
            "uq_orders_one_pending",
            "user_id",
            "chart_id",
            "report_type",
            unique=True,
            postgresql_where=sql_text("status = 'pending'"),
        ),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)

    # Публичный адрес заказа: он попадает в ссылку на страницу оплаты, то
    # есть его увидит и человек, и его почта, и, возможно, чат с друзьями.
    # Поэтому не id: последовательные номера позволяют подставить соседний
    # и увидеть чужой заказ. 24 случайных байта в urlsafe-виде подобрать
    # перебором нельзя.
    #
    # Значение генерирует Python, а не база: server_default тут был бы
    # gen_random_uuid(), а uuid и длиннее в URL, и завязывает нас на
    # конкретную СУБД ради значения, которое всё равно создаётся в момент
    # создания заказа сервисом.
    token: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        unique=True,
        default=lambda: secrets.token_urlsafe(24),
    )

    # RESTRICT, а не CASCADE: заказ переживает пользователя. «Удалить мои
    # данные» у нас означает обнулить профиль и снести charts (см. User),
    # а не стереть историю платежей — её надо хранить и для бухгалтерии,
    # и на случай спора о возврате. RESTRICT заодно делает случайный
    # DELETE FROM users в psql громкой ошибкой вместо тихой потери денег.
    user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="RESTRICT"), nullable=False
    )

    # Карта, за разбор которой платят. Nullable и SET NULL, потому что
    # требования тут прямо конфликтуют: карту человек вправе удалить (это
    # его персональные данные), а заказ удалять нельзя (это деньги).
    # Компромисс — заказ остаётся, но уже без ссылки на данные рождения.
    chart_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("charts.id", ondelete="SET NULL")
    )

    # Что именно покупают. Тот же перечень, что у reports.type, — и это не
    # совпадение: после оплаты сервис ищет (или генерирует) отчёт ровно
    # с этим типом для этой карты.
    report_type: Mapped[ReportType] = mapped_column(
        SAEnum(
            ReportType,
            name="report_type",
            native_enum=False,
            create_constraint=True,
            length=16,
            values_callable=lambda cls: [m.value for m in cls],
        ),
        nullable=False,
    )

    # Сумма В КОПЕЙКАХ целым числом: 490 ₽ → 49000. Float для денег
    # использовать нельзя — 0.1 + 0.2 в двоичной дроби даёт не 0.3, и на
    # сверке с выпиской это вылезает копеечными расхождениями, которые
    # невозможно объяснить. Целые копейки складываются точно.
    #
    # Цена копируется в заказ, а не берётся из конфига в момент показа:
    # прайс поменяется, а этот человек заплатил столько, сколько заплатил.
    amount: Mapped[int] = mapped_column(Integer, nullable=False)

    # Колонки currency нет намеренно: ЮKassa для самозанятого принимает
    # только рубли, а колонка, у которой всегда одно значение, — это
    # обещание мультивалютности, которого мы не выполняем.

    status: Mapped[OrderStatus] = mapped_column(
        SAEnum(
            OrderStatus,
            name="order_status",
            native_enum=False,
            create_constraint=True,
            length=16,
            values_callable=lambda cls: [m.value for m in cls],
        ),
        nullable=False,
        default=OrderStatus.PENDING,
        server_default=sql_text("'pending'"),
    )

    # --- Сторона ЮKassa ---------------------------------------------------
    # Идентификатор платежа у них (uuid-строка). UNIQUE здесь — это защита
    # от двойного зачисления: ЮKassa повторяет вебхук, пока не получит 200,
    # и один и тот же платёж легко прилетает дважды. Найдя заказ по этому
    # полю и увидев, что он уже PAID, мы просто отвечаем 200 и ничего не
    # делаем. NULL до того, как платёж создан.
    provider_payment_id: Mapped[str | None] = mapped_column(String(64), unique=True)

    # Ссылка на форму оплаты, которую вернула ЮKassa. Храним, чтобы человек,
    # закрывший вкладку и вернувшийся по той же ссылке /pay/<token>, попал
    # в СВОЙ уже созданный платёж, а не породил второй на ту же сумму.
    confirmation_url: Mapped[str | None] = mapped_column(String(512))

    # Сырое тело последнего уведомления от ЮKassa как есть. Разбирать его
    # в колонки смысла нет — это их формат, он меняется без нашего участия;
    # а при споре «мы не получали от вас платёж» это единственное, что можно
    # положить на стол.
    provider_data: Mapped[dict | None] = mapped_column(JSONB)

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    # Момент зачисления денег (по нашим часам, в UTC). Отдельно от status,
    # потому что вопрос «когда пришли деньги» — это выручка по дням, и
    # ответ на него не должен требовать разбора логов вебхука.
    paid_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    @property
    def is_paid(self) -> bool:
        """Открывать ли отчёт. Возврат снова закрывает доступ."""
        return self.status is OrderStatus.PAID

    @property
    def amount_rub(self) -> str:
        """Сумма для показа человеку: 49000 → "490.00" (и для ЮKassa тоже)."""
        return f"{self.amount / 100:.2f}"

    user: Mapped[User] = relationship(back_populates="orders", lazy="raise_on_sql")
    chart: Mapped[Chart | None] = relationship(back_populates="orders", lazy="raise_on_sql")

    def __repr__(self) -> str:
        return (
            f"<Order id={self.id} user_id={self.user_id} "
            f"{self.report_type.value} {self.amount_rub}₽ {self.status.value}>"
        )


class Event(Base):
    """Своя аналитика: что человек сделал и когда.

    Одна строка — один факт: «открыл бота», «ввёл дату», «увидел пейволл»,
    «нажал купить», «оплатил». Собранные вместе, они отвечают на главный
    вопрос запуска — ГДЕ ЛЮДИ ОТВАЛИВАЮТСЯ. Из ста открывших бота дату ввели
    сорок, разбор дочитали двадцать, до пейволла дошли восемь, заплатил один.
    Без этой таблицы известно только «выручка маленькая», и непонятно, что
    чинить: онбординг, текст разбора или цену.

    Почему не Яндекс.Метрика: она живёт в браузере и видит клики по страницам.
    Половина нашей воронки — переписка с ботом в Telegram, где никакого
    оплаты. Метрика не соберёт это в один путь одного человека, а join
    по user_id — соберёт.

    ЭТО ТАБЛИЦА-ПОТОК. У неё другая природа, чем у остальных: строки только
    добавляются, никогда не меняются, и их на порядки больше. Отсюда всё
    устройство ниже — никаких внешних связей в ORM, дешёвая запись, индексы
    под чтение по времени.

    Правило, которое легко нарушить: В props НЕ КЛАДЁМ ПЕРСОНАЛЬНЫЕ ДАННЫЕ —
    ни имени, ни даты рождения, ни города. Персональные данные живут в charts
    именно затем, чтобы их можно было удалить одним DELETE по просьбе
    человека; расползшись по миллиону строк аналитики, они станут
    неудаляемыми.
    """

    __tablename__ = "events"

    __table_args__ = (
        # Воронка: «сколько раз случилось событие X за последнюю неделю».
        # Порядок колонок не случаен — сначала то, по чему сравнивают на
        # равенство (name), потом то, по чему берут диапазон (ts). Индекс
        # читается слева направо, и при обратном порядке база не смогла бы
        # сузить поиск по имени события.
        Index(None, "name", "ts"),
        # Путь одного человека: «что он делал перед тем, как отвалиться».
        # Нужен и для поддержки («у меня не открылся отчёт» — смотрим,
        # что у него вообще происходило).
        Index(None, "user_id", "ts"),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)

    # Имя события — обычная строка, а не enum. Тут сознательный размен:
    # enum ловил бы опечатки, но каждое новое событие требовало бы миграции,
    # и в итоге события просто перестали бы писать («ради одной строчки
    # аналитики миграцию катать не буду»). Аналитика ценна, только когда её
    # дёшево добавлять.
    #
    # От разъезжания имён ("paywall_shown" против "paywall_show") защищаемся
    # в коде: единственный источник правды — константы в модуле аналитики,
    # руками строки в вызовах не пишем.
    name: Mapped[str] = mapped_column(String(64), nullable=False)

    # Кто. NULL — «человек ещё не опознан»: заход на лендинг или на страницу
    # оплаты, где пользователя нет до первого касания с ботом.
    #
    # SET NULL, а не CASCADE: человек попросил удалить свои данные — событие
    # остаётся, но становится анонимным. Иначе вчерашняя воронка задним
    # числом изменилась бы, а отчёт, который меняет прошлое, бесполезен.
    user_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="SET NULL")
    )

    # Подробности события: {"type": "free_natal", "source": "vk_ads_may"},
    # {"reason": "no_time"}. Свободный JSON тут уместен ровно потому, что
    # у каждого события свой набор деталей, и заводить под них колонки —
    # значит получить таблицу из полусотни вечно пустых полей.
    #
    # server_default '{}' вместо NULL: код всегда получает словарь, и
    # props["x"] не падает на проверке «а вдруг там None».
    props: Mapped[dict] = mapped_column(
        JSONB, nullable=False, default=dict, server_default=sql_text("'{}'::jsonb")
    )

    # Момент события в UTC. Назван ts, а не created_at, намеренно: в других
    # таблицах created_at — это «когда завели строку», побочная метка. Здесь
    # время и есть содержание факта, по нему строятся все отчёты.
    ts: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    # Связи с User здесь нет намеренно, хотя внешний ключ есть.
    # user.events выглядел бы удобно, но означал бы «загрузить в память все
    # события пользователя» — а их тысячи, и нужны они всегда в виде
    # агрегатов (COUNT, воронка за период), а не списка объектов.
    # Внешний ключ при этом на месте: он гарантирует, что user_id
    # ссылается на существующего человека, и обеспечивает SET NULL.

    def __repr__(self) -> str:
        return f"<Event id={self.id} {self.name} user_id={self.user_id} {self.ts:%Y-%m-%d %H:%M}>"
