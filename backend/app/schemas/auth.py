"""Схемы входа через VK: параметры запуска на вход, сессия на выход.

Граница с app/models/: там строки базы со всем внутренним, здесь — только
то, что можно показать клиенту. Внутренний `users.id` и `external_id`
(он же `vk_user_id`) наружу не уходят: первый нужен лишь нам, второй — чужой
идентификатор человека в VK, и место ему в базе, а не в ответах API.
"""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict


class VkLaunchIn(BaseModel):
    """Параметры запуска Mini App — ровно то, что VK положил в адрес.

    Плоским словарём, а не именованными полями: подпись считается по ВСЕМ
    параметрам с префиксом `vk_`, и набор их задаёт VK, а не мы. Перечисли
    мы их поимённо — новый параметр в их платформе молча ломал бы подпись.
    """

    params: dict[str, str]
    # Плитка меню сообщества, с которой открыли приложение (natal, pair,
    # horoscope). Значение не ограничено схемой намеренно: кривая метка
    # аналитики не должна давать 422 на вход. Белый список — в events.ENTRY_GOALS.
    # Подписью VK не защищена: это хеш адреса, его может подменить кто угодно
    entry: str | None = None


class UserOut(BaseModel):
    """Пользователь глазами фронта: подпись в интерфейсе и признак тестера."""

    model_config = ConfigDict(from_attributes=True)

    name: str | None
    # Фронту нужен, чтобы показать тестеру полный разбор без цены. На доступ
    # он не влияет — плату снимает бэк, здесь только вид кнопки.
    is_tester: bool


class SessionOut(BaseModel):
    """Ответ на успешный вход: токен для заголовка Authorization.

    `expires_in` в секундах, как в OAuth: фронту нужно знать, когда идти за
    новым токеном, а разбирать наш JWT ради поля `exp` он не должен — это
    сделало бы формат токена частью контракта.
    """

    token: str
    expires_in: int
    user: UserOut
