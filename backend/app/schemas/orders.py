"""Схемы заказов для JSON-API: создание платежа и состояние заказа.

Этим API пользуется только веб-ветка фронта: внутри VK продавать нельзя, и
маршруты в app/api/routes/orders.py отвечают VK-пользователю 403.

Форма ответов продиктована тем, что платит человек не у нас: на создание
возвращается адрес чужой формы, а состояние заказа спрашивается уже после
возврата с неё.
"""

from __future__ import annotations

from datetime import datetime

from pydantic import BaseModel

from app.models import OrderStatus, ReportType


class OrderCreated(BaseModel):
    """Ответ на создание заказа: куда вести человека платить.

    Токен заказа фронт запоминает — по нему после возврата с формы
    спрашивается состояние (GET /orders/{token}).
    """

    token: str
    # Адрес формы ЮKassa. Открывать его нужно переходом в этой же вкладке:
    # оплата не должна выглядеть всплывшим окном неизвестного сайта.
    confirmation_url: str


class OrderOut(BaseModel):
    """Состояние заказа для экрана «оплачено».

    `number` и `price_rub` показываются человеку: назвать номер — всё, что
    он может сделать при обращении в поддержку, контактов мы не спрашиваем.
    """

    token: str
    # Номер заказа (id строки). Отдельным полем, потому что для человека это
    # не идентификатор ресурса, а то, что он назовёт в письме.
    number: int
    status: OrderStatus
    # Оплачен ли — то же, что status == paid, но фронту не нужно знать
    # список статусов, чтобы нарисовать главную развилку экрана.
    paid: bool
    report_type: ReportType
    title: str
    # Целые рубли, а не строка «290.00» из Order.amount_rub: та сделана для
    # формы ЮKassa, на экране копейки не показываем.
    price_rub: int

    created_at: datetime
    paid_at: datetime | None = None
