"""Схемы слоя разборов: состояние текста по карте и запрос на генерацию.

Форма ответа продиктована тем, что текста может ещё не быть: LLM отвечает
30–60 секунд, поэтому фронт получает не «отчёт или 404», а состояние —
готов, готовится, заперт пейволлом, доступен к запросу, отказано.

Тот же набор состояний собирает для шаблона стенд (`_report_block` в
app/web/routes/stand.py), но там это четыре независимых поля. Здесь одно
перечисление: четыре флага допускают «готов и одновременно заперт», а фронт
на такой ответ нарисует и текст, и кнопку покупки.
"""

from __future__ import annotations

import enum
from datetime import datetime

from pydantic import BaseModel, ConfigDict

from app.models import ReportType


class ReportStatus(str, enum.Enum):
    """Что происходит с одним разбором прямо сейчас — ровно один из пяти.

    Колонки в базе за этим нет: у `reports` нет статуса, строка появляется
    сразу с готовым текстом. Состояние собирается на лету из наличия строки,
    реестра генераций (app/generation.py) и права на покупку.
    """

    # Текст есть — заполнено `sections`, остальные поля не важны.
    READY = "ready"
    # Генерация идёт: опрашивать этот же маршрут раз в несколько секунд.
    RUNNING = "running"
    # Разбор закрыт: текста не будет, пока его не купят. Цена приходит только
    # вне VK — см. ReportOut.
    LOCKED = "locked"
    # Текста нет, ничего не идёт, платить не надо — можно просить генерацию.
    AVAILABLE = "available"
    # Последняя попытка не удалась: заполнены `error_code` и `error`.
    FAILED = "failed"


class SectionOut(BaseModel):
    """Кусок готового разбора: заголовок и текст.

    Заголовка может не быть — бесплатный разбор приходит от модели сплошным
    текстом и отдаётся одной секцией без подписи.
    """

    model_config = ConfigDict(from_attributes=True)

    title: str | None
    body: str


class ReportOut(BaseModel):
    """Один разбор карты во всех его возможных состояниях.

    Что заполнено, определяет `status`; поля, которые к текущему состоянию не
    относятся, приходят `null`.
    """

    type: ReportType
    # Продуктовое название («Полный разбор») — из services/orders.py, чтобы
    # фронт и страница оплаты называли товар одинаково.
    title: str
    status: ReportStatus

    sections: list[SectionOut] | None = None
    # Из чего разбор будет состоять — анонс до генерации. Пусто, если промпт
    # состава не объявляет.
    section_titles: list[str] = []

    # Цена заполнена только вне VK: внутри Mini App продавать нельзя ни на
    # одной платформе (docs/astro-context.md), и `locked` без цены фронт
    # показывает как «этот разбор закрыт».
    price_rub: int | None = None
    # Всегда `null`: веб-фронт ведёт на свой экран оплаты и строит его адрес
    # сам. Поле оставлено для стенда, который отдаёт ссылку в шаблон.
    pay_url: str | None = None

    # Машинный код отказа: limit_exhausted, needs_purchase, budget_exceeded,
    # not_supported, failed. Список ведёт app/generation.py, там же тексты.
    error_code: str | None = None
    # Фраза для человека. Фронту решать по коду, а не по ней: формулировки
    # меняются вместе с продуктом.
    error: str | None = None

    created_at: datetime | None = None


class ReportRequest(BaseModel):
    """Просьба сгенерировать разбор: какой именно.

    Значение вне ReportType pydantic отсеет сам (422), до похода в базу.
    """

    type: ReportType
