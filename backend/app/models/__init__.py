"""Таблицы базы данных: один файл на таблицу, снаружи — один пакет.

Все модели наследуются от Base из app/db.py — его metadata и есть «схема,
как её видит код»: с ней Alembic сравнивает реальную базу. Поэтому здесь
импортируются ВСЕ модули пакета: незамеченная таблица выглядит для
autogenerate как удалённая, а незагруженный класс ломает связи соседей.

Импортировать наружу всегда отсюда — `from app.models import Chart, User`,
а не из app.models.chart. Так пакет остаётся волен перекладывать классы
между файлами, не трогая пятнадцать вызывающих модулей.

Устройство файлов: user, chart, report, order — продуктовое ядро, они
ссылаются друг на друга; event — аналитика, post — контент сообщества, эти
двое не связаны ни с кем. Связи внутри ядра объявлены типами
(`Mapped[list[Chart]]`), поэтому файлы импортируют друг друга под
`if TYPE_CHECKING` — в рантайме имена классов SQLAlchemy находит в своём
реестре, а настоящий импорт дал бы цикл.

Общие соглашения по всем таблицам:

* Первичный ключ — bigint. Идентификаторы наружу не светятся: доступ к
  чужому отчёту закрывается проверкой владения в сервисах, а не тем, что
  id трудно угадать. Где понадобится безопасная публичная ссылка (страница
  оплаты), заведён отдельный несекретный токен.

* Все моменты времени — TIMESTAMPTZ (DateTime(timezone=True)) и всегда UTC.
  Исключений два, оба намеренные: дата и время рождения (Chart.birth_local)
  локальны по своей природе и хранятся вместе с именем зоны отдельным полем,
  иначе теряются исторические смещения, ради которых сделан astro_core/geo.py;
  и день, которому адресован пост (Post.target_date) — это сутки по Москве,
  а не момент.

* Значения по умолчанию задаются на стороне сервера (server_default), а не
  только в Python. Питоновский default работает лишь тогда, когда строку
  вставляет ORM; server_default действует ещё и для миграций (он заполняет
  колонку в существующих строках) и для запросов руками из psql.

* Функция sqlalchemy.text импортируется как sql_text: в Report и Post есть
  колонка text, и внутри тела класса она затенила бы функцию.
"""

