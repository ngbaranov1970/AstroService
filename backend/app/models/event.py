"""Аналитика воронки: что человек сделал и когда.

Таблица-поток, устроенная иначе, чем остальные: связей в ORM нет, запись
дешёвая, индексы под чтение по времени. Общие соглашения пакета — в
app/models/__init__.py.
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import (
    BigInteger,
    DateTime,
    ForeignKey,
    Index,
    String,
    func,
)
from sqlalchemy import (
    text as sql_text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.db import Base


class Event(Base):
    """Своя аналитика: что человек сделал и когда.

    Одна строка — один факт: «открыл бота», «ввёл дату», «увидел пейволл»,
    «нажал купить», «оплатил». Собранные вместе, они отвечают на главный
    вопрос запуска — ГДЕ ЛЮДИ ОТВАЛИВАЮТСЯ. Из ста открывших бота дату ввели
    сорок, разбор дочитали двадцать, до пейволла дошли восемь, заплатил один.
    Без этой таблицы известно только «выручка маленькая», и непонятно, что
    чинить: онбординг, текст разбора или цену.

    Почему не Яндекс.Метрика: она живёт в браузере и видит клики по страницам.
    Половина нашей воронки — переписка с ботом в Telegram, где никакого
    оплаты. Метрика не соберёт это в один путь одного человека, а join
    по user_id — соберёт.

    ЭТО ТАБЛИЦА-ПОТОК. У неё другая природа, чем у остальных: строки только
    добавляются, никогда не меняются, и их на порядки больше. Отсюда всё
    устройство ниже — никаких внешних связей в ORM, дешёвая запись, индексы
    под чтение по времени.

    Правило, которое легко нарушить: В props НЕ КЛАДЁМ ПЕРСОНАЛЬНЫЕ ДАННЫЕ —
    ни имени, ни даты рождения, ни города. Персональные данные живут в charts
    именно затем, чтобы их можно было удалить одним DELETE по просьбе
    человека; расползшись по миллиону строк аналитики, они станут
    неудаляемыми.
    """

    __tablename__ = "events"

    __table_args__ = (
        # Воронка: «сколько раз случилось событие X за последнюю неделю».
        # Порядок колонок не случаен — сначала то, по чему сравнивают на
        # равенство (name), потом то, по чему берут диапазон (ts). Индекс
        # читается слева направо, и при обратном порядке база не смогла бы
        # сузить поиск по имени события.
        Index(None, "name", "ts"),
        # Путь одного человека: «что он делал перед тем, как отвалиться».
        # Нужен и для поддержки («у меня не открылся отчёт» — смотрим,
        # что у него вообще происходило).
        Index(None, "user_id", "ts"),
    )

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)

    # Имя события — обычная строка, а не enum. Тут сознательный размен:
    # enum ловил бы опечатки, но каждое новое событие требовало бы миграции,
    # и в итоге события просто перестали бы писать («ради одной строчки
    # аналитики миграцию катать не буду»). Аналитика ценна, только когда её
    # дёшево добавлять.
    #
    # От разъезжания имён ("paywall_shown" против "paywall_show") защищаемся
    # в коде: единственный источник правды — константы в модуле аналитики,
    # руками строки в вызовах не пишем.
    name: Mapped[str] = mapped_column(String(64), nullable=False)

    # Кто. NULL — «человек ещё не опознан»: заход на лендинг или на страницу
    # оплаты, где пользователя нет до первого касания с ботом.
    #
    # SET NULL, а не CASCADE: человек попросил удалить свои данные — событие
    # остаётся, но становится анонимным. Иначе вчерашняя воронка задним
    # числом изменилась бы, а отчёт, который меняет прошлое, бесполезен.
    user_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="SET NULL")
    )

    # Подробности события: {"type": "free_natal", "source": "vk_ads_may"},
    # {"reason": "no_time"}. Свободный JSON тут уместен ровно потому, что
    # у каждого события свой набор деталей, и заводить под них колонки —
    # значит получить таблицу из полусотни вечно пустых полей.
    #
    # server_default '{}' вместо NULL: код всегда получает словарь, и
    # props["x"] не падает на проверке «а вдруг там None».
    props: Mapped[dict] = mapped_column(
        JSONB, nullable=False, default=dict, server_default=sql_text("'{}'::jsonb")
    )

    # Момент события в UTC. Назван ts, а не created_at, намеренно: в других
    # таблицах created_at — это «когда завели строку», побочная метка. Здесь
    # время и есть содержание факта, по нему строятся все отчёты.
    ts: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=func.now()
    )

    # Связи с User здесь нет намеренно, хотя внешний ключ есть.
    # user.events выглядел бы удобно, но означал бы «загрузить в память все
    # события пользователя» — а их тысячи, и нужны они всегда в виде
    # агрегатов (COUNT, воронка за период), а не списка объектов.
    # Внешний ключ при этом на месте: он гарантирует, что user_id
    # ссылается на существующего человека, и обеспечивает SET NULL.

    def __repr__(self) -> str:
        return f"<Event id={self.id} {self.name} user_id={self.user_id} {self.ts:%Y-%m-%d %H:%M}>"
