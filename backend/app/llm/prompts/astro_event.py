def _moment_ru(moment: datetime) -> str:
    """«28 августа 2026, 07:18 МСК» — момент уже в московской зоне."""
    return (
        f"{moment.day} {_MONTHS_RU[moment.month - 1]} {moment.year}, "
        f"{moment:%H:%M} МСК"
    )


def build_user(event: dict, until: date | None = None) -> str:
    """Собирает user-сообщение из одного события transits.

    until — дата обратной станции для ретроградности: «до 15 октября» читатель
    ищет в первую очередь. Ищет её вызывающий, промпт только печатает.
    """
    lines = [
        f"Событие: {event['title_ru']}",
        f"Момент: {_moment_ru(event['moment'])}",
    ]

    hint = _KIND_HINTS.get(event["kind"])
    if hint:
        lines.append(f"Что это такое: {hint}")

    if event.get("sign_ru"):
        lines.append(f"Знак: {event['sign_ru']}, {event['deg_in_sign']:.0f}°")

    if event["kind"] == "aspect":
        lines.append(
            f"Участники: {event['body_ru']} и {event['body2_ru']}, "
            f"аспект — {event['aspect_ru']}"
        )
    elif event.get("body_ru"):
        lines.append(f"Тело: {event['body_ru']}")

    if event.get("eclipse_kind"):
        lines.append(f"Вид затмения: {event['eclipse_kind']}")

    if until is not None:
        lines.append(
            f"Период длится до {until.day} {_MONTHS_RU[until.month - 1]} {until.year}"
        )

    lines.append("")
    lines.append("Напиши пост об этом событии по правилам из системного сообщения.")
    return "\n".join(lines)


def _strip_fence(text: str) -> str:
    """Снимает ```-забор, если модель всё же обернула JSON в блок кода."""
    t = text.strip()
    if not t.startswith("```"):
        return t
    if "\n" in t:
        t = t.split("\n", 1)[1]
    return t.rstrip().removesuffix("```").strip()


def parse(text: str) -> dict[str, str] | None:
    """Ответ модели → {"title": ..., "body": ...} или None, если разобрать нельзя.

    None — сигнал вызывающему не публиковать пост. Пустое поле считается
    браком наравне с непарсящимся ответом: пост без заголовка в очереди
    неотличим от сбоя генерации.
    """
    try:
        data = json.loads(_strip_fence(text))
        title, body = str(data["title"]).strip(), str(data["body"]).strip()
    except (ValueError, TypeError, KeyError):
        return None

    if not title or not body:
        return None
    return {"title": title, "body": body}


def render(text: str, seed: int | None = None) -> str:
    """JSON-ответ модели → готовый к вставке пост: заголовок, пустая строка, тело.

    seed выбирает приписку из promo.LINES — см. promo.line().

    Строки не переносятся и служебных пометок нет: этот текст копируют из
    /admin/content в отложку VK как есть, и любой перенос уехал бы в пост.
    Брак разбора отдаём как есть — за текст заплачено.
    """
    post = parse(text)
    if post is None:
        return text
    # Абзацы разделяем пустой строкой: модель шлёт их одиночным переводом
    # строки, а в ленте VK такой текст слипается в полотно.
    body = "\n\n".join(par.strip() for par in post["body"].split("\n") if par.strip())
    # Приписка последней строкой, а не после заголовка: пост о событии — один
    # сюжет на 200 слов, и врезка в середине оборвала бы его на полумысли.
    return f"{post['title']}\n\n{body}\n\n{promo.line(seed)}"
