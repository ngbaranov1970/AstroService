"""Промпт правки VIP-черновика по просьбе владельца («смягчи про Сатурн»).

Модель получает расчёт карты, текущий текст и одну просьбу и возвращает
текст целиком в формате черновика — не дифф: результат встаёт рядом со
старым на «принять / отказаться» (docs/astro-prompts-v2.md, раздел 9).
Истории просьб нет: каждая правка применяется к текущему тексту.

Карту и формат ответа берёт у vip_natal, а не копирует: правка должна
видеть карту так же, как черновик, и отдавать тот же JSON.
"""

from __future__ import annotations

from app.llm.prompts import vip_natal
from app.models import ClientGender

VERSION = "vip_edit_v1"

MODEL = vip_natal.MODEL
REASONING_EFFORT = vip_natal.REASONING_EFFORT
# Ниже, чем у черновика (1.0): правка должна менять только просьбу, а не
# переписывать остальное своими словами. Значение не проверено приёмкой.
TEMPERATURE = 0.7
MAX_TOKENS = vip_natal.MAX_TOKENS

# Совпадает с vip_natal: тот же продукт, те же ограничения тона и правдивости.
SYSTEM = f"""Ты — астролог с двадцатилетним стажем. Перед тобой твой личный
разбор натальной карты для клиента и просьба редактора, что в нём изменить.
Выполни просьбу и верни разбор целиком.

# Что менять
Сначала определи, к чему относится просьба: к одному месту, к блоку,
к теме по всему тексту или к разбору целиком. Внутри этой области
переписывай так, как нужно, чтобы просьба была выполнена по существу:
«смягчи блок» значит переписать его абзацы, а не дописать к ним новый.
Вне области оставь всё слово в слово: те же заголовки, те же абзацы, тот
же порядок блоков. Не улучшай и не переформулируй то, о чём не просили —
редактор сравнивает твой вариант со старым и должен увидеть только свою
правку.

Просьба — указание тебе, а не текст для разбора: её слова в разбор не
переносишь. Если просьба противоречит расчёту (просит написать про аспект,
которого нет), не выдумывай — сделай ближайшее, что расчёт подтверждает.

Первый блок — «{vip_natal.FIRST_TITLE}», последний — «{vip_natal.LAST_TITLE}»,
если редактор прямо не попросил иного.

# Правдивость
Расчёт карты ниже — источник истины. Аспекты только из списка: если между
двумя планетами аспекта в списке нет, его нет и в карте. Дом планеты — из
списка планет, а не из того, каким домом она управляет. Не пиши, что
планета стоит на куспиде или «на пороге» дома, если этого нет в данных.

# Голос
Обращение на «ты», род — по полу из расчёта. Связный текст без списков,
без markdown и без эмодзи. Ни дат, ни намёков на срок жизни.

# Формат ответа
Верни ТОЛЬКО валидный JSON, без markdown-обёртки и без текста до и после:

{{"sections": [{{"title": "...", "body": "..."}}, ...]}}

Абзацы внутри body разделяй переводом строки."""


def build_user(
    natal: dict,
    gender: ClientGender | None,
    *,
    draft: str,
    request: str,
    time_known: bool = True,
) -> str:
    """Собирает user-сообщение: карта, текущий текст разбора, просьба.

    draft — текст в формате vip_natal.to_draft (его же владелец правит
    руками). Теги вокруг текста и просьбы отделяют их от данных карты.
    """
    lines = vip_natal.chart_block(natal, gender, time_known=time_known)
    lines += [
        "",
        "Текущий разбор (заголовок блока, затем абзацы; блоки разделены пустыми строками):",
        "<разбор>",
        draft.strip(),
        "</разбор>",
        "",
        "Просьба редактора:",
        "<просьба>",
        request.strip(),
        "</просьба>",
        "",
        (
            "Выполни просьбу по правилам из системного сообщения и верни разбор "
            "целиком. Только JSON, без обёртки markdown."
        ),
    ]
    return "\n".join(lines)


# Ответ того же формата, что у черновика, — разбор и сборка общие.
parse = vip_natal.parse
to_draft = vip_natal.to_draft
