"""Приписка про приложение, которую render() ставит под заголовок постов сообщества.

Тексты живут отдельным модулем, чтобы правка формулировок не разъехалась по
файлам. Модель их не пишет: в astro_event.SYSTEM стоит запрет на приглашения,
да и приписка обязана быть дословной, а не пересказанной.

В рассылку (services/broadcast.py) не идёт — там ту же работу делает кнопка
под письмом.
"""

from __future__ import annotations

import random

from app.config import get_settings

# Без цены и без слова «купить»: ссылка ведёт в Mini App, а платное — за
# пределами VK (docs/astro-context.md, «Приписка про приложение»).
# Формулировки не привязаны ко дню: тот же кортеж кормит посты о событиях,
# которые описывают период в недели и месяцы. Точку или ссылку ставит line().
LINES = (
    (
        "Небо ниже — одно на всех, а карта рождения у каждого своя. "
        "Свою можно собрать в приложении сообщества"
    ),
    (
        "Ниже — про небо для всех сразу. Как оно ложится на твою собственную "
        "карту, видно в приложении сообщества"
    ),
    (
        "Свои дома, аспекты и положения планет при рождении можно посмотреть "
        "в приложении сообщества"
    ),
    (
        "Что из этого неба про тебя лично, видно по натальной карте — "
        "она считается в приложении сообщества"
    ),
    (
        "Свою карту целиком — с домами, аспектами и разбором — можно посмотреть "
        "в приложении сообщества"
    ),
)


def line(seed: int | None = None) -> str:
    """Одна приписка из LINES, выбранная случайно, со ссылкой на Mini App.

    seed делает выбор постоянным для поста: /admin/content зовёт render() на
    каждую перезагрузку, и без зерна приписка менялась бы под курсором во
    время вычитки. Без VK_APP_ID (локально, в тестах) — без ссылки.
    """
    text = random.Random(seed).choice(LINES)
    app_id = get_settings().vk_app_id
    # Адрес без https://: VK сам делает его ссылкой, а в тексте он короче.
    return f"{text}: vk.com/app{app_id}" if app_id else f"{text}."
