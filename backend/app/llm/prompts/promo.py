"""Приписка про приложение, которую render() приклеивает к постам сообщества.

Тексты живут отдельным модулем, чтобы правка формулировок не разъехалась по
файлам. Модель их не пишет: в astro_event.SYSTEM стоит запрет на приглашения,
да и приписка обязана быть дословной, а не пересказанной.

В рассылку (services/broadcast.py) не идёт — там ту же работу делает кнопка
под письмом.
"""

from __future__ import annotations

import random

# Без цены, без слова «купить» и без ссылки: пост живёт в ленте сообщества,
# а платное — за пределами VK (docs/astro-context.md, «Оплата вне Mini App»).
# Формулировки не привязаны ко дню: тот же кортеж кормит посты о событиях,
# которые описывают период в недели и месяцы.
LINES = (
    (
        "А свою карту целиком — с домами, аспектами и разбором — "
        "можно посмотреть в приложении сообщества."
    ),
    (
        "А как всё это ложится на твою собственную карту — "
        "видно в приложении сообщества."
    ),
    (
        "Небо одно на всех, а карта рождения у каждого своя — "
        "её можно собрать в приложении сообщества."
    ),
    (
        "Свои дома, аспекты и положения планет при рождении "
        "можно посмотреть в приложении сообщества."
    ),
    (
        "Что из этого про тебя лично, видно по натальной карте — "
        "она считается в приложении сообщества."
    ),
)


def line(seed: int | None = None) -> str:
    """Одна приписка из LINES, выбранная случайно.

    seed делает выбор постоянным для поста: /admin/content зовёт render() на
    каждую перезагрузку, и без зерна приписка менялась бы под курсором во
    время вычитки. Соседние посты при этом могут совпасть — это допустимо.
    """
    return random.Random(seed).choice(LINES)
