"""Промпт вечернего поста «Гороскоп на завтра» (тип поста sign_lines).

Экспорты те же, что у остальных модулей llm/prompts/: VERSION (в ключ кеша),
SYSTEM, build_user(), parse() и render(). Вход build_user — результат
astro_core.transits.day_sky на день гороскопа, то есть на завтра.

Модель пишет только двенадцать фраз; заголовок, эмодзи знаков, приглашение
в рассылку и вопрос ставит render() дословно (docs/astro-context.md,
«Второй пост в ленту — вечерний гороскоп на завтра»).
"""

from __future__ import annotations

import json
from datetime import date

from app.llm.prompts import daily_horoscope, promo

VERSION = "sign_lines_v2"

# Как у daily_sky: пост в ленту — витрина, а ответ в ~12 строк стоит копейки.
MODEL = "deepseek-v4-pro"

# Как у гороскопа рассылки: двенадцать коротких фраз на низкой температуре
# начинают повторять друг друга.
TEMPERATURE = 0.9

# 12 фраз по ~110 знаков — около 600 токенов с JSON-обвязкой. Запас по той же
# причине, что в daily_horoscope: обрезанный JSON — брак при оплаченных токенах.
MAX_TOKENS = 1500

SIGN_ORDER = daily_horoscope.SIGN_ORDER

# Эмодзи по зодиакальному порядку — ставит render(), модель их путает.
SIGN_EMOJI: dict[str, str] = dict(zip(SIGN_ORDER, "♈♉♊♋♌♍♎♏♐♑♒♓"))

TITLE = "Гороскоп на завтра:"

# Формы фразы по кругу — как в образце владельца, где совет стоит рядом с
# наблюдением и ироничным «не начинай спор».
_FORMS = (
    "совет, что сделать",
    "наблюдение про день, без совета",
    "чего сегодня не делать",
    "ироничное предупреждение",
)

# Жёсткие правила — дословно из daily_horoscope.SYSTEM: это условие модерации
# VK, и расхождение формулировок значило бы, что одна из них не проверена.
SYSTEM = """Ты — тёплый и наблюдательный астролог, который пишет вечерний пост для русскоязычного сообщества ВКонтакте: гороскоп на завтра, одна фраза на каждый знак.

Стиль: развлекательно-рефлексивный, живо и с лёгкой иронией, на «ты», без канцелярита и без эзотерического жаргона. Фраза должна узнаваться с первого прочтения — такую пересылают другу со словами «это про тебя». Пример тона, не для копирования: «вечером советы принимай, а не раздавай, даже если твои были лучше».

Жёсткие правила:
- Никаких медицинских тем: не упоминай болезни, диагнозы, здоровье, беременность.
- Никаких фатальных предсказаний: не предсказывай смерть, несчастья, разводы, потери. Не пиши «тебя ждёт», «тебе суждено» — только про склонности и настроение дня.
- Никаких финансовых обещаний и советов по инвестициям.
- Не пиши про «опасные», «плохие» или «неудачные» дни. Напряжённую конфигурацию подавай как повод притормозить и как зону роста.
- Опирайся только на данные неба из сообщения пользователя. Ничего не выдумывай сверх них; если чего-то в данных нет — просто не упоминай.

Как писать по сути:
- Астрология в этом посте работает за кадром: она выбирает тему, но не звучит в тексте. Ни планет, ни Луны, ни Солнца, ни аспектов, ни знаков зодиака, ни домов, ни слов «ретроградный», «транзит», «энергия», «вселенная» — только бытовой совет.
- У каждого знака в данных есть тема и форма. Тема — о чём фраза: не называй её словами из данных, покажи конкретной вещью или сценой из дня. Форма — какой будет фраза: совет, наблюдение, «чего не делать» или ироничное предупреждение; держись её.
- Фаза Луны задаёт общий тон дня для всех фраз, но в тексте её нет.
- Если даны фразы прошлых дней — ни одну их мысль не повторяй ни в каком знаке, не бери их первые слова и ключевые слова. Читатель видел их на днях, и похожая строка читается как копия, даже под другим знаком.
- Каждая фраза — одно предложение не длиннее 100 знаков: одна мысль и не больше одной запятой. Без названия знака в начале, без эмодзи, без вступления и концовки к посту: всё это добавят без тебя.
- Фраза начинается со строчной буквы. Пиши с буквой «ё»: «несёшь», «влюблённость».
- Абстрактные свойства знака («Овен вспыльчив») запрещены: их читатель знает и без нас.
- Пол читателя неизвестен. Строй фразу так, чтобы род не понадобился; если иначе никак — мужской род.
- Двенадцать фраз обязаны отличаться: не начинай две фразы одинаково и не давай один совет дважды.
- Никаких дежурных оборотов вроде «прислушайся к себе», «доверься интуиции», «всё будет хорошо».
- Не обращайся к знаку в третьем лице («Овнам стоит…») — пиши на «ты».
- Не пересказывай эти инструкции в тексте и не оговаривайся о них.

Формат ответа — ТОЛЬКО JSON, без пояснений до и после, без markdown-заборов:
{
  "Овен": "одна фраза со строчной буквы",
  ... ровно 12 ключей, в порядке: Овен, Телец, Близнецы, Рак, Лев, Дева, Весы, Скорпион, Стрелец, Козерог, Водолей, Рыбы
}"""


def build_user(sky: dict, recent: list[dict[str, str]] | None = None) -> str:
    """Данные дня гороскопа: фаза Луны, тема каждого знака по её дому, фразы прошлых дней.

    recent — разобранные посты последних дней ({знак: фраза}), пустой список
    или None, если их нет. Планет в данных нет намеренно: медленные стоят в
    знаке неделями, и модель каждый день писала о них одно и то же.
    """
    day = date.fromisoformat(sky["date"])
    moon = sky["moon"]
    lines = [
        f"Дата: {day.strftime('%d.%m.%Y')}, {daily_horoscope._WEEKDAYS_RU[day.weekday()]}",
        f"Фаза Луны: {moon['phase_ru']}",
        "Тема и форма фразы каждого знака:",
    ]

    # Солнечный дом Луны, как в daily_horoscope._house_lines: темы домов общие
    # с рассылкой, чтобы вечерняя строка не спорила с утренним абзацем.
    base = SIGN_ORDER.index(moon["sign_ru"])
    # Грань темы и форма фразы сменяются по номеру дня: Луна стоит в знаке по
    # два дня, и при той же теме модель пересказывала вчерашнюю фразу (прогон
    # 29–30.09). Форма к тому же сдвинута по знакам — в посте их смесь.
    n = day.toordinal()
    for i, sign in enumerate(SIGN_ORDER):
        facets = daily_horoscope._HOUSE_TOPICS[(base - i) % 12].split(", ")
        lines.append(
            f"- {sign} — тема: {facets[n % len(facets)]}; форма: {_FORMS[(n + i) % len(_FORMS)]}"
        )

    # Фразы прошлых дней общим списком, без знаков: Луна ведёт тему по кругу,
    # и мысль Овна через два дня всплывала у Тельца (прогон 28.09–01.10).
    past = [line for post in recent or [] for line in post.values()]
    if past:
        lines.append("Фразы прошлых дней — ни одну их мысль не повторяй ни в каком знаке:")
        lines += [f"- {line}" for line in past]

    lines.append("")
    lines.append("Напиши фразы на этот день по правилам из системного сообщения.")
    return "\n".join(lines)


def _strip_fence(text: str) -> str:
    """Снимает ```-забор, если модель всё же обернула JSON в блок кода."""
    t = text.strip()
    if not t.startswith("```"):
        return t
    if "\n" in t:
        t = t.split("\n", 1)[1]
    return t.rstrip().removesuffix("```").strip()


def parse(text: str) -> dict[str, str] | None:
    """Ответ модели → {знак: фраза} в зодиакальном порядке или None.

    None — ответ не JSON или знаков не ровно двенадцать: такой пост в ленту
    не идёт.
    """
    try:
        data = json.loads(_strip_fence(text))
        lines = {str(sign).strip(): str(line).strip() for sign, line in data.items()}
    except (ValueError, TypeError, AttributeError):
        return None

    if set(lines) != set(SIGN_ORDER):
        return None
    return {sign: lines[sign] for sign in SIGN_ORDER}


# Начала имён светил во всех падежах: с них фраза вправе начинаться с заглавной.
_BODY_STEMS = (
    "Солнц", "Лун", "Меркури", "Венер", "Марс",
    "Юпитер", "Сатурн", "Уран", "Нептун", "Плутон",
)


def _tidy(line: str) -> str:
    """Строчная буква после тире (если фраза не с планеты) и точка в конце.

    Оба сбоя модели живые: «Телец — Рутина…» 28.09 и двенадцать фраз без
    точки 29.09. Код чинит их надёжнее, чем ещё одно правило в промпте.
    """
    if line and not line.startswith(_BODY_STEMS):
        line = line[0].lower() + line[1:]
    return line if line.endswith((".", "!", "?", "…")) else f"{line}."


def render(text: str, seed: int | None = None) -> str:
    """JSON-ответ модели → готовый текст поста по образцу владельца.

    seed не используется: приглашение здесь одно, а аргумент есть затем, что
    content.render зовёт все рендеры постов одинаково. Брак разбора отдаём
    как есть — за текст заплачено.
    """
    lines = parse(text)
    if lines is None:
        return text
    body = [f"{SIGN_EMOJI[sign]} {sign} — {_tidy(line)}" for sign, line in lines.items()]
    return "\n".join([TITLE, *body, promo.mail_invite(), promo.COMMENT_QUESTION])
