def _roles(table: dict, aspect: dict[str, Any]) -> tuple[str, str] | str:
    """Роли сторон A и B в контакте — или одна строка, если роль общая."""
    key = tuple(sorted((aspect["a"], aspect["b"]), key=_ORDER.index))
    roles = table[key]
    if isinstance(roles, str):
        return roles
    # Ключ упорядочен по _ORDER; если у стороны A вторая планета ключа — роли меняем.
    return roles if aspect["a"] == key[0] else (roles[1], roles[0])


def _section(table: dict, aspects: list[dict[str, Any]], label_b: str, missing: str) -> list[str]:
    if not aspects:
        return [f"1. {missing}"]
    lines = []
    for n, aspect in enumerate(aspects, 1):
        roles = _roles(table, aspect)
        if isinstance(roles, str):
            lines.append(f"{n}. оба — {roles}")
        else:
            lines.append(f"{n}. ты — {roles[0]}; {label_b} — {roles[1]}")
    return lines


def build_user(facts: dict[str, Any], *, name_b: str | None = None) -> str:
    """User-сообщение из фактов тизера (services/pair_teaser.facts)."""
    named = bool((name_b or "").strip())
    label_b = (name_b or "").strip() or "партнёр"
    lines = [
        "Тот, кто спросил, — «ты»."
        + (
            f" Партнёра зовут {label_b}."
            if named
            # Пол безымянного партнёра неизвестен: в v1 модель в двух прогонах из трёх писала «его», «он».
            else " Имени и пола партнёра мы не знаем: пиши «твой партнёр», «партнёра», "
            "«партнёру» и обходись без слов «он», «она», «его», «её»."
        ),
        "Список «держит» — на каждый пункт один пункт strong:",
        *_section(_STRONG, facts["strong"], label_b, "оба — просто хорошо себя чувствовать рядом"),
        "Список «искрит» — на каждый пункт один пункт spark:",
        *_section(_SPARK, facts["spark"], label_b, "оба — по-разному понимать, что такое близость"),
        "",
        "Напиши тизер по правилам из системного сообщения. Верни только JSON.",
    ]
    return "\n".join(lines)


def _strip_fence(text: str) -> str:
    """Снимает ```json-забор: запрет в SYSTEM соблюдается не всегда."""
    t = text.strip()
    if not t.startswith("```"):
        return t
    if "\n" in t:
        t = t.split("\n", 1)[1]
    return t.rstrip().removesuffix("```").strip()


_FIRST_SENTENCE = re.compile(r"(?<=[.!?…])\s+")


def _clean(value: Any) -> str:
    return " ".join(str(value).split())


def _item(value: Any) -> str:
    # Пункт начинаем с прописной сами: модель пишет то так, то так.
    text = _clean(value)
    return text[:1].upper() + text[1:]


def parse(text: str) -> dict[str, Any] | None:
    """Ответ модели → {"hook", "spark", "strong", "outcome"} или None, если не разобрать.

    spark и strong — непустые списки строк, не длиннее MAX_ITEMS. Знак «%» где
    угодно — тоже None: процент совместимости запрещён, проще запросить заново.
    """
    try:
        data = json.loads(_strip_fence(text))
        out: dict[str, Any] = {
            "hook": _clean(data["hook"]).rstrip("."),
            "spark": [_item(x) for x in data["spark"]][:MAX_ITEMS],
            "strong": [_item(x) for x in data["strong"]][:MAX_ITEMS],
                # Итог — одна фраза: второй модель дописывает условие «если…», а это
            # уже ответ на «что делать», который продаёт платный разбор.
            "outcome": _FIRST_SENTENCE.split(_item(data["outcome"]), maxsplit=1)[0],
        }
    except (ValueError, TypeError, KeyError):
        return None
    every = [out["hook"], out["outcome"], *out["spark"], *out["strong"]]
    if not out["spark"] or not out["strong"] or any(not line or "%" in line for line in every):
        return None
    return out
