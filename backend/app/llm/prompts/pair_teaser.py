"""Промпт бесплатного тизера пары в VK-боте: короткий пост про одну пару.

Формат — как посты про пары в сообществе: заголовок-сцена, пункты «Что
держит», пункты «Где искрит», итог одной фразой. Тизер — крючок: он
показывает, что происходит, а почему и что делать — продаёт платный разбор;
фразу про него ставит код. На каждый пункт код даёт контакт уже в виде ролей
(_STRONG, _SPARK): планет и знаков во входе нет, тизер считается по дате и
времени, а не по знаку зодиака.
Ответ — JSON {hook, strong, spark, outcome}. В reports не пишется, не кешируется.
История версий и замеры — docs/astro-prompts-v2.md, раздел 8.
"""

