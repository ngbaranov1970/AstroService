"""Промпт бесплатного тизера пары в VK-боте: три короткие строки.

Вход — факты, уже отобранные services/pair_teaser.facts(): знаки и несколько
контактов без орбов, градусов и счёта. Чисел в промпте нет намеренно —
процитировать процент или орб модели нечем. Ответ — JSON {strong, spark, more};
подписи строк ставит код. Отчётом в reports тизер не является и в кеш не идёт.
Правила пары (без домов, вердикта и предсказаний) — docs/astro-prompts-v2.md, раздел 8.
"""

from __future__ import annotations

import json
from typing import Any

VERSION = "pair_teaser_v1"

# Как у вечерних строк по знакам: короткой фразе нужна живость, а не точность пересказа.
TEMPERATURE = 0.9

# Три строки по 20 слов и JSON-обвязка; запас — чтобы ответ не оборвался на середине.
MAX_TOKENS = 500

# Предел строки в символах: первые две печатаются на картинке 1080×1080.
LINE_MAX = 170

KEYS = ("strong", "spark", "more")

SYSTEM = f"""Ты — тёплый и наблюдательный астролог. Ты пишешь короткий бесплатный
тизер совместимости для личных сообщений ВКонтакте: три строки про пару.

# Вход
Знаки нескольких планет двух людей и список контактов между их картами.
Сторона A — тот, кто спросил; сторона B — его партнёр. Расчёт уже сделан,
не пересчитывай и не дополняй его.

# Что написать
strong — что в этой паре сильное: одна мысль про то, что их держит или тянет
друг к другу. Опирайся на гармоничный контакт из списка, а если его нет —
на сочетание знаков.
spark — где между ними искрит: одна мысль про трение или разный темп.
Опирайся на напряжённый контакт или контакт Сатурна, а если их нет — на
разницу знаков. Это наблюдение, а не приговор.
more — что видно только в полном разборе: просто перечисли две-три темы из
строки «За бортом тизера», своими словами и без трактовок. Не объясняй, что
они значат, — только назови.

# Правила
Каждая строка — одно предложение, не длиннее {LINE_MAX} символов.
К стороне A обращайся на «ты», о стороне B пиши в третьем лице: по имени,
если оно дано, иначе «твой партнёр».
Называй планеты и знаки из входа — так видно, что это расчёт, а не общие слова.
Контакты бери только из списка. Если контакта в списке нет — его нет.
Не пиши про дома, асцендент и время рождения.
Никаких процентов, баллов, оценок совместимости и вердиктов «подходите /
не подходите».
Не предсказывай расставание, измену, брак, болезни и любые события.
Без эмодзи, без markdown, без кавычек вокруг строк.

# Формат ответа
Верни ТОЛЬКО валидный JSON, без markdown-обёртки и без текста до и после:

{{"strong": "...", "spark": "...", "more": "..."}}"""


_SIGN_POINTS = (("Sun", "Солнце"), ("Moon", "Луна"), ("Venus", "Венера"), ("Mars", "Марс"))


def _signs_line(side: str, label: str, signs: dict[str, str]) -> str:
    parts = [f"{ru} — {signs[key]}" for key, ru in _SIGN_POINTS if key in signs]
    return f"- {side} ({label}): " + ", ".join(parts)


def _aspect_line(aspect: dict[str, Any]) -> str:
    # Буквы сторон у каждой планеты: шапку списка модель теряет к третьей строке.
    return f"- {aspect['a_ru']} A — {aspect['type_ru']} — {aspect['b_ru']} B"


def build_user(facts: dict[str, Any], *, name_b: str | None = None) -> str:
    """User-сообщение из фактов тизера (services/pair_teaser.facts)."""
    label_b = (name_b or "").strip() or "партнёр"
    lines = [
        "Сторона A — тот, кто спросил; обращайся к нему на «ты».",
        f"Сторона B — {label_b}."
        if (name_b or "").strip()
        else "Сторона B — партнёр, имени мы не знаем: пиши «твой партнёр».",
        "Знаки:",
        _signs_line("A", "ты", facts["signs"]["a"]),
        _signs_line("B", label_b, facts["signs"]["b"]),
    ]
    for title, key in (
        ("Венера и Марс между картами:", "venus_mars"),
        ("Солнце и Луна между картами:", "sun_moon"),
        ("Сатурн одного к личным планетам другого:", "saturn"),
    ):
        lines.append(title)
        lines += [_aspect_line(a) for a in facts[key]] or ["- контактов нет"]
    lines.append("За бортом тизера (только назвать, не трактовать): " + "; ".join(facts["rest"]) + ".")
    lines.append("")
    lines.append("Напиши три строки по правилам из системного сообщения. Верни только JSON.")
    return "\n".join(lines)


def _strip_fence(text: str) -> str:
    """Снимает ```json-забор: запрет в SYSTEM соблюдается не всегда."""
    t = text.strip()
    if not t.startswith("```"):
        return t
    if "\n" in t:
        t = t.split("\n", 1)[1]
    return t.rstrip().removesuffix("```").strip()


def parse(text: str) -> dict[str, str] | None:
    """Ответ модели → {"strong", "spark", "more"} или None, если не разобрать.

    Строка с «%» — тоже None: процент совместимости в тизере запрещён, и
    проще запросить заново, чем вырезать.
    """
    try:
        data = json.loads(_strip_fence(text))
        out = {key: " ".join(str(data[key]).split()) for key in KEYS}
    except (ValueError, TypeError, KeyError):
        return None
    if any(not line or "%" in line for line in out.values()):
        return None
    return out
