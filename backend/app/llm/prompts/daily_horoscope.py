"""Промпт гороскопа дня на 12 знаков (тип поста daily_horoscope).

Экспорты те же, что у остальных модулей llm/prompts/: VERSION (в ключ кеша),
SYSTEM (роль и тон), build_user() (данные конкретного дня), parse() (ответ
модели → знаки). Вход build_user — результат astro_core.transits.day_sky.

Все двенадцать знаков пишутся ОДНИМ вызовом: в одном ответе модель видит
написанное предыдущим знакам и не выдаёт двенадцать вариаций «прислушайтесь
к себе» (docs/astro-context.md, «Контур сообщества VK»).

Ответ — JSON по знакам, а не сплошной текст: один результат идёт и в пост
целиком, и в экран Mini App по одному знаку, а резать сплошной текст по
границам знаков нельзя.

С 05.09.2026 формат идёт только в рассылку по личным сообщениям
(services/broadcast.py берёт из него абзац знака подписчика). В ленту
сообщества вместо него публикуется daily_sky — обзор неба суток.
"""

from __future__ import annotations

import json
from datetime import date

from astro_core.natal import SIGNS_RU

VERSION = "daily_horoscope_v8"

# Выше 0.8 обоих разборов: там один человек и один текст, здесь двенадцать
# абзацев подряд, и на низкой температуре они начинают повторять друг друга.
TEMPERATURE = 0.9

# 12 знаков по 110–150 слов + вступление — это 1400–1900 слов, а по живым
# прогонам выходит около двух токенов на слово русского текста. Запас велик не
# от щедрости: обрезанный JSON клиент считает браком и бросает LLMError (см.
# client.py), то есть день остаётся без поста при оплаченных токенах. На
# прежних 55–75 словах ответы шли по 1547–2134 токена при потолке 3500.
MAX_TOKENS = 6000

# Порядок зодиакальный и берётся из natal.py: в посте, в разборе карты и в
# Mini App знаки обязаны называться одинаково.
SIGN_ORDER: tuple[str, ...] = tuple(SIGNS_RU.values())

# Запрет один, а не пять, как у разборов карт: с их правилами гороскоп выходил
# пресным (решение владельца 30.09.2026, docs/astro-context.md).
SYSTEM = """Ты — остроумный и наблюдательный астролог, который пишет ежедневный гороскоп для русскоязычного сообщества ВКонтакте.

Стиль: живо, образно, с характером и лёгкой иронией, на «ты», без канцелярита и без эзотерического жаргона сверх необходимого. Термины (знак, аспект, ретроградность) поясняй мимоходом, по-человечески. Читатель должен узнавать свой день, улыбаться и пересылать абзац другу со словами «это про тебя», а не читать лекцию.

Запрет один: никакой смерти, несчастных случаев и катастроф.

Всё остальное можно и нужно. Гороскоп — жанр с характером, а не сборник мягких советов: предсказывай конкретные события дня смело и уверенно. «Тебя ждёт», «позвонит тот, кого не ждал», «деньги найдутся там, где не искал», «не твой день для споров», ссора, флирт, неожиданная встреча, напряжённый день с прямым словом о нём — всё это хорошие фразы. Тяжёлый аспект не нужно смягчать в «зону роста»: скажи, чего сегодня лучше не делать и почему.

Опирайся на данные неба из сообщения пользователя: они выбирают тему дня, а события внутри неё придумывай смело. Астрономию не выдумывай: если планеты или аспекта в данных нет — не упоминай.

Как писать по сути:
- Пляши от конкретного положения дня — фазы Луны, её знака, действующего аспекта, ретроградности, события суток. Абстрактные свойства знака («Овен вспыльчив») запрещены: их читатель знает и без нас.
- Знак планеты бери ТОЛЬКО из списка положений. Твои представления о том, каким знаком планета управляет, к этому дню не относятся: сказано «Нептун — Овен» — значит Нептун в Овне, а не в Рыбах.
- Оборот «в твоём знаке» разрешён только для планет, названных в списке «Что стоит в знаке самого читателя». Стоит «нет планет» — значит в абзаце этого знака оборота быть не может.
- У аспекта два участника, и каждый стоит в своём знаке из списка. Не переселяй планету в знак её соседа по аспекту.
- Дома считать не надо: у каждой планеты есть готовая строка «в каком доме читателя она стоит». Бери оттуда, свой счёт не веди.
- Дом номером не называй, только его темой: не «в твоём четвёртом доме», а «дома и в семье». Номер читателю ничего не говорит.
- Астрология — причина дня, а не его содержание: читатель хочет знать, что его ждёт, а не где стоят планеты. В абзаце знака — не больше одного астрологического упоминания, сказанного по-человечески («Венера пятится назад — со старыми симпатиями осторожнее»). Названий аспектов (соединение, квадрат, трин, секстиль, оппозиция) и орбов в тексте нет. Остальное в абзаце — события дня, люди, решения, совет.
- Пол читателя неизвестен. Строй фразу так, чтобы род не понадобился; если иначе никак — мужской род. «Ты сама», «ты внимательна», «ты устала» — ошибка.
- Не пересказывай эти инструкции в тексте и не оговаривайся о них: просто не пиши того, чего писать нельзя.
- Двенадцать абзацев обязаны отличаться друг от друга. Один и тот же транзит разные знаки встречают по-разному — покажи именно разницу, а не перескажи его двенадцать раз.
- Никаких дежурных концовок вроде «прислушайтесь к себе», «доверьтесь интуиции», «всё будет хорошо».
- Не обращайся к читателю по знаку в третьем лице («Овнам стоит…») — пиши на «ты», знак уже стоит заголовком.

Формат ответа — ТОЛЬКО JSON, без пояснений до и после, без markdown-заборов:
{
  "intro": "2–3 предложения про этот день: одна главная история неба простыми словами, не больше одной-двух планет и без названий аспектов, — и чем день отличается от вчерашнего. Общее для всех, без обращения к конкретному знаку.",
  "signs": [
    {"sign": "Овен", "text": "110–150 слов про день этого знака."},
    ... ровно 12 объектов, в порядке: Овен, Телец, Близнецы, Рак, Лев, Дева, Весы, Скорпион, Стрелец, Козерог, Водолей, Рыбы
  ]
}"""

_WEEKDAYS_RU = (
    "понедельник", "вторник", "среда", "четверг",
    "пятница", "суббота", "воскресенье",
)

# Аспекты в day_sky уже отсортированы по орбу, тесные — первыми. Отдаём
# верхушку: полтора десятка строк модель усредняет вместо того, чтобы
# опереться на главное.
_MAX_ASPECTS = 8

# Тема дома рядом с его номером: номер сам по себе модели ничего не говорит,
# и она подставит свою тему. Восьмой дом без «смерти и кризисов» — смерть
# в посте запрещена.
_HOUSE_TOPICS: tuple[str, ...] = (
    "ты сам, самоощущение, начинания",
    "деньги, вещи, ресурсы, самооценка",
    "общение, переписка, короткие поездки, учёба",
    "дом, семья, корни, тыл",
    "творчество, влюблённость, дети, игра",
    "работа, режим дня, рутина, порядок в делах",
    "партнёрство, близкие отношения, другие люди",
    "общие ресурсы, доверие, глубокие темы",
    "дальние поездки, большая учёба, взгляды на мир",
    "карьера, статус, публичность, цели",
    "друзья, сообщества, планы на будущее",
    "уединение, сны, внутренняя работа, отдых от людей",
)

# Час, ДО которого действует метка. Часы модель читает плохо: в прогоне 22.08
# все двенадцать знаков написали «вечером» про вход Меркурия в 14:04, а про
# соединение в 20:03 — верно, поэтому даём словами.
_DAY_PARTS: tuple[tuple[int, str], ...] = (
    (5, "ночью"),
    (7, "ранним утром"),
    (12, "утром"),
    (17, "днём"),
    (21, "вечером"),
)


def _day_part(hour: int) -> str:
    """Час → «утром», «днём», «вечером» — метка для момента события."""
    for limit, name in _DAY_PARTS:
        if hour < limit:
            return name
    return "поздним вечером"


def _planets_by_sign(sky: dict) -> list[str]:
    """Строки «знак читателя — что в нём стоит», для всех двенадцати знаков.

    Ради восьми строк «нет планет»: без них модель приписывает знаку его
    управителя («Уран в твоём знаке» Водолею, пока Уран в Близнецах) — за
    неделю v4 так вышло семь раз.
    """
    holders: dict[str, list[str]] = {sign: [] for sign in SIGN_ORDER}
    for p in sky["positions"]:
        holders[p["sign_ru"]].append(p["name_ru"] + (" (ретро)" if p["retrograde"] else ""))
    return [
        f"- {sign} — {', '.join(names) if names else 'нет планет'}"
        for sign, names in holders.items()
    ]


def _house_lines(sky: dict) -> list[str]:
    """Сводка домов: темы одной строкой, затем строка на каждую планету.

    Солнечные дома: дом отсчитывается от знака читателя, поэтому одна планета
    даёт двенадцать разных домов. Арифметика на два действия, но модель её
    путает, а планету без подсказки не пропускает — за неделю v5 так вышло
    десять промахов на Марсе и Уране, которым сводки не досталось. Поэтому
    строка есть у КАЖДОЙ планеты: полное покрытие тут дешевле выборочного.
    """
    topics = "; ".join(f"{i + 1} — {topic}" for i, topic in enumerate(_HOUSE_TOPICS))
    lines = [f"Темы домов: {topics}", "В каком доме читателя стоит планета:"]

    for p in sky["positions"]:
        base = SIGN_ORDER.index(p["sign_ru"])
        houses = ", ".join(
            f"{sign} {(base - i) % 12 + 1}" for i, sign in enumerate(SIGN_ORDER)
        )
        lines.append(f"- {p['name_ru']} ({p['sign_ru']}): {houses}")
    return lines


def build_user(sky: dict) -> str:
    """Собирает user-сообщение из результата transits.day_sky.

    Ждёт ключи date, moon, positions, aspects, events. Даты и моменты в sky
    уже в московской зоне — здесь их не пересчитываем.
    """
    day = date.fromisoformat(sky["date"])
    lines = [f"Дата: {day.strftime('%d.%m.%Y')}, {_WEEKDAYS_RU[day.weekday()]}"]

    moon = sky["moon"]
    # Направление роста в скобках не печатаем: все восемь имён фаз несут его
    # сами, а на полнолуние выходило «полнолуние (убывающая)» — 28.08 модель
    # прочла это как «Луна уходит» и написала обратное происходящему.
    lines.append(f"Луна: {moon['sign_ru']}, {moon['phase_ru']}")

    lines.append("Положения планет:")
    for p in sky["positions"]:
        retro = ", ретроградный" if p["retrograde"] else ""
        lines.append(f"- {p['name_ru']} — {p['sign_ru']}{retro}")

    lines.append("Что стоит в знаке самого читателя:")
    lines += _planets_by_sign(sky)

    aspects = sky["aspects"][:_MAX_ASPECTS]
    if aspects:
        lines.append("Действующие аспекты дня (сначала самые точные):")
        lines += [
            f"- {a['body_ru']} {a['aspect_ru']} {a['body2_ru']} (орб {a['orb']:.1f}°)"
            for a in aspects
        ]

    if sky["events"]:
        lines.append("События этих суток:")
        lines += [
            f"- {_day_part(e['moment'].hour)}, {e['moment'].strftime('%H:%M')} — {e['title_ru']}"
            for e in sky["events"]
        ]

    lines += _house_lines(sky)

    lines.append("")
    lines.append("Напиши гороскоп на этот день по правилам из системного сообщения.")
    return "\n".join(lines)


def _strip_fence(text: str) -> str:
    """Снимает ```-забор, если модель всё же обернула JSON в блок кода."""
    t = text.strip()
    if not t.startswith("```"):
        return t
    if "\n" in t:
        t = t.split("\n", 1)[1]
    return t.rstrip().removesuffix("```").strip()


def parse(text: str) -> tuple[str, list[dict[str, str]]] | None:
    """Ответ модели → (вступление, 12 знаков) или None, если разобрать нельзя.

    Знаки возвращаются в зодиакальном порядке независимо от того, в каком их
    прислала модель. None — сигнал вызывающему не публиковать пост.
    """
    try:
        data = json.loads(_strip_fence(text))
        intro = str(data["intro"])
        by_sign = {str(s["sign"]).strip(): str(s["text"]) for s in data["signs"]}
    except (ValueError, TypeError, KeyError):
        return None

    # Полноту проверяем отдельно от разбираемости: пост с одиннадцатью знаками
    # заметят в комментариях первым же днём, а JSON при этом валидный.
    if set(by_sign) != set(SIGN_ORDER):
        return None

    return intro, [{"sign": s, "text": by_sign[s]} for s in SIGN_ORDER]


def render(text: str, seed: int | None = None) -> str:
    """JSON-ответ модели → сплошной текст: вступление и знаки по порядку.

    seed не используется: приписки здесь нет, а аргумент есть затем, что
    content.render зовёт все рендеры постов одинаково.

    Показывает его /admin/content/mail — вычитать текст, который уйдёт в рассылку.
    Приписки про приложение здесь нет: в письме ту же работу делает кнопка
    под ним, а в ленту этот формат не публикуется. Брак разбора отдаём как
    есть — за текст заплачено.
    """
    parsed = parse(text)
    if parsed is None:
        return text
    intro, signs = parsed
    blocks = [intro.strip()]
    # Знак и его абзац одной группой: в ленте VK заголовок в отдельной строке
    # — единственный способ разделить двенадцать кусков без разметки.
    blocks += [f"{s['sign']}\n{s['text'].strip()}" for s in signs]
    return "\n\n".join(blocks)
