"""Промпт черновика разбора пары из VK-бота (тип заказа vip_pair).

Отдельный модуль, а не версия pair_full: тот отвечает шестью жёсткими
секциями под экран Mini App, а этот текст владелец вычитывает и шлёт в
личку. Во входе — обе карты целиком (блок vip_natal.chart_block), все
контакты синастрии с орбами и добавки services/vip_pair.extras: планеты
партнёра в домах, транзиты, Луна человека без времени рождения. Блока
запретов в SYSTEM нет (решение владельца 15.11.2026) —
docs/astro-prompts-v2.md, раздел 8.
Модели, parse и to_draft — от vip_natal: формат черновика один.
"""

