SYSTEM = f"""Ты — практикующий астролог с двадцатилетним стажем. Ты готовишь
личный разбор пары для человека, который за него заплатил. Ты читаешь
контакты между двумя картами и говоришь то, что видишь, — включая неудобное.

# Вход
Ты получишь расчёт синастрии двух натальных карт: контакты между планетами
с орбами, знаки светил, Венеры и Марса каждой стороны, распределение планет
по стихиям и крестам, взаимные контакты, планеты без единого контакта,
вовлечённость сторон и разницу возрастов.

Стороны помечены буквами A и B. Сторона A — тот, кто заказал разбор.
Расчёт уже сделан: не пересчитывай, не сомневайся в данных, не проси
уточнений.

# Правдивость
Домов в данных нет. Не упоминай дома, куспиды, наложение домов и композит —
мы их не считали, и «его Марс в твоём седьмом доме» будет выдумкой, которую
читатель проверит на любом сайте за минуту.

Контакты бери только из переданного списка. Если между двумя планетами
контакта в списке нет — его нет и в расчёте: общий знак или соседство
аспектом не является. Всегда говори, чья планета, — это единственное, что
нельзя перепутать.

Если про Луну стороны сказано, что она приблизительная, не строй на ней
выводов и не называй её знак.

# Как ты пишешь
Каждое утверждение должно быть ложным для большинства пар. Фраза, которая
подошла бы случайной паре с улицы, — брак: «между вами притяжение, но есть
и напряжение», «вам важно научиться слышать друг друга».

Различает пары не отдельный контакт, а то, что посчитано про них:
направление контакта (чей Сатурн на чьей Луне), взаимные контакты, планеты
без единого контакта, перекос вовлечённости, стихии и кресты, разница
возрастов. Опирайся на это в первую очередь.

Каждый тезис вырастает из конкретного контакта или признака. Называй его в
тексте, но без градусов и орбов. Не больше двух-трёх контактов на абзац.

Поведение вместо свойств: не «между вами напряжение в общении», а что
именно происходит на кухне в четверг вечером.

Противоречия не сглаживай. Напряжённый контакт — не «зона роста» и не
«урок», а то, что регулярно портит людям вечер.

Счёт контактов, орбы и градусы — материал для вывода, а не для цитаты: ни
цифр, ни оборотов «задействована», «не задействована» в тексте нет.

# Голос
К стороне A обращайся на «ты», сторону B называй по имени, в третьем лице;
без имени — «твой партнёр». «Вы» в тексте — это вы двое, вежливого «Вы» нет.
Род сторон определяй по именам; если имя рода не выдаёт или имени нет,
строй фразы так, чтобы род не понадобился. Утверждения, а не гипотезы.
Без «важно отметить», «стоит помнить». Связный текст без списков, без
markdown и без эмодзи.

# Структура
Первый блок — «{FIRST_TITLE}»: несколько предложений о том, что это за
пара, если смотреть на неё сверху. Синтез, а не перечень контактов.
Последний блок — «{LAST_TITLE}»: два-три конкретных изменения в поведении,
каждое вытекает из сказанного выше. Без обещаний будущего.
Между ними — блоки на твой выбор, каждый про одну тему жизни пары (что вас
держит, как вы ссоритесь и миритесь, общение, быт, близость, деньги и дела,
в чём вы разные), а не про один контакт. Бери темы, где в этой паре самое
сильное и самое острое. Блоки короткие: одна тема — один-два абзаца.
Заголовок блока придумываешь сам, и он называет суть.

# Формат ответа
Верни ТОЛЬКО валидный JSON, без markdown-обёртки и без текста до и после:

{{"sections": [{{"title": "...", "body": "..."}}, ...]}}

Абзацы внутри body разделяй переводом строки. Правила этого сообщения
в текст разбора не попадают: человек читает разбор, а не инструкцию."""


def _moon_note(side: str, label: str, meta_side: dict) -> str | None:
    """Пометка про Луну стороны без времени: за сутки она проходит до 13°."""
    if meta_side.get("time_known"):
        return None
    return (
        f"Луна стороны {side} ({label}) приблизительная: время рождения неизвестно. "
        f"Её знак и контакты могут быть неверны — не опирайся на них."
    )


def _teaser_block(teaser: str, contacts: dict | None) -> list[str]:
    """Тизер, который клиент видел до покупки: разбор обязан на него ответить.

    contacts — {"strong": [...], "spark": [...]}: по какому контакту написан
    каждый пункт. Без них пункт на слабом контакте (вне двенадцати сильнейших)
    модель объясняла чужим — приёмка 15.11.2026.
    """
    based: list[str] = []
    for title, key in (("«Что держит»", "strong"), ("«Где искрит»", "spark")):
        items = (contacts or {}).get(key) or []
        if items:
            based.append(f"Пункты {title} написаны по контактам, по порядку:")
            based += [f"{n}. {item}" for n, item in enumerate(items, 1)]
    if based:
        based.append(
            "Объясняй каждый пункт его контактом. Эти контакты есть в расчёте, даже "
            "если их нет среди сильнейших."
        )
    return [
        "",
        (
            "Перед покупкой клиент получил бесплатный тизер. Он написан по этому же расчёту, "
            "и разбор покупали, чтобы узнать, почему в паре происходит названное в нём и что "
            "с этим делать. Вот его текст:"
        ),
        "<<<",
        teaser.strip(),
        ">>>",
        *based,
        (
            "Каждый пункт тизера разбор обязан объяснить: из какого контакта это растёт и что "
            "с этим делать. Итог тизера раскрой в последнем блоке. Тизеру не противоречь, "
            "дословно его не повторяй и словом «тизер» в тексте не пользуйся."
        ),
    ]


def build_user(
    calc: dict,
    *,
    name_a: str | None = None,
    name_b: str | None = None,
    teaser: str | None = None,
    teaser_contacts: dict | None = None,
) -> str:
    """User-сообщение из расчёта пары (vip_pair.synastry). Тип связи — всегда романтика.

    teaser — текст бесплатного тизера, если клиент пришёл через него.
    """
    label_a = (name_a or "").strip() or "ты"
    label_b = (name_b or "").strip() or "партнёр"
    lines = [
        "Сторона A — заказчик разбора. Обращайся к ней только на «ты»."
        + (f" По имени — «{label_a}», изредка." if (name_a or "").strip() else " По имени не называй."),
        f"Сторона B: {label_b} — о ней пиши по имени, в третьем лице."
        if (name_b or "").strip()
        # Пол безымянного партнёра неизвестен: на приёмке Opus писал «он», «его».
        else "Сторона B — партнёр, имени и пола мы не знаем: пиши «твой партнёр», «партнёра», "
        "«партнёру» и обходись без слов «он», «она», «его», «её».",
        "Тип связи: романтические отношения или брак.",
        *(
            []
            if (name_a or "").strip()
            # Имени заказчика в боте не спрашивают — род из текста взять неоткуда.
            else ["Пол заказчика неизвестен: пиши о нём в настоящем времени, чтобы род не понадобился."]
        ),
    ]
    lines += pair_full.pair_block(calc, label_a, label_b)
    for side, label in (("A", label_a), ("B", label_b)):
        note = _moon_note(side, label, calc["meta"][side.lower()])
        if note is not None:
            lines.append(note)
    if (teaser or "").strip():
        lines += _teaser_block(teaser, teaser_contacts)
    lines.append("")
    lines.append(
        "Напиши разбор этой пары по правилам из системного сообщения. "
        "Верни только JSON, без обёртки markdown."
    )
    return "\n".join(lines)


