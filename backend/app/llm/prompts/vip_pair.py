def _day(d: date) -> str:
    return f"{d:%d.%m.%Y}"


def _moon_line(side: str, moon: dict) -> str:
    """Что известно о Луне стороны без времени: один знак или два с моментом смены."""
    start, end = moon["start"], moon["end"]
    if moon["same_sign"]:
        return (
            f"Луна стороны {side}: весь день рождения {start['sign_loc']} "
            f"(от {start['deg_in_sign']:.0f}° до {end['deg_in_sign']:.0f}°). Знак называй уверенно, "
            f"градус и контакты — приблизительны."
        )
    return (
        f"Луна стороны {side}: в начале суток — {start['sign_ru']} {start['deg_in_sign']:.0f}°, "
        f"в конце — {end['sign_ru']} {end['deg_in_sign']:.0f}°; знак сменился в "
        f"{moon['change_at']} по местному времени. Назови оба знака и скажи, какой вероятнее: "
        f"до {moon['change_at']} — {start['sign_ru']}, после — {end['sign_ru']}."
    )


def _contact_line(aspect: dict, unsure: set[str]) -> str:
    """«- Венера A — трин — Марс B (орб 1.2°)»; буква стороны у каждой планеты."""
    line = f"- {aspect['a_ru']} A — {aspect['type_ru']} — {aspect['b_ru']} B (орб {aspect['orb']}°)"
    # unsure — стороны с приблизительной Луной: её контакт может не существовать.
    if ("A" in unsure and aspect["a"] == "Moon") or ("B" in unsure and aspect["b"] == "Moon"):
        line += " — Луна приблизительная"
    return line


def _transit_lines(side: str, items: list[dict]) -> list[str]:
    """«- Сатурн — соединение — Солнце B: 17.03.2027»; пусто — строка «нет»."""
    if not items:
        return ["- точных транзитов в этом окне нет"]
    return [
        f"- {t['body_ru']} — {t['aspect_ru']} — {t['point_ru']} {side}: "
        + ", ".join(_day(d) for d in t["dates"])
        for t in items
    ]


def _teaser_block(teaser: str, contacts: dict | None) -> list[str]:
    """Тизер, который клиент видел до покупки: разбор обязан на него ответить.

    contacts — {"strong": [...], "spark": [...]}: по какому контакту написан
    каждый пункт. Без них пункт на слабом контакте модель объясняла чужим —
    приёмка 15.11.2026.
    """
    based: list[str] = []
    for title, key in (("«Что держит»", "strong"), ("«Где искрит»", "spark")):
        items = (contacts or {}).get(key) or []
        if items:
            based.append(f"Пункты {title} написаны по контактам, по порядку:")
            based += [f"{n}. {item}" for n, item in enumerate(items, 1)]
    if based:
        based.append("Объясняй каждый пункт его контактом.")
    return [
        "",
        (
            "Перед покупкой клиент получил бесплатный тизер. Он написан по этому же расчёту, "
            "и разбор покупали, чтобы узнать, почему в паре происходит названное в нём и что "
            "с этим делать. Вот его текст:"
        ),
        "<<<",
        teaser.strip(),
        ">>>",
        *based,
        (
            "Каждый пункт тизера разбор обязан объяснить в подходящем блоке: из какого "
            "контакта это растёт и что с этим делать. Тизеру не противоречь, дословно его "
            "не повторяй и словом «тизер» в тексте не пользуйся."
        ),
    ]


def data_lines(
    calc: dict,
    natal_a: dict,
    natal_b: dict,
    extras: dict,
    *,
    name_a: str | None = None,
    name_b: str | None = None,
    gender_a: ClientGender | None = None,
    teaser: str | None = None,
    teaser_contacts: dict | None = None,
) -> list[str]:
    """Данные пары для модели: синастрия calc, обе карты и extras (services/vip_pair.extras).

    Общие для черновика и правки (vip_pair_edit). Тип связи — всегда романтика.
    gender_a — род обращения к заказчику; None у заказов до вопроса о роде в
    боте. teaser — текст бесплатного тизера, если клиент пришёл через него.
    """
    label_a = (name_a or "").strip() or "ты"
    label_b = (name_b or "").strip() or "партнёр"
    known = {"A": calc["meta"]["a"]["time_known"], "B": calc["meta"]["b"]["time_known"]}
    unsure = {side for side, ok in known.items() if not ok}

    lines = [
        f"Сегодня: {_day(extras['today'])}.",
        "Сторона A — заказчик разбора. Обращайся к ней только на «ты»."
        + (f" По имени — «{label_a}», изредка." if (name_a or "").strip() else " По имени не называй."),
        f"Сторона B: {label_b} — о ней пиши по имени, в третьем лице."
        if (name_b or "").strip()
        # Пол безымянного партнёра неизвестен: на приёмке Opus писал «он», «его».
        else "Сторона B — партнёр, имени и пола мы не знаем: пиши «твой партнёр», «партнёра», "
        "«партнёру» и обходись без слов «он», «она», «его», «её».",
        "Тип связи: романтические отношения или брак.",
        _GENDER_LINES.get(gender_a, _NO_GENDER_LINE),
        f"Разница возрастов: {calc['summary']['age_gap_years']} года.",
    ]

    for side, label, natal in (("A", label_a, natal_a), ("B", label_b, natal_b)):
        lines += ["", f"# Карта стороны {side} ({label})"]
        lines += vip_natal.chart_block(
            natal, None, time_known=known[side], no_time_note=_NO_TIME_NOTE
        )
        moon = extras[side.lower()]["moon"]
        if moon is not None:
            lines.append(_moon_line(side, moon))

    lines += ["", "# Контакты между картами (все, от сильных к слабым)"]
    lines += [_contact_line(a, unsure) for a in calc["aspects"]]
    reciprocal = calc["summary"]["reciprocal"]
    if reciprocal:
        lines.append("Контакты, которые есть в обе стороны:")
        # Обе стороны выписаны целиком: «Меркурий A к Луна B» модель читает как опечатку.
        lines += [
            f"- {r['points_ru'][0]} A — {r['points_ru'][1]} B, "
            f"и одновременно {r['points_ru'][1]} A — {r['points_ru'][0]} B"
            for r in reciprocal
        ]

    for host, guest in (("A", "B"), ("B", "A")):
        overlay = extras[host.lower()]["overlay"]
        lines += ["", f"# Планеты {guest} в домах {host}"]
        if overlay is None:
            lines.append(f"- домов у стороны {host} нет: время рождения неизвестно")
        else:
            lines += [f"- {p['name_ru']} {guest} — {p['house']} дом {host}" for p in overlay]

    lines += ["", "# Транзиты медленных планет (соединения, оппозиции, квадраты; даты точного аспекта)"]
    for side in ("A", "B"):
        extra = extras[side.lower()]
        if extra["sky"] is not None:
            lines.append(
                f"Сегодня в домах {side}: "
                + "; ".join(f"{s['body_ru']} — {s['sign_ru']}, {s['house']} дом" for s in extra["sky"])
                + "."
            )
        lines.append(f"К карте {side}:")
        lines += _transit_lines(side, extra["transits"])

    if teaser and teaser.strip():
        lines += _teaser_block(teaser, teaser_contacts)
    return lines


def build_user(*args, **kwargs) -> str:
    """User-сообщение черновика: data_lines (те же аргументы) и просьба написать разбор."""
    lines = data_lines(*args, **kwargs)
    lines.append("")
    lines.append(
        "Напиши разбор этой пары по правилам из системного сообщения. "
        "Верни только JSON, без обёртки markdown."
    )
    return "\n".join(lines)


