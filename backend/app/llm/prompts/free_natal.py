"""Промпт бесплатного разбора натальной карты (тип отчёта free_natal).

Каждый модуль в llm/prompts/ — один тип отчёта и четыре экспорта:
- VERSION      — входит в ключ кеша отчётов (расчёт, тип, prompt_version):
                 любое изменение текста промпта = новая версия, иначе кеш
                 продолжит отдавать отчёты по старому промпту.
- SYSTEM       — роль и правила тона. Держим стабильным и общим для запросов:
                 контекстный кеш DeepSeek дешевле в ~10 раз именно на
                 совпадающем префиксе (см. Usage.cached_prompt_tokens).
- build_user() — данные конкретной карты: рендерит dict из compute_natal
                 в компактный текст. В LLM идёт не сырой JSON, а читаемые
                 строки: меньше токенов, меньше поводов у модели путаться
                 в ключах и градусах.
- parse()      — обратная сторона формата, заданного в SYSTEM: режет ответ
                 на секции по markdown-заголовкам. Зовётся из
                 services/reports.py.

Бесплатный разбор — тизер (v4): 120–180 слов, 2–3 попадания по карте, одно
слабое место названо без разбора, в конце два вопроса без ответа. Задача —
доказать, что расчёт настоящий, и оборвать текст на интересном месте.

Слов «полный разбор», цен и услуг в тексте нет: он один на веб, VK и бота, а
продаёт блок под ним (docs/astro-prompts-v2.md, раздел 8). Вопросы в конце
открытые — мостиком их делает интерфейс.
"""

from __future__ import annotations

import re

VERSION = "free_natal_v4"

# Явно, а не через DEFAULT_TEMPERATURE в client.py (1.0) — чтобы значение
# было видно рядом с промптом и не завязано на дефолт, общий с другими типами.
TEMPERATURE = 0.8

# 180 слов по-русски — около 450 токенов; запас двойной, потому что обрезанный
# по потолку ответ client.py считает ошибкой, а не коротким текстом.
MAX_TOKENS = 1000

# Требования CLAUDE.md к тону зашиты правилами: развлекательно-рефлексивный
# стиль, никакой медицины и фатальных предсказаний — это условие прохождения
# модерации каталога VK, а не пожелание.
SYSTEM = """Ты — тёплый и наблюдательный астролог, который пишет короткие разборы натальных карт для русскоязычной аудитории.

Стиль: развлекательно-рефлексивный. Пиши живо, на «ты», без канцелярита и эзотерического жаргона. Термин (знак, дом, аспект) называй один раз и сразу переводи на язык поведения. Орбы и градусы не называй, пиши «ретроградный», а не «ретро». Обращайся к читателю только на «ты», никогда в третьем лице («человек», «он»). Пол читателя неизвестен: вместо слов с родом («склонен», «привык») пиши «тебе свойственно», «у тебя». Читатель должен узнать себя, а не прочитать лекцию.

Задача текста — доказать, что расчёт сделан по этой карте, а не по знаку зодиака, и остановиться на самом интересном месте. Это короткий тизер, а не портрет: всю карту не пересказывай, Солнце, Луну и асцендент по очереди не описывай.

Жёсткие правила:
- Никаких медицинских тем: не упоминай болезни, диагнозы, здоровье, беременность.
- Никаких фатальных предсказаний: не предсказывай смерть, несчастья, разводы, потери. Не пиши «тебя ждёт», «тебе суждено» — только про склонности.
- Никаких финансовых обещаний и советов по инвестициям.
- Не давай оценок «хорошая/плохая карта».
- Опирайся только на данные карты из сообщения пользователя. Ничего не выдумывай сверх них; если чего-то в данных нет — не упоминай.
- Не упоминай другие разборы, услуги, покупки, подписки и цены. Не пиши, что в карте «видно гораздо больше».

Формат ответа — Markdown на русском, ровно один заголовок:
## Заголовок-крючок (образный, про суть этого человека, без слова «разбор»)
Затем три части без подзаголовков, каждая с новой строки. Всего под заголовком один абзац попаданий, одно предложение слабого места и две строки вопросов — других абзацев нет.

1. Попадания — один абзац. Выбери две-три самые выраженные конфигурации карты: самый тесный аспект, планету в доме, скопление планет в одном знаке. По каждой скажи одну конкретную вещь о том, как человек себя ведёт, — такую, которую нельзя сказать о любом человеке с тем же знаком Солнца. Каждое попадание привязано к названной конфигурации. Одно точное наблюдение сильнее трёх общих.

2. Слабое место — одно предложение отдельным абзацем. Назови одну уязвимость характера и обязательно — конфигурацию карты, из которой она следует. Бери её из напряжённого аспекта (квадрат, оппозиция), а если таких в данных нет — из положения планеты в знаке. Не объясняй, откуда она берётся, не смягчай, не превращай в «ресурс» и не давай совета. Назвал — и остановился. Слабое место — черта поведения или внутреннее противоречие, а не здоровье, деньги или судьба.

3. Два вопроса — каждый отдельной строкой, каждый заканчивается знаком «?». Это вопросы, которые эта карта ставит перед человеком и на которые текст выше не отвечает. Первый — именно про то слабое место, которое ты назвал во второй части, а не про другую черту. Второй — про сферу жизни, которой текст не коснулся, с опорой на конкретную планету или дом из данных. Вопросы личные и конкретные, не риторические. Ответов и подсказок не давай.

Вопросами текст заканчивается: после них ни строки — ни вывода, ни прощания, ни приглашения.

Объём всего ответа: 120–180 слов. Больше 180 — ошибка."""


def _dm(deg: float) -> str:
    """20.6874 → «20°41'» — так градусы пишут астрологи и astro-seek."""
    d = int(deg)
    m = round((deg - d) * 60)
    if m == 60:  # 29.9999 не должно превращаться в «29°60'»
        d, m = d + 1, 0
    return f"{d}°{m:02d}'"


def _planet_line(p: dict, with_house: bool = True) -> str:
    """«Солнце — Телец 20°41', 8 дом» (+ пометка ретроградности)."""
    parts = [f"{p['name_ru']} — {p['sign_ru']} {_dm(p['deg_in_sign'])}"]
    if with_house and p.get("house"):
        parts.append(f"{p['house']} дом")
    if p.get("retrograde"):
        parts.append("ретроградный")
    return ", ".join(parts)


# Тесный аспект (малый орб) ощущается сильнее широкого, поэтому сортируем
# по орбу и отдаём модели только верхушку. Шесть, а не десять (как было в v3):
# тизеру нужно 2–3 попадания, а лишние аспекты модель начинает перечислять.
_MAX_ASPECTS = 6

# Углы в списке аспектов compute_natal: без времени их аспекты посчитаны от
# подставленного полудня и так же выдуманы, как дома.
_ANGLES_RU = {"Асцендент", "Середина неба"}

# Строка вместо углов при неизвестном времени. Запрет назван прямо: без него
# модель дорисовывает асцендент и дома по знаку Солнца.
_NO_TIME_NOTE = (
    "Время рождения неизвестно: асцендента и домов в этой карте нет. "
    "Асцендент и дома не упоминай и отсутствие времени не оговаривай."
)


# Напоминания в хвосте user-сообщения: на живых прогонах v4 модель писала
# «понял», «готов» и задавала первый вопрос не про названное слабое место.
_REMINDERS = [
    "Проверь перед ответом:",
    (
        "- Пол читателя неизвестен. Про читателя нет ни одного слова в мужском "
        "или женском роде: ни глаголов прошедшего времени («понял», «устал»), ни "
        "кратких прилагательных («готов», «должен»), ни «сам». Пиши в настоящем "
        "времени или безлично: «ты понимаешь», «тебе трудно», «у тебя»."
    ),
    (
        "- Первый вопрос — про ту самую уязвимость, что названа в предложении "
        "о слабом месте, теми же словами о ней. Второй — про другую сферу жизни."
    ),
]


def build_user(natal: dict, name: str | None = None, *, time_known: bool = True) -> str:
    """Собирает user-сообщение из результата compute_natal.

    name — имя из профиля VK; с ним текст персональнее, без него разбор
    остаётся валидным. При time_known=False домов, углов и аспектов к углам
    в сообщении нет: compute_natal считает их от подставленного 12:00.
    """
    lines: list[str] = []
    if name:
        lines.append(f"Имя: {name}")

    lines.append("Планеты:")
    lines += [f"- {_planet_line(p, with_house=time_known)}" for p in natal["planets"]]

    if time_known:
        angles = natal["angles"]
        lines.append("Углы:")
        lines.append(f"- Асцендент — {angles['asc']['sign_ru']} {_dm(angles['asc']['deg_in_sign'])}")
        lines.append(f"- Середина неба — {angles['mc']['sign_ru']} {_dm(angles['mc']['deg_in_sign'])}")
    else:
        lines.append(_NO_TIME_NOTE)

    aspects = natal["aspects"]
    if not time_known:
        aspects = [a for a in aspects if not {a["p1_ru"], a["p2_ru"]} & _ANGLES_RU]
    aspects = sorted(aspects, key=lambda a: abs(a["orb"]))[:_MAX_ASPECTS]
    if aspects:
        lines.append("Самые тесные аспекты:")
        lines += [
            f"- {a['p1_ru']} {a['type_ru']} {a['p2_ru']} (орб {abs(a['orb']):.1f}°)"
            for a in aspects
        ]

    lines.append("")
    lines.append("Напиши бесплатный разбор этой натальной карты по правилам из системного сообщения.")
    # Эти два правила есть и в SYSTEM, но там модель их пропускает: строка
    # рядом с данными работает, общий запрет — нет (docs/astro-prompts-v2.md).
    lines += _REMINDERS
    return "\n".join(lines)


# Строка-заголовок markdown: решётки в начале, текст, иногда закрывающие
# решётки. Допускаем от одной до четырёх — в SYSTEM просим `##`, но модель
# временами сбивается на `#` или `###`, и показывать их читателю нельзя.
_HEADING = re.compile(r"^#{1,4}\s+(.+?)\s*#*$")


def parse(text: str) -> list[dict[str, str]] | None:
    """Ответ модели → список секций [{"title": ..., "body": ...}] или None.

    None означает «заголовков нет»: модель проигнорировала формат из SYSTEM.
    Это не исключение, а сигнал вызывающему показать текст как есть.

    У v4 секция одна: заголовок-крючок и весь текст под ним. Пустой title у
    первой секции возможен — так помечен текст, попавший выше заголовка
    (страница такую секцию рисует без подзаголовка).
    """
    sections: list[dict[str, str]] = []
    title = ""
    body: list[str] = []

    def flush() -> None:
        joined = "\n".join(body).strip()
        # Пустые куски отбрасываем: строка `## X` сразу за другим заголовком
        # дала бы секцию без текста, а вступление перед первым заголовком
        # модель обычно не пишет вовсе.
        if title or joined:
            sections.append({"title": title, "body": joined})

    for line in text.splitlines():
        match = _HEADING.match(line.strip())
        if match is None:
            body.append(line)
            continue
        flush()
        title = match.group(1)
        body = []

    flush()

    # Ни одного заголовка — разбирать было нечего, и отдать одну секцию с
    # тем же текстом значило бы соврать вызывающему, что формат соблюдён.
    if not any(s["title"] for s in sections):
        return None
    return sections
