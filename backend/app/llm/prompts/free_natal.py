"""Промпт бесплатного разбора натальной карты (тип отчёта free_natal).

Каждый модуль в llm/prompts/ — один тип отчёта и четыре экспорта:
- VERSION      — входит в ключ кеша отчётов (расчёт, тип, prompt_version):
                 любое изменение текста промпта = новая версия, иначе кеш
                 продолжит отдавать отчёты по старому промпту.
- SYSTEM       — роль и правила тона. Держим стабильным и общим для запросов:
                 контекстный кеш DeepSeek дешевле в ~10 раз именно на
                 совпадающем префиксе (см. Usage.cached_prompt_tokens).
- build_user() — данные конкретной карты: рендерит dict из compute_natal
                 в компактный текст. В LLM идёт не сырой JSON, а читаемые
                 строки: меньше токенов, меньше поводов у модели путаться
                 в ключах и градусах.
- parse()      — обратная сторона формата, заданного в SYSTEM: режет ответ
                 на секции по markdown-заголовкам. Зовётся из
                 services/reports.py.

Бесплатный разбор — приманка воронки: даёт настоящий, но короткий портрет
личности (Солнце/Луна/Асцендент + самые тесные аспекты). Темы
отношений/карьеры/кармы здесь не раскрываем — они за пейволлом.

Мостика к платному разбору в тексте нет (v3): текст один на веб и на VK, а
зовут под ним разные блоки — в вебе цена и кнопка, в VK подписка на
сообщество. Фраза «полный разбор раскроет подробнее» в VK превращалась в
обещание того, чего там нет вовсе (docs/astro-context.md).
"""

from __future__ import annotations

import re

VERSION = "free_natal_v3"

# Явно, а не через DEFAULT_TEMPERATURE в client.py (1.0) — чтобы значение
# было видно рядом с промптом и не завязано на дефолт, общий с другими типами.
TEMPERATURE = 0.8

# Требования CLAUDE.md к тону зашиты правилами: развлекательно-рефлексивный
# стиль, никакой медицины и фатальных предсказаний — это условие прохождения
# модерации каталога VK, а не пожелание.
SYSTEM = """Ты — тёплый и наблюдательный астролог, который пишет разборы натальных карт для русскоязычной аудитории.

Стиль: развлекательно-рефлексивный. Пиши живо, образно, на «ты», без канцелярита и без эзотерического жаргона сверх необходимого. Термины (знак, дом, аспект) поясняй мимоходом, по-человечески. Читатель должен узнавать себя и улыбаться, а не читать лекцию.

Жёсткие правила:
- Никаких медицинских тем: не упоминай болезни, диагнозы, здоровье, беременность.
- Никаких фатальных предсказаний: не предсказывай смерть, несчастья, разводы, потери. Не пиши «тебя ждёт», «тебе суждено» — только про склонности и потенциал.
- Никаких финансовых обещаний и советов по инвестициям.
- Не давай оценок «хорошая/плохая карта». Любую напряжённую конфигурацию подавай как ресурс и зону роста.
- Опирайся только на данные карты из сообщения пользователя. Ничего не выдумывай сверх них; если чего-то в данных нет — просто не упоминай.

Формат ответа — Markdown на русском:
## Заголовок-крючок (образный, про суть этого человека, без слова «разбор»)
Абзац-портрет: главное впечатление от карты, 3–4 предложения.
## Солнце: <знак>
## Луна: <знак>
## Асцендент: <знак>
По каждому — один плотный абзац: что это даёт характеру, как проявляется в жизни, с конкретикой из дома и аспектов, если они переданы.
## Что ещё видно в карте
2–3 самые яркие детали из аспектов или скоплений планет — по одному-два предложения на каждую.
Этой секцией текст и заканчивается. Не пиши финальных фраз про то, что «в карте видно гораздо больше», не упоминай другие разборы, услуги, покупки и подписки.

Объём всего ответа: 350–500 слов."""


def _dm(deg: float) -> str:
    """20.6874 → «20°41'» — так градусы пишут астрологи и astro-seek."""
    d = int(deg)
    m = round((deg - d) * 60)
    if m == 60:  # 29.9999 не должно превращаться в «29°60'»
        d, m = d + 1, 0
    return f"{d}°{m:02d}'"


def _planet_line(p: dict, with_house: bool = True) -> str:
    """«Солнце — Телец 20°41', 8 дом» (+ пометка ретроградности)."""
    parts = [f"{p['name_ru']} — {p['sign_ru']} {_dm(p['deg_in_sign'])}"]
    if with_house and p.get("house"):
        parts.append(f"{p['house']} дом")
    if p.get("retrograde"):
        parts.append("ретроградный")
    return ", ".join(parts)


# Тесный аспект (малый орб) ощущается сильнее широкого, поэтому сортируем
# по орбу и отдаём модели только верхушку: остальные — шум для короткого
# бесплатного текста.
_MAX_ASPECTS = 10

# Углы в списке аспектов compute_natal: без времени их аспекты посчитаны от
# подставленного полудня и так же выдуманы, как дома.
_ANGLES_RU = {"Асцендент", "Середина неба"}

# Строка вместо углов при неизвестном времени. SYSTEM требует раздел
# «Асцендент» всегда, поэтому отмена раздела названа прямо — править SYSTEM
# значит бампать VERSION и перегенерировать разборы карт со временем.
_NO_TIME_NOTE = (
    "Время рождения неизвестно: асцендента и домов в этой карте нет. "
    "Раздел «Асцендент» не пиши, дома не упоминай и отсутствие времени "
    "не оговаривай."
)


def build_user(natal: dict, name: str | None = None, *, time_known: bool = True) -> str:
    """Собирает user-сообщение из результата compute_natal.

    name — имя из профиля VK; с ним текст персональнее, без него разбор
    остаётся валидным. При time_known=False домов, углов и аспектов к углам
    в сообщении нет: compute_natal считает их от подставленного 12:00.
    """
    lines: list[str] = []
    if name:
        lines.append(f"Имя: {name}")

    lines.append("Планеты:")
    lines += [f"- {_planet_line(p, with_house=time_known)}" for p in natal["planets"]]

    if time_known:
        angles = natal["angles"]
        lines.append("Углы:")
        lines.append(f"- Асцендент — {angles['asc']['sign_ru']} {_dm(angles['asc']['deg_in_sign'])}")
        lines.append(f"- Середина неба — {angles['mc']['sign_ru']} {_dm(angles['mc']['deg_in_sign'])}")
    else:
        lines.append(_NO_TIME_NOTE)

    aspects = natal["aspects"]
    if not time_known:
        aspects = [a for a in aspects if not {a["p1_ru"], a["p2_ru"]} & _ANGLES_RU]
    aspects = sorted(aspects, key=lambda a: abs(a["orb"]))[:_MAX_ASPECTS]
    if aspects:
        lines.append("Самые тесные аспекты:")
        lines += [
            f"- {a['p1_ru']} {a['type_ru']} {a['p2_ru']} (орб {abs(a['orb']):.1f}°)"
            for a in aspects
        ]

    lines.append("")
    lines.append("Напиши бесплатный разбор этой натальной карты по правилам из системного сообщения.")
    return "\n".join(lines)


# Строка-заголовок markdown: решётки в начале, текст, иногда закрывающие
# решётки. Допускаем от одной до четырёх — в SYSTEM просим `##`, но модель
# временами сбивается на `#` или `###`, и показывать их читателю нельзя.
_HEADING = re.compile(r"^#{1,4}\s+(.+?)\s*#*$")


def parse(text: str) -> list[dict[str, str]] | None:
    """Ответ модели → список секций [{"title": ..., "body": ...}] или None.

    None означает «заголовков нет»: модель проигнорировала формат из SYSTEM.
    Это не исключение, а сигнал вызывающему показать текст как есть.

    Пустой title у первой секции возможен — так помечен текст, попавший
    выше первого заголовка (страница такую секцию рисует без подзаголовка).
    """
    sections: list[dict[str, str]] = []
    title = ""
    body: list[str] = []

    def flush() -> None:
        joined = "\n".join(body).strip()
        # Пустые куски отбрасываем: строка `## X` сразу за другим заголовком
        # дала бы секцию без текста, а вступление перед первым заголовком
        # модель обычно не пишет вовсе.
        if title or joined:
            sections.append({"title": title, "body": joined})

    for line in text.splitlines():
        match = _HEADING.match(line.strip())
        if match is None:
            body.append(line)
            continue
        flush()
        title = match.group(1)
        body = []

    flush()

    # Ни одного заголовка — разбирать было нечего, и отдать одну секцию с
    # тем же текстом значило бы соврать вызывающему, что формат соблюдён.
    if not any(s["title"] for s in sections):
        return None
    return sections
