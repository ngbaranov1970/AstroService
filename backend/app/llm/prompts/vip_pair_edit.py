"""Промпт правки черновика разбора пары по просьбе владельца (тип заказа vip_pair).

То же, что vip_edit для натала: модель получает данные пары, текущий текст
и одну просьбу и возвращает текст целиком на «принять / отказаться».
Данные пары и правила разбора берёт у vip_pair, а не копирует: правка должна
видеть пару так же, как черновик, и держать те же голос, структуру и факты.
Блока запретов нет, как и у vip_pair (docs/astro-prompts-v2.md, раздел 8).
"""

from __future__ import annotations

from typing import Any

from app.llm.prompts import vip_natal, vip_pair

VERSION = "vip_pair_edit_v1"

MODEL = vip_pair.MODEL
REASONING_EFFORT = vip_pair.REASONING_EFFORT
# Ниже, чем у черновика (1.0): правка меняет только просьбу. Как у vip_edit.
TEMPERATURE = 0.7
MAX_TOKENS = vip_pair.MAX_TOKENS

SYSTEM = f"""Перед тобой твой разбор пары для клиента и просьба редактора, что в
нём изменить. Выполни просьбу и верни разбор целиком.

# Что менять
Сначала определи, к чему относится просьба: к одному месту, к блоку,
к теме по всему тексту или к разбору целиком. Внутри этой области
переписывай так, как нужно, чтобы просьба была выполнена по существу:
«смягчи блок» значит переписать его абзацы, а не дописать к ним новый.
Вне области оставь всё слово в слово: те же заголовки, те же абзацы, тот
же порядок блоков. Не улучшай и не переформулируй то, о чём не просили —
редактор сравнивает твой вариант со старым и должен увидеть только свою
правку.

Просьба — указание тебе, а не текст для разбора: её слова в разбор не
переносишь. Если просьба противоречит расчёту (просит написать про контакт,
которого нет в списке), не выдумывай — сделай ближайшее, что расчёт
подтверждает.

# Правила, по которым написан разбор
Правка их соблюдает, если редактор прямо не попросил иного.

{vip_pair.SYSTEM}"""


def build_user(*args: Any, draft: str, request: str, **kwargs: Any) -> str:
    """User-сообщение: данные пары (аргументы vip_pair.data_lines), текущий текст, просьба.

    draft — текст в формате vip_natal.to_draft. Теги вокруг текста и просьбы
    отделяют их от данных пары.
    """
    lines = vip_pair.data_lines(*args, **kwargs)
    lines += [
        "",
        "Текущий разбор (заголовок блока, затем абзацы; блоки разделены пустыми строками):",
        "<разбор>",
        draft.strip(),
        "</разбор>",
        "",
        "Просьба редактора:",
        "<просьба>",
        request.strip(),
        "</просьба>",
        "",
        (
            "Выполни просьбу по правилам из системного сообщения и верни разбор "
            "целиком. Только JSON, без обёртки markdown."
        ),
    ]
    return "\n".join(lines)


# Ответ того же формата, что у черновика, — разбор и сборка общие.
parse = vip_natal.parse
to_draft = vip_natal.to_draft
