"""Промпт платного полного разбора натальной карты (тип отчёта full_natal).

Второе поколение промптов проекта (см. docs/astro-prompts-v2.md,
prompt_version: natal-ru-v2): в отличие от free_natal_v1 ставка не на
осторожность и мягкость тона, а на конкретность — модель обязана называть
элемент карты, из которого вырос каждый тезис, и не сглаживать противоречия.
free_natal_v1 при этом остаётся основным промптом бесплатного разбора,
этот файл его не меняет и не заменяет.

Экспорты — тот же контракт, что у free_natal.py:
- VERSION      — входит в ключ кеша отчётов (расчёт, тип, prompt_version).
- SYSTEM       — роль и правила тона, статичный текст (кешируется на
                 стороне DeepSeek по совпадающему префиксу).
- build_user() — рендерит dict из compute_natal в текст: сюда, в отличие
                 от free_natal, идёт вся карта (все дома, больше аспектов) —
                 платный разбор должен опираться на карту целиком.
- render()     — обратное преобразование: JSON-ответ модели → читаемый
                 текст. Нужно для терминала и вычитки промпта.

Ответ модели — JSON (не Markdown, см. формат в SYSTEM): секции портрета,
характера, отношений, карьеры, денег и точки роста, каждая со своим телом
текста. Формат обязателен продукту: пейволл открывает первую секцию и
закрывает остальные, а для этого их надо получить по отдельности — сплошной
текст так не разрезать.
"""

