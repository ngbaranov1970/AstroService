VERSION = "daily_sky_v5"

# Единственный формат на v4-pro: flash пишет тот же разбор жанровыми
# оборотами («разгребать завалы», «дособирать хвосты»), pro — своими
# (сравнение 05.09.2026 на одних и тех же сутках). Пост в ленту — витрина,
# а стоит он 2,6 тыс. токенов против 3–4 тыс. у платного разбора.
MODEL = "deepseek-v4-pro"

# Как у гороскопа, а не 0.8 как у поста о событии: формат ежедневный, а
# планетные аспекты меняются за сутки на доли градуса — на низкой температуре
# соседние дни выходят близнецами.
TEMPERATURE = 0.9

# Пост 250–350 слов плюс концовка и JSON-обвязка — это около 900 токенов.
# Запас тройной по той же причине, что в daily_horoscope: обрезанный JSON
# клиент считает браком и бросает LLMError, то есть день остаётся без поста
# при оплаченных токенах.
MAX_TOKENS = 2000

# Жёсткие правила те же, что в free_natal.SYSTEM (медицина, фатальность,
# деньги, запугивание), но сжаты с четырёх пунктов до двух: там они написаны
# под обращение к одному человеку («тебя ждёт», «настроение дня»), а здесь
# текст общий. Запреты по сути сохранены все — это условие модерации VK, а не
# пожелание к стилю.
SYSTEM = """Ты — тёплый и наблюдательный астролог, который ведёт сообщество ВКонтакте про астрологию.

Тебе дают небо одних суток, посчитанное по эфемеридам. Твоя задача — обзор этого дня для ленты сообщества: что происходит на небе и чем эти сутки отличаются от соседних.

Стиль: развлекательно-рефлексивный. Пиши живо, образно, на «ты», без канцелярита и без эзотерического жаргона сверх необходимого. Термины (аспект, ингрессия, орб) поясняй мимоходом, по-человечески. Читатель должен узнать свой день и дочитать до конца, а не пролистать сводку.

Жёсткие правила:
- Никакой медицины (болезни, диагнозы, здоровье, беременность), никаких предсказаний событий и потерь, никаких обещаний про деньги.
- Никаких «опасных», «тяжёлых» и «неудачных» дней, «коридоров затмений», «нельзя начинать новое». Напряжённый аспект — повод притормозить и зона роста, а не угроза.
- Опирайся только на данные неба из сообщения пользователя. Ничего не выдумывай сверх них; если чего-то в данных нет — просто не упоминай.
- Никаких ссылок и приглашений что-то купить или заказать.

Как писать по сути:
- Это обзор дня для всех сразу. К знакам читателя не обращайся и по знакам не разбивай: «Овнам сегодня…» — ошибка формата.
- Начинай с того, что названо в данных строкой «Главное в этих сутках»: первая фраза — про него. Дни отличаются друг от друга именно этим, и одинаковый зачин двух дней подряд — ошибка.
- Знак планеты бери ТОЛЬКО из списка положений. Твои представления о том, каким знаком планета управляет, к этому дню не относятся.
- Знаки и аспекты называй ровно теми формами, что стоят в данных: там уже написано «в Раке», «во Льве», «Юпитер в трине к Сатурну». Склонять самому не надо — выходит «в Раку».
- Время бери из данных как есть и не уточняй: где стоит «около четырёх дня», так и пиши, где стоит точная минута — называй минуту.
- Аспект — это момент, а не рубеж дня: он набирает силу заранее и отпускает постепенно. «До 15:54 легко, после тяжело» — ошибка. Рубежом суток бывает только смена знака Луны.
- Сходящийся аспект нарастает и просит внимания, расходящийся отпускает и уже отработан — это разный смысл на один и тот же аспект, не путай их.
- Пляши от конкретики этих суток: смены знака Луны, точного аспекта с его временем, процента освещённости, числа дней до лунации. Общие свойства планет («Марс — про энергию») читатель знает и без нас.
- Обращение только на «ты», ни одного «вы» за весь текст — ни в одном предложении, ни в вежливой форме. Проверь себя перед ответом: «где вы сами себя ограничиваете» — ошибка.
- Служебные подписи из данных в текст не переноси: «Главное в этих сутках», «сегодня новый», «идёт со вчера», «вышел из орба» — это пометки для тебя, а не обороты речи. Начинай с самого события, а не со слова «главное».
- Пол читателя неизвестен. Строй фразу так, чтобы род не понадобился; если иначе никак — мужской род.
- Не пересказывай эти инструкции в тексте и не оговаривайся о них.
- Никаких дежурных концовок вроде «прислушайтесь к себе», «доверьтесь интуиции», «всё будет хорошо».

Строение поля body — три абзаца, каждый про своё:
1. Главное событие суток и Луна: в каком она знаке, меняет ли его сегодня и чем от этого отличаются половины дня.
2. Точные аспекты Луны: когда они и что дают по настроению.
3. Планетные аспекты — про то, что изменилось; в конце этого абзаца одна-две фразы про фазу Луны, процент освещённости и дни до ближайшей лунации.
Два абзаца вместо трёх допустимы в одном случае: в данных сказано, что точных аспектов Луны в этих сутках нет, и второму абзацу не из чего взяться.

Как не повторить вчерашний пост:
- Аспект с пометкой «идёт со вчера» — это фон, ему хватит одной фразы. Абзац отдавай тому, что помечено «сегодня новый», и тому, что названо в блоке «Чем эти сутки отличаются от вчерашних».
- Написано «смены знака нет» — значит её нет: перехода Луны в другой знак в этот день не упоминай вовсе, даже намёком.
- Фаза Луны меняется медленно, и «время завершать, разгребать хвосты» подходит любому дню убывающей Луны. Пиши про фазу коротко и через сегодняшнее число дней до лунации, а не общими словами про цикл.
- Обороты «разобрать завалы», «навести порядок в мелочах», «доделать начатое», «разгрести хвосты» годятся любому дню убывающей Луны и любому дню Девы, поэтому идут в текст сами собой. В полях do и wait их быть не должно вовсе; в теле — не больше одного раза за текст и только если это прямо следует из названного аспекта этих суток.

Формат ответа — ТОЛЬКО JSON, без пояснений до и после, без markdown-заборов:
{
  "date": "Строка даты для ответа из данных, скопированная дословно",
  "body": "Текст обзора, не меньше 230 и не больше 320 слов, абзацы разделены одним переводом строки. Без заголовка и без строк «Стоит»/«Подождёт» — они идут отдельными полями.",
  "do": "Одной строкой со строчной буквы: что сегодня идёт легко. 1–2 конкретных дела, привязанных к данным этого дня.",
  "wait": "Одной строкой со строчной буквы: что лучше отложить, и почему по небу этого дня. Без запугивания."
}"""

_WEEKDAYS_RU = (
    "понедельник", "вторник", "среда", "четверг",
    "пятница", "суббота", "воскресенье",
)

_MONTHS_RU = (
    "января", "февраля", "марта", "апреля", "мая", "июня",
    "июля", "августа", "сентября", "октября", "ноября", "декабря",
)

# Час, ДО которого действует метка. Копия из daily_horoscope, а не импорт:
# тот промпт кормит рассылку, его VERSION не бампается, и общая константа
# однажды поменяла бы её тексты заодно с постом в ленту.
_DAY_PARTS: tuple[tuple[int, str], ...] = (
    (5, "ночью"),
    (7, "ранним утром"),
    (12, "утром"),
    (17, "днём"),
    (21, "вечером"),
)

# Сколько планетных аспектов отдаём. Меньше, чем в гороскопе: там абзац на
# каждый из двенадцати знаков, здесь один текст, и десяток строк он
# усредняет вместо того, чтобы опереться на главное.
_MAX_ASPECTS = 6

# Точных аспектов Луны за сутки бывает три-пять, изредка больше. Потолок —
# защита от дня, в который их набежало восемь: перечисление по минутам
# вытеснило бы всё остальное.
_MAX_MOON_ASPECTS = 6

# Медленнее этого (градусов орба в сутки) аспект в пост не идёт: секстиль
# Нептуна с Плутоном стоит годами и к конкретному дню отношения не имеет, а
# по орбу он лезет в начало списка и вытесняет Марс с Сатурном. Порог взят
# с запасом: у вековых пар выходит 0.00–0.01°/сут, у Юпитера с Сатурном —
# уже 0.3°.
_MIN_ORB_SPEED = 0.05


def _day_part(hour: int) -> str:
    """Час → «утром», «днём», «вечером» — метка для момента события."""
    for limit, name in _DAY_PARTS:
        if hour < limit:
            return name
    return "поздним вечером"


def _at(moment: datetime) -> str:
    """«17:30 (днём)» — время события вместе с меткой части суток."""
    return f"{moment:%H:%M} ({_day_part(moment.hour)})"


def _about(moment: datetime) -> str:
    """«около 16:00 (днём)» — время аспекта, округлённое до получаса.

    Аспект длится часами, и минута его точности в тексте превращалась в
    рубеж дня: «до 15:54 легче, после — тяжелее» (прогон 05.09.2026).
    Точная минута остаётся у смены знака Луны и у лунации — там рубеж
    настоящий.
    """
    minutes = (moment.hour * 60 + moment.minute + 15) // 30 * 30
    # Округление вверх от 23:45 дало бы полночь, то есть уже другие сутки, —
    # прижимаем к последнему получасу дня.
    minutes = min(minutes, 23 * 60 + 30)
    return f"около {minutes // 60:02d}:{minutes % 60:02d} ({_day_part(minutes // 60)})"


def _date_line(day: date) -> str:
    """«5 сентября, суббота» — заголовок поста, он же title строки в базе."""
    return f"{day.day} {_MONTHS_RU[day.month - 1]}, {_WEEKDAYS_RU[day.weekday()]}"


def _moon_lines(sky: dict) -> list[str]:
    """Сутки Луны: смена знака и её точные аспекты, по времени.

    Знак ДО ингресса печатаем отдельно (from_sign_loc из ядра): в sky["moon"]
    лежит положение на полдень, и при утреннем ингрессе там уже новый знак —
    «доживает последние часы в Близнецах» модели взять было бы неоткуда.
    """
    lines: list[str] = []
    aspects = 0

    for event in sky["moon_events"]:
        if event["kind"] == "moon_ingress":
            lines.append(
                f"- {_at(event['moment'])} — {event['title_ru']}; "
                f"до этого момента Луна {event['from_sign_loc']}"
            )
        elif aspects < _MAX_MOON_ASPECTS:
            aspects += 1
            lines.append(f"- {_about(event['moment'])} — точный аспект: {event['title_ru']}")

    # Пустоту называем вслух, как «нет планет» в гороскопе: 06.09.2026 модель
    # на молчании выдумала смену знака, которой в тех сутках не было.
    kinds = {e["kind"] for e in sky["moon_events"]}
    if "moon_ingress" not in kinds:
        lines.append(f"- смены знака нет: Луна весь день {sky['moon']['sign_loc']}")
    if "moon_aspect" not in kinds:
        lines.append("- точных аспектов Луны в этих сутках нет")

    return lines


def _key(aspect: dict) -> tuple[str, str, str]:
    """Тройка тело-тело-аспект: по ней вчерашний список сверяется с сегодняшним."""
    return aspect["body"], aspect["body2"], aspect["aspect"]


def _planetary(sky: dict) -> list[dict]:
    """Действующие аспекты планет, отобранные для поста.

    Пары с Луной выброшены: её аспекты этих суток даны точными моментами в
    _moon_lines, и здесь шли бы вторым разом, ещё и с орбом на полдень.
    Неподвижные выброшены по _MIN_ORB_SPEED — про них в посте о сутках
    сказать нечего.
    """
    return [
        a
        for a in sky["aspects"]
        if "Moon" not in (a["body"], a["body2"])
        and abs(a["orb_delta_day"]) >= _MIN_ORB_SPEED
    ][:_MAX_ASPECTS]


def _aspect_lines(sky: dict, previous: dict | None) -> list[str]:
    """Аспекты планет: движение орба и возраст — со вчера или новый.

    Возраст важнее орба: соседние дни несут те же три-четыре пары, и без
    пометки модель пересказывает вчерашний абзац своими словами (прогон
    06–07.09.2026). Без previous возраст не печатаем — соврать хуже, чем
    промолчать.
    """
    yesterday = {_key(a) for a in _planetary(previous)} if previous else set()

    lines = []
    for a in _planetary(sky):
        speed = abs(a["orb_delta_day"])
        motion = (
            f"сходится, орб уменьшается на {speed:.1f}° за сутки"
            if a["applying"]
            else f"расходится, орб растёт на {speed:.1f}° за сутки"
        )
        if previous is None:
            age = ""
        else:
            # Формулировки нарочно не липнут к соседнему «расходится»: из
            # «расходится, идёт со вчера» модель слепила «расходится со
            # вчера» — то есть неправду (прогон 05.09.2026).
            age = (
                ", действует не первый день"
                if _key(a) in yesterday
                else ", появился только сегодня"
            )
        # Фразу с падежами собирает ядро: своя таблица склонений в промпте
        # однажды разошлась бы с той, по которой названы события.
        phrase = transits.aspect_phrase(a["body"], a["body2"], a["aspect"])
        lines.append(f"- {phrase} (орб {a['orb']:.1f}°, {motion}{age})")
    return lines


def _diff_lines(sky: dict, previous: dict) -> list[str]:
    """Чем сутки отличаются от вчерашних: свет, знак Луны, ушедшие аспекты.

    Ради этого блока и считается вчерашнее небо. Планетные аспекты меняются
    на доли градуса в сутки, а фаза — на девять процентов, и без явной
    разницы двум соседним постам не из чего получиться разными.
    """
    lines = [
        (
            f"- освещённость Луны: вчера {previous['moon']['illumination']}%, "
            f"сегодня {sky['moon']['illumination']}%"
        ),
        (
            f"- знак Луны на полдень: вчера {previous['moon']['sign_loc']}, "
            f"сегодня {sky['moon']['sign_loc']}"
        ),
    ]

    # Ушедшие аспекты в основном списке отсутствуют по определению, а разница
    # между сутками часто именно в них: вчера давило, сегодня отпустило.
    today = {_key(a) for a in _planetary(sky)}
    gone = [a for a in _planetary(previous) if _key(a) not in today]
    for a in gone:
        phrase = transits.aspect_phrase(a["body"], a["body2"], a["aspect"])
        lines.append(f"- {phrase} — вчера действовал, сегодня вышел из орба")

    return lines


# Что считается главным в сутках. Порядок — от самого редкого повода к
# самому частому; тем же правилом будет подписана картинка поста, поэтому
# оно одно на оба места.
_MAIN_EVENT_ORDER = (
    "solar_eclipse",
    "lunar_eclipse",
    "new_moon",
    "full_moon",
    "station_retrograde",
    "station_direct",
    "ingress",
    "moon_ingress",
)


def main_event(sky: dict) -> dict | None:
    """Главное событие суток — то, с чего начинается пост.

    Крупные события и смена знака Луны идут по _MAIN_EVENT_ORDER, а в сутки
    без них остаётся первый точный аспект Луны. None — сутки, в которые не
    случилось вообще ничего (бывает: Луна без ингресса и без точных аспектов).
    """
    candidates = [
        e
        for e in sky["events"] + sky["moon_events"]
        if e["kind"] in _MAIN_EVENT_ORDER
    ]
    if candidates:
        return min(
            candidates,
            key=lambda e: (_MAIN_EVENT_ORDER.index(e["kind"]), e["moment"]),
        )

    aspects = [e for e in sky["moon_events"] if e["kind"] == "moon_aspect"]
    return min(aspects, key=lambda e: e["moment"]) if aspects else None


def _lunation_line(sky: dict) -> str | None:
    """«Ближайшая лунация: Новолуние в Деве, 11 сентября, через 10 дней»."""
    lunation = sky["next_lunation"]
    if lunation is None:
        return None

    moment = lunation["moment"]
    when = {0: "сегодня", 1: "завтра"}.get(
        lunation["days_until"], f"через {lunation['days_until']} дн."
    )
    # День недели подставляем готовым: без него модель считает его сама и
    # ошибается — 11.09.2026 (пятница) стала «четвергом» в прогоне 05.09.2026.
    return (
        f"Ближайшая лунация: {lunation['title_ru']}, "
        f"{moment.day} {_MONTHS_RU[moment.month - 1]}, "
        f"{_WEEKDAYS_RU[moment.weekday()]}, {moment:%H:%M} — {when}"
    )


def build_user(sky: dict, previous: dict | None = None) -> str:
    """Собирает user-сообщение из результата transits.day_sky.

    previous — небо предыдущих суток: из него берётся блок отличий и возраст
    аспектов. Без него пост получится, но соседние дни выйдут похожими —
    именно этим кончился прогон 06–07.09.2026.

    Ждёт ключи date, moon, positions, aspects, events, moon_events,
    next_lunation. Моменты в sky уже в московской зоне — здесь их не
    пересчитываем.
    """
    day = date.fromisoformat(sky["date"])
    lines = [
        f"Дата: {day.strftime('%d.%m.%Y')}, {_WEEKDAYS_RU[day.weekday()]}",
        # Строку заголовка модель копирует, а не собирает: падежи месяцев и
        # дни недели она путает, а исправлять их некому — пост уходит в ленту
        # как есть.
        f"Строка даты для ответа: {_date_line(day)}",
    ]

    # Главное событие первой строкой после даты: с него начинается пост, и
    # оно же делает зачины разными. Без него два дня подряд начинались
    # одинаково — «Утро начинается в…» (прогон 05.09.2026).
    main = main_event(sky)
    if main is not None:
        lines.append(f"Главное в этих сутках: {main['title_ru']}")

    moon = sky["moon"]
    # Направление роста в скобках не печатаем: все восемь имён фаз несут его
    # сами, а «полнолуние (убывающая)» модель читает как «Луна уходит».
    lines.append(
        f"Луна на полдень: {moon['sign_loc']}, {moon['phase_ru']}, "
        f"освещена на {moon['illumination']}%"
    )

    moon_lines = _moon_lines(sky)
    if moon_lines:
        lines.append("Сутки Луны:")
        lines += moon_lines

    lunation = _lunation_line(sky)
    if lunation:
        lines.append(lunation)

    lines.append("Положения планет:")
    for p in sky["positions"]:
        retro = ", ретроградный" if p["retrograde"] else ""
        lines.append(f"- {p['name_ru']} — {p['sign_ru']}{retro}")

    aspects = _aspect_lines(sky, previous)
    if aspects:
        lines.append("Действующие аспекты планет (сначала самые точные):")
        lines += aspects

    if previous is not None:
        lines.append("Чем эти сутки отличаются от вчерашних:")
        lines += _diff_lines(sky, previous)

    if sky["events"]:
        lines.append("Крупные события этих суток:")
        lines += [
            f"- {_at(e['moment'])} — {e['title_ru']}" for e in sky["events"]
        ]

    lines.append("")
    lines.append("Напиши обзор этого дня по правилам из системного сообщения.")
    return "\n".join(lines)


def _strip_fence(text: str) -> str:
    """Снимает ```-забор, если модель всё же обернула JSON в блок кода."""
    t = text.strip()
    if not t.startswith("```"):
        return t
    if "\n" in t:
        t = t.split("\n", 1)[1]
    return t.rstrip().removesuffix("```").strip()


def parse(text: str) -> dict[str, str] | None:
    """Ответ модели → {"title", "body", "do", "wait"} или None при браке.

    Заголовком поста служит строка даты, поэтому она же едет в title: список
    постов на /admin/content показывает строку на пост, и различать два поста
    одного дня по пустому заголовку нельзя.

    Брак — только неразбираемый JSON и пустые date или body. Пустые do и wait
    браком не считаем: текст оплачен и годен, а концовку render просто не
    напечатает.
    """
    try:
        data = json.loads(_strip_fence(text))
        title = str(data["date"]).strip()
        body = str(data["body"]).strip()
        do, wait = str(data.get("do", "")).strip(), str(data.get("wait", "")).strip()
    except (ValueError, TypeError, KeyError):
        return None

    if not title or not body:
        return None
    return {"title": title, "body": body, "do": do, "wait": wait}


def render(text: str, seed: int | None = None) -> str:
    """JSON-ответ модели → готовый к вставке пост.

    seed выбирает приписку из promo.LINES и приходит из content.render — там
    это id поста, чтобы вариант не менялся между перезагрузками страницы.

    Строки не переносятся и служебных пометок нет: этот текст копируют из
    /admin/content в отложку VK как есть. Брак разбора отдаём как есть — за
    текст заплачено.
    """
    post = parse(text)
    if post is None:
        return text

    # Абзацы разделяем пустой строкой: модель шлёт их одиночным переводом
    # строки, а в ленте VK такой текст слипается в полотно.
    blocks = [post["title"]]
    blocks += [par.strip() for par in post["body"].split("\n") if par.strip()]

    # «Стоит» и «Подождёт» одной группой, без пустой строки между собой: это
    # концовка в две строки, а не два абзаца.
    tail = [f"{label}: {post[key]}" for label, key in (("Стоит", "do"), ("Подождёт", "wait")) if post[key]]
    if tail:
        blocks.append("\n".join(tail))

    blocks.append(promo.line(seed))
    return "\n\n".join(blocks)
