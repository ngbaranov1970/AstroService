"""Промпт обзора неба дня (тип поста daily_sky).

Экспорты те же, что у остальных модулей llm/prompts/: VERSION (в ключ кеша),
SYSTEM (роль и тон), build_user() (данные суток), parse() и render(). Вход
build_user — результат astro_core.transits.day_sky.

Единственный пост в ленту сообщества: небо суток одним текстом, без деления
по знакам. Двенадцатизнаковый daily_horoscope с 05.09.2026 идёт только в
рассылку (docs/astro-context.md, «Контур сообщества VK»).

Ответ — JSON, а не сплошной текст: концовка «Стоит / Подождёт» обязана
стоять на своём месте каждый день, а внутри свободного текста модель её
растворяет в очередном абзаце.
"""

from __future__ import annotations

import json
from datetime import date, datetime

from app.llm.prompts import promo
