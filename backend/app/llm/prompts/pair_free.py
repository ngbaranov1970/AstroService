"""Промпт бесплатного тизера совместимости (тип отчёта pair_free).

Контракт тот же, что у free_natal.py (VERSION, SYSTEM, build_user, parse), но
вход другой: не одна карта, а результат compute_synastry — аспекты между двумя
картами и производные признаки пары. Зовёт модуль только
services/reports.py, форма вызова объявлена там же в _user_message().

Тизер — вход в воронку и единственный парный текст, который увидит партнёр,
пришедший по ссылке-приглашению. Мостика к платному разбору в нём нет: текст
один на веб и на VK, а в VK продавать нельзя (та же причина, что у
free_natal_v3).

Домов в данных нет вовсе, и в SYSTEM это сказано прямым текстом: наложение
домов мы не считаем, а без запрета модель его дорисует. Остальные правила
синастрии — в docs/compatibility-plan.md, раздел «Промпты».
"""

from __future__ import annotations

import re

VERSION = "pair_free_v1"

# Как у free_natal: значение видно рядом с промптом и не завязано на общий
# дефолт client.py (1.0), калиброванный под другой тип текста.
TEMPERATURE = 0.8

# 400 слов по-русски — примерно 950 токенов; остальное запас на заголовки.
MAX_TOKENS = 1400

# Сколько контактов уходит в тизер. Пара даёт 21-43 аспекта, в summary["top"]
# лежат 12 сильнейших — для трёх абзацев и это перечисление (docs/progress.md,
# «Правило для промптов»: данные сильнее правил и во вред тоже).
TOP_ASPECTS = 6

# Точки, чьи знаки идут в промпт, и порядок их вывода. Кортеж, а не
# PLANETS_RU из astro_core: словарь порядка не задаёт, а знаки светил с Венерой
# и Марсом читаются как «визитка» стороны только в привычной очерёдности.
_SIGN_POINTS = (
    ("Sun", "Солнце"),
    ("Moon", "Луна"),
    ("Venus", "Венера"),
    ("Mars", "Марс"),
)

# Две формы на каждую стихию: «преобладает земля», «воздуха нет вовсе».
# Склонять в коде нечем, а кривой падеж в промпте модель повторяет за нами.
_ELEMENTS_RU = {
    "fire": ("огонь", "огня"),
    "earth": ("земля", "земли"),
    "air": ("воздух", "воздуха"),
    "water": ("вода", "воды"),
}

# Сколько планет из десяти делают стихию преобладающей.
_DIST_STRONG = 4

# Во сколько раз вес вовлечённости одной стороны должен превзойти другую,
# чтобы это стоило называть перекосом.
_INVOLVE_GAP = 1.25

# Тип связи и рамка к нему. Рамка едет в user-сообщении вместе с данными, а не
# запретом в SYSTEM: проверено шестью поколениями промпта гороскопа — общий
# запрет модель нарушает, конкретная строка про этот случай работает.
_KIND_FRAME = {
    "romance": (
        "романтические отношения или брак. Уместны влечение, ревность, "
        "нежность, быт вдвоём, планы на общую жизнь."
    ),
    "family": (
        "близкие родственники (например, мать и ребёнок, брат и сестра). "
        "Про влечение, романтику, секс и расставание не пиши вовсе — пиши про "
        "привязанность, обязательства, границы и то, как они друг друга растят."
    ),
}

SYSTEM = """Ты — тёплый и наблюдательный астролог, который пишет разборы совместимости для русскоязычной аудитории.

# Вход
Ты получишь расчёт синастрии — контактов между двумя натальными картами. Стороны помечены буквами A и B, рядом даны их имена. Сторона A — тот, для кого разбор. Расчёт уже сделан: не пересчитывай, не сомневайся в данных, не проси уточнений.

Домов в данных нет. Не упоминай дома, наложение домов и композит — мы их не считали, и фраза вроде «его Марс в твоём седьмом доме» будет выдумкой, которую читатель проверит на любом сайте за минуту.

Контакты бери только из переданного списка. Если между двумя планетами контакта в списке нет — его нет и в расчёте: общий знак или соседство аспектом не является.

# Как ты пишешь
Стиль: развлекательно-рефлексивный. Живо, образно, без канцелярита и эзотерического жаргона сверх необходимого. Термины (знак, аспект, соединение) поясняй мимоходом, по-человечески.

К стороне A обращайся на «ты». Сторону B называй по имени, в третьем лице.

Всегда говори, чья планета: «твоя Луна», «Венера Маши». Это единственное, что нельзя перепутать: контакт «его Сатурн к её Луне» и обратный — разные сюжеты.

«Вы» в тексте — это вы двое. К стороне A обращайся только на «ты»: вежливого «Вы» в разборе нет нигде.

Не называй градусы и орбы: числа расчёта в текст не идут.

Числа расчёта служебные — счёт контактов, орбы, градусы. Делай из них вывод про поведение, но в текст не переноси: ни цифрами, ни оборотами «задействована», «не задействована», «участвует в контактах».

Род сторон определяй по именам. Если имя рода не выдаёт, строй фразы так, чтобы род не понадобился: перепутанный род читатель замечает в первой строке.

ГЛАВНОЕ ПРАВИЛО. Каждое утверждение должно быть ложным для большинства пар. Прежде чем оставить фразу, проверь: подошла бы она случайной паре с улицы? Если да — вычеркни и напиши то, что следует именно из этих контактов.

Так писать нельзя, это «вода»:
- «Между вами сильное притяжение, но есть и напряжение»
- «Вам важно научиться слышать друг друга»
- «У вас глубокая связь, которая требует работы»
- «Вы очень разные, и в этом ваша сила»
- «Ваша связь телесная, почти животная»
Образ и метафора допустимы, но сразу за ними идёт конкретное поведение, иначе это украшение пустоты.

ВИДНО ГЛАЗАМИ. В каждой секции хотя бы раз должно быть видно, кто что делает и говорит и в какой момент, — так, чтобы читатель представил это как кадр и узнал себя. Проверка та же: другой паре это не подошло бы. Бери из обычной жизни — деньги, переписка и молчание в ответ, сборы и опоздания, гости и родня, отпуск, ремонт, кто первым идёт мириться. Готовых примеров здесь нет намеренно: списанный кадр годится любой паре, а нужен этот. Вводных слов вроде «представь себе» и «вот пример» не пиши — просто рассказывай.

Пиши про поведение, а не про свойства. Не «между вами есть напряжение», а «ты рассказываешь о планах, а она в ответ считает, что может пойти не так, — и ты слышишь в этом отказ».

Не больше двух-трёх контактов на абзац. Список контактов — материал, а не план текста: перечисление аспектов читается как выписка из учебника.

# Жёсткие правила
- Никакого вердикта «подходите / не подходите». Никаких процентов совместимости, баллов, оценок и рейтингов пары.
- Не предсказывай расставание, свадьбу, детей, измену. Не пиши «вам суждено», «вы встретились не случайно», «вас связывает карма» и про прошлые жизни.
- Никаких медицинских тем: болезни, диагнозы, здоровье, беременность.
- Не оценивай пару как хорошую или плохую. Напряжённый контакт — это про то, где двое регулярно задевают друг друга, а не приговор и не «урок».
- Никаких финансовых обещаний и советов по вложениям.
- Опирайся только на данные из сообщения пользователя. Чего в них нет — не упоминай; отсутствие данных не оговаривай и не извиняйся за него.
- Про точность контакта не пиши нигде, включая заголовок: ни «орб 0.19°», ни «почти вплотную», ни «впритык», ни «очень тесно». Читателю это ничего не даёт, а «вплотную» он понимает как «планеты рядом» — и тип контакта в его голове подменяется.
- Слова из этой инструкции в тексте не употребляй: «сцена», «кадр», «контакт», «расчёт», «служебный», «данные». Читатель видит разбор, а не отчёт о том, как он собран.

# Формат ответа
Markdown на русском:
## Заголовок-крючок (образный, про эту пару; без слов «совместимость» и «разбор»)
Абзац: главное впечатление от пары, 3–4 предложения.
## Что между вами работает
Один плотный абзац: самое сильное в паре, с опорой на два-три контакта.
## Где вы задеваете друг друга
Один плотный абзац: где двое спотыкаются и как это выглядит в обычной жизни.
Этой секцией текст и заканчивается. Не пиши финальных фраз, не упоминай другие разборы, услуги, покупки и подписки.

Объём всего ответа: 300–400 слов."""


def _label(name: str | None, default: str) -> str:
    """Этикетка стороны для промпта: имя или заглушка.

    Имя может не прийти вовсе — person_name в форме необязателен. Пустую
    строку тоже считаем отсутствием: в базу она попадает из формы.
    """
    cleaned = (name or "").strip()
    return cleaned or default


def _signs_line(side: str, label: str, signs: dict[str, str]) -> str:
    """«A (Коля): Солнце — Телец, Луна — Рак, Венера — Овен, Марс — Лев».

    Знаки светил, Венеры и Марса — то, чем торгует ручной рынок ВК, и из
    списка контактов они не выводятся вовсе.
    """
    parts = [f"{ru} — {signs[key]}" for key, ru in _SIGN_POINTS if key in signs]
    return f"- {side} ({label}): " + ", ".join(parts)


def _elements_line(side: str, label: str, elements: dict[str, int]) -> str:
    """«- A (Коля): сильнее всего земля; воздуха нет вовсе».

    Словами, а не счётом планет: счёт модель переносит в текст дословно
    («пять планет в земле»), и абзац читается как выписка из таблицы.
    """
    strong = [ru for key, (ru, _) in _ELEMENTS_RU.items() if elements.get(key, 0) >= _DIST_STRONG]
    empty = [gen for key, (_, gen) in _ELEMENTS_RU.items() if elements.get(key, 0) == 0]

    parts = []
    if strong:
        parts.append("сильнее всего " + ", ".join(strong))
    if empty:
        parts.append(", ".join(empty) + " нет вовсе")
    if not parts:
        parts.append("распределение ровное, без перевеса")
    return f"- {side} ({label}): " + "; ".join(parts)


def _aspect_line(aspect: dict) -> str:
    """«- Венера A — трин — Марс B (орб 1.2°)».

    Буквы сторон стоят у каждой планеты, а не в шапке списка: шапку модель
    теряет к третьей строке, и стороны в тексте меняются местами.
    """
    return f"- {aspect['a_ru']} A — {aspect['type_ru']} — {aspect['b_ru']} B (орб {aspect['orb']}°)"


# Границы словесной оценки. Число в промпт не идёт намеренно: «гармоничных
# 62% по весу» модель превращает в процент совместимости, а он запрещён
# (docs/compatibility-plan.md, раздел «Промпты»).
#
# Пороги — квартили замера по всем 45 парам золотых карт (разброс 0.15–0.73,
# медиана 0.50): 13 пар попадают в «напряжённых больше», 10 в «гармоничных
# больше», 22 в середину. На круглых 0.35/0.65 в середину падало 39 из 45 —
# признак, одинаковый почти для всех, пары не различает.
_HARMONY_SOFT = 0.58
_HARMONY_HARD = 0.42


def _harmony_phrase(harmony: float | None) -> str | None:
    """Перевес гармоничных или напряжённых контактов словами.

    None на входе — в паре одни соединения, и окрашивать нечего (см.
    astro_core.synastry._harmony); тогда строки в промпте нет.
    """
    if harmony is None:
        return None
    if harmony >= _HARMONY_SOFT:
        return "гармоничных контактов заметно больше напряжённых"
    if harmony <= _HARMONY_HARD:
        return "напряжённых контактов заметно больше гармоничных"
    return "гармоничных и напряжённых контактов примерно поровну"


def _voids_line(side: str, label: str, voids: list[dict]) -> str:
    """Точки стороны, не получившие ни одного контакта.

    Отсутствия различают пары лучше присутствий, а сама модель их не заметит:
    она видит список того, что есть. Формулировка человеческая, без
    «задействована»: этот оборот модель переносит в текст дословно.
    """
    if not voids:
        return f"- {side} ({label}): таких нет, отзывается вся карта"
    return f"- {side} ({label}): " + ", ".join(v["point_ru"] for v in voids)


def _involvement_phrase(involvement: dict, label_a: str, label_b: str) -> str:
    """Перекос вовлечённости словами: чья карта включена в пару сильнее.

    Сравниваем вес затронутых точек, а не их счёт: восемь контактов к высшим
    планетам и восемь к светилам — разная вовлечённость. Числа в промпт не
    идут по той же причине, что и в _elements_line.
    """
    weight_a = involvement["a"]["touched_weight"]
    weight_b = involvement["b"]["touched_weight"]
    high, low = max(weight_a, weight_b), min(weight_a, weight_b)

    # Ноль возможен только у пары вовсе без контактов — там и перекоса нет.
    if low <= 0 or high / low < _INVOLVE_GAP:
        return "обе карты включены в пару примерно одинаково"
    leader, other = (label_a, label_b) if weight_a > weight_b else (label_b, label_a)
    return f"карта {leader} включена в пару заметно сильнее, чем карта {other}"


def _time_note(side: str, label: str, meta_side: dict) -> str | None:
    """Предупреждение про неизвестное время рождения, иначе None.

    Асцендент и MC такой стороны в расчёт не входят вовсе, и в списке
    контактов их нет. Без этой строки модель считает, что углы просто ни с чем
    не соединились, и пишет про «незадействованный Асцендент» — про точку,
    которой у нас нет.
    """
    if meta_side.get("time_known"):
        return None
    return (
        f"Время рождения стороны {side} ({label}) неизвестно: Асцендент и MC её карты "
        f"не считались и в контактах не участвуют. Не упоминай их и не оговаривай "
        f"отсутствие времени в тексте."
    )


def build_user(
    calc: dict,
    *,
    kind: str,
    name_a: str | None = None,
    name_b: str | None = None,
) -> str:
    """Собирает user-сообщение из расчёта пары (выход compute_synastry).

    kind — значение PairKind: он меняет текст и потому обязателен. Имена
    сторон идут в промпт как этикетки («твоя Луна» и «Венера Маши»); в логи
    они не попадают ни на одном слое.

    Незнакомый kind не роняет генерацию: рамка типа связи просто не
    подставляется, остальные правила остаются в силе.
    """
    summary = calc["summary"]
    label_a = _label(name_a, "ты")
    label_b = _label(name_b, "партнёр")

    # Указание о голосе стоит рядом с именем, а не только правилом в SYSTEM:
    # в приёмке v1 модель уходила в «рассказ о двоих» и переключалась на
    # вежливое «Вы», а строка при данных держит лучше.
    named_a = bool((name_a or "").strip())
    lines = [
        f"Сторона A: {label_a} — для него разбор."
        if named_a
        else "Сторона A — тот, для кого разбор, имени мы не знаем.",
        "Обращайся к стороне A только на «ты»: «ты», «тебе», «твой». В третьем лице о ней не пиши."
        + (f" По имени — «{label_a}», изредка." if named_a else " По имени не называй."),
        f"Сторона B: {label_b} — о ней пиши по имени, в третьем лице."
        if (name_b or "").strip()
        else "Сторона B — партнёр, имени мы не знаем: пиши «твой партнёр», в третьем лице.",
    ]

    frame = _KIND_FRAME.get(kind)
    if frame is not None:
        lines.append(f"Тип связи: {frame}")

    lines.append(f"Разница возрастов: {summary['age_gap_years']} года.")

    for side, label in (("A", label_a), ("B", label_b)):
        note = _time_note(side, label, calc["meta"][side.lower()])
        if note is not None:
            lines.append(note)

    lines.append("Знаки:")
    lines.append(_signs_line("A", label_a, summary["signs"]["a"]))
    lines.append(_signs_line("B", label_b, summary["signs"]["b"]))

    lines.append("Планет по стихиям:")
    lines.append(_elements_line("A", label_a, summary["elements"]["a"]))
    lines.append(_elements_line("B", label_b, summary["elements"]["b"]))

    top = summary["top"][:TOP_ASPECTS]
    if top:
        lines.append(f"Сильнейшие контакты между картами (всего их {len(calc['aspects'])}):")
        lines += [_aspect_line(a) for a in top]

    harmony = _harmony_phrase(summary["harmony"])
    if harmony is not None:
        lines.append(f"По всем контактам пары: {harmony}.")

    # Взаимность — свойство пары, а не аспекта: в учебниках её нет, и есть она
    # далеко не у всех. Один из главных различителей текста.
    reciprocal = summary["reciprocal"]
    if reciprocal:
        lines.append("Контакты, которые есть в обе стороны:")
        # Обе стороны выписаны целиком, без «и наоборот»: имена точек мы не
        # склоняем, а «Меркурий A к Луна B» модель читает как опечатку.
        lines += [
            f"- {r['points_ru'][0]} A — {r['points_ru'][1]} B, "
            f"и одновременно {r['points_ru'][1]} A — {r['points_ru'][0]} B"
            for r in reciprocal
        ]

    # Пометка «служебное» стоит рядом с данными, а не только правилом в SYSTEM:
    # в приёмке v1 модель цитировала эти числа в тексте («Венера не задействована»),
    # а запрет у самих данных работает лучше общего (docs/progress.md).
    lines.append("Планеты, которые в этой паре ни на что не отзываются:")
    lines.append(_voids_line("A", label_a, summary["voids"]["a"]))
    lines.append(_voids_line("B", label_b, summary["voids"]["b"]))

    lines.append(
        "Вовлечённость: " + _involvement_phrase(summary["involvement"], label_a, label_b) + "."
    )

    lines.append("")
    lines.append("Напиши короткий бесплатный разбор этой пары по правилам из системного сообщения.")
    return "\n".join(lines)


# Строка-заголовок markdown. Как в free_natal, допускаем от одной до четырёх
# решёток: в SYSTEM просим `##`, но модель временами сбивается, а показывать
# решётки читателю нельзя.
_HEADING = re.compile(r"^#{1,4}\s+(.+?)\s*#*$")


def parse(text: str) -> list[dict[str, str]] | None:
    """Ответ модели → список секций [{"title": ..., "body": ...}] или None.

    None означает «заголовков нет»: модель проигнорировала формат из SYSTEM.
    Это не исключение, а сигнал вызывающему показать текст как есть.

    Дублирует free_natal.parse: модули промптов намеренно самостоятельные, и
    общий хелпер связал бы два текста, которые правятся независимо.
    """
    sections: list[dict[str, str]] = []
    title = ""
    body: list[str] = []

    def flush() -> None:
        joined = "\n".join(body).strip()
        # Пустые куски отбрасываем: `## X` сразу за другим заголовком дал бы
        # секцию без текста.
        if title or joined:
            sections.append({"title": title, "body": joined})

    for line in text.splitlines():
        match = _HEADING.match(line.strip())
        if match is None:
            body.append(line)
            continue
        flush()
        title = match.group(1)
        body = []

    flush()

    if not any(s["title"] for s in sections):
        return None
    return sections
