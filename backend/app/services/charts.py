"""Карты: поиск города, расчёт, сохранение в базу.

Это продуктовая склейка. Расчётное ядро (astro_core) не знает ни про базу,
ни про пользователей — оно умеет «дата + координаты → словарь». Модели
(app/models.py) не знают, как этот словарь получить. Здесь эти две половины
соединяются и получается операция «человек ввёл данные рождения — в базе
появилась его карта».

Про Telegram, VK и HTTP в этом файле нет ни слова, и это не случайность,
а граница из CLAUDE.md: одни и те же функции вызывают и бот, и веб-стенд,
и будущий Mini App. Всё, что знает про кнопки и формы, живёт снаружи.

Две вещи, ради которых стоит читать дальше.

ПОЧЕМУ ПОИСК ГОРОДА И СОЗДАНИЕ КАРТЫ — ДВА ОТДЕЛЬНЫХ ВЫЗОВА

Соблазнительно написать одну функцию «дата + строка "Ростов" → карта».
Так нельзя: Ростовов два (Ростов-на-Дону и Ростов Великий), Ивановок —
десятки. Выбирает всегда человек, а между поиском и расчётом обязан
поместиться экран со списком. Поэтому search_places() отдаёт варианты,
а create_chart() принимает уже выбранные координаты.

ПОЧЕМУ INPUT_HASH, А НЕ СРАВНЕНИЕ ПОЛЕЙ

«Посчитай ещё раз» не должно плодить копии карты: за каждой копией
потянутся свои отчёты, то есть лишние деньги за DeepSeek. Дубль ловится
уникальной парой (user_id, input_hash) в базе — то есть физически, а не
«мы вроде проверили перед вставкой». Сравнивать вместо хеша пять колонок,
две из которых числа с плавающей точкой, — путь к тому, что 55.5 и
55.50000000000001 окажутся разными городами.
"""

from __future__ import annotations

import asyncio
import hashlib
from dataclasses import dataclass
from datetime import datetime, time
from importlib.metadata import version

from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncSession

from app.models import Chart
from astro_core.geo import City, search_cities, tz_at
from astro_core.natal import compute_natal

# Версия расчётного ядра — пишется в каждую карту (Chart.calc_version).
#
# Зачем: обновили kerykeion или pyswisseph — цифры могут сдвинуться на доли
# минуты дуги. По этому полю потом видно, какие карты чем посчитаны, и можно
# пересчитать только старые, не трогая свежие.
#
# Версии берём у самих пакетов, а не пишем руками: рукописную константу
# гарантированно забудут обновить. Ведущее "n1" — наша собственная версия
# формата словаря calc; её меняем руками, когда меняется состав полей
# в compute_natal (например, добавим Лилит).
CALC_VERSION = f"n1-k{version('kerykeion')}-s{version('pyswisseph')}"

# Время, которое подставляем, когда час рождения неизвестен.
#
# Полдень, а не полночь: без времени нельзя считать дома, Асцендент и MC —
# они «проезжают» весь круг за сутки. Полдень — середина возможного
# диапазона, то есть худшая ошибка вдвое меньше, чем от полуночи. Плюс
# полночь опасна ещё и тем, что при пересчёте в UTC легко перескакивает
# на соседнюю дату, и тогда уезжает уже Луна.
UNKNOWN_TIME = time(12, 0)


@dataclass(frozen=True, slots=True)
class Place:
    """Место рождения, готовое к показу и к расчёту.

    Отдельный тип, а не astro_core.geo.City, по двум причинам:

    * City — это строка из базы GeoNames со своими полями (население,
      английское имя); наружу должно уходить только то, что нужно
      интерфейсу и расчёту;
    * место может прийти не из справочника, а точкой на карте
      (см. place_from_coords) — City для этого не подходит.

    label — то, что человек видит в списке и потом в шапке своей карты:
    «Ростов-на-Дону, RU». Страна в подписи обязательна, иначе два
    одинаковых названия в списке не различить.
    """

    label: str
    lat: float
    lon: float
    tz: str


def _place_from_city(city: City) -> Place:
    return Place(
        label=f"{city.display_name}, {city.country}",
        lat=city.lat,
        lon=city.lon,
        tz=city.tz,
    )


def search_places(query: str, limit: int = 8) -> list[Place]:
    """Подсказки для поля «город рождения». Крупные города — первыми.

    Пустой список означает «ничего не нашли» (в том числе если ввели
    один символ — поиск начинается с двух). Это не ошибка: интерфейс
    показывает «уточните название», а не падает.

    Функция синхронная и в базу не ходит: справочник городов целиком
    лежит в памяти процесса, поиск — двоичный по отсортированному
    индексу, доли миллисекунды.
    """
    return [_place_from_city(c) for c in search_cities(query, limit)]


def place_from_coords(lat: float, lon: float, label: str | None = None) -> Place:
    """Место, заданное координатами, — для точки на карте или для села,
    которого нет в справочнике (там только города от 5000 жителей).

    Таймзону в этом случае определяем геометрически (timezonefinder):
    по контурам часовых поясов. Именно ИМЯ зоны, а не смещение —
    смещение зависит от даты рождения и вычисляется позже, в расчёте.
    """
    return Place(
        label=label or f"{lat:.4f}, {lon:.4f}",
        lat=lat,
        lon=lon,
        tz=tz_at(lat, lon),
    )


def _input_hash(
    birth_local: datetime, lat: float, lon: float, tz: str, time_known: bool
) -> str:
    """Отпечаток входных данных: одинаковый вход — одинаковая строка.

    Что входит и почему именно это:

    * дата и время рождения, флаг «время известно». Флаг обязателен:
      «родился ровно в 12:00» и «время не помню» дают одинаковый расчёт,
      но это РАЗНЫЕ карты — во второй нельзя показывать дома, и промпт
      для неё другой. Без флага в хеше они схлопнулись бы в одну строку;

    * координаты и зона. Округляем до 4 знаков — это ~11 метров, гораздо
      точнее, чем нужно астрологии (0.01° долготы двигает Асцендент
      меньше чем на минуту дуги). Округление здесь — не про точность,
      а про стабильность: без него один и тот же город, пришедший
      из справочника и из формы, мог бы дать разные хеши из-за
      последнего бита float.

    Чего в хеше НЕТ: подписи места. «Ростов-на-Дону, RU» и «Ростов-на-Дону»
    с теми же координатами — одна и та же карта, расчёт от подписи
    не зависит.

    Название функции с подчёркиванием: это внутреннее правило модуля.
    Именно поэтому вычисление хеша живёт здесь, а не в вызывающем коде, —
    иначе бот и веб однажды посчитают его по-разному, и у одного человека
    появятся две «одинаковые» карты.
    """
    parts = "|".join(
        [
            birth_local.isoformat(timespec="minutes"),
            "t" if time_known else "f",
            f"{lat:.4f}",
            f"{lon:.4f}",
            tz,
        ]
    )
    return hashlib.sha256(parts.encode("utf-8")).hexdigest()


async def _find_by_hash(
    session: AsyncSession, user_id: int, input_hash: str
) -> Chart | None:
    stmt = select(Chart).where(
        Chart.user_id == user_id, Chart.input_hash == input_hash
    )
    return await session.scalar(stmt)


async def create_chart(
    session: AsyncSession,
    *,
    user_id: int,
    birth_local: datetime,
    place: Place,
    time_known: bool = True,
) -> Chart:
    """Главная функция модуля: данные рождения → строка в charts.

    Возвращает либо только что созданную карту, либо ту, что уже была,
    если этот пользователь считал ровно эти данные раньше. Для вызывающего
    разницы нет — он в обоих случаях получает объект Chart и работает
    дальше. Отличить можно по chart.created_at, если вдруг понадобится.

    Все аргументы, кроме сессии, — только по имени (звёздочка в сигнатуре).
    Иначе на месте вызова получилось бы create_chart(s, 1, dt, place, False),
    где последний False читается как что угодно.

    Транзакцию НЕ коммитим — это делает вызывающий (см. get_session
    в app/db.py). Причина: создание карты почти всегда часть более крупной
    работы («создать пользователя, посчитать карту, записать событие»),
    и решать, что считать успехом, должен тот, кто эту работу затеял.
    """
    # Время неизвестно — подставляем полдень ЗДЕСЬ, до вычисления хеша.
    # Если оставить это вызывающему, бот подставит 12:00, веб — 00:00,
    # и одна и та же карта запишется дважды.
    if not time_known:
        birth_local = datetime.combine(birth_local.date(), UNKNOWN_TIME)
    else:
        # Секунды и микросекунды в дате рождения — всегда мусор от datetime.now()
        # или парсера формы. В хеш они попадают, и «17:20» из бота разошлось бы
        # с «17:20:00.000123» из веб-формы.
        birth_local = birth_local.replace(second=0, microsecond=0)

    input_hash = _input_hash(
        birth_local, place.lat, place.lon, place.tz, time_known
    )

    # Шаг 1: может, уже считали. Проверка до расчёта, а не после, —
    # расчёт стоит сотню миллисекунд процессорного времени.
    existing = await _find_by_hash(session, user_id, input_hash)
    if existing is not None:
        return existing

    # Шаг 2: считаем.
    #
    # to_thread, потому что compute_natal — обычный синхронный код, который
    # молотит процессором ~50–150 мс (эфемериды Swiss Ephemeris). Вызванный
    # напрямую в async-обработчике, он на это время замораживает ВЕСЬ
    # процесс: другие запросы не обрабатываются, ответы не отправляются.
    # to_thread уводит его в отдельный поток, и event loop остаётся живым.
    natal = await asyncio.to_thread(
        compute_natal, birth_local, place.lat, place.lon, place.tz
    )

    chart = Chart(
        user_id=user_id,
        birth_local=birth_local,
        time_known=time_known,
        # Обрезаем под String(128): подпись места приходит снаружи, и длинное
        # название («Сан-Кристобаль-де-лас-Касас, MX») не должно ронять вставку.
        place_name=place.label[:128],
        lat=place.lat,
        lon=place.lon,
        tz=place.tz,
        input_hash=input_hash,
        # Контейнер под все расчёты по этим данным рождения. Сейчас в нём
        # только натальная карта; matrix и eastern добавятся сюда же
        # соседними ключами, новой таблицы не потребуется.
        calc={"natal": natal},
        calc_version=CALC_VERSION,
    )

    # Шаг 3: вставка с защитой от гонки.
    #
    # Между проверкой на шаге 1 и вставкой здесь прошло время (мы считали
    # карту). За это время тот же человек мог отправить форму второй раз —
    # два запроса, оба не нашли дубль, оба вставляют. Уникальная пара
    # (user_id, input_hash) в базе не даст записать второй, и он получит
    # IntegrityError.
    #
    # begin_nested() — это SAVEPOINT, точка сохранения внутри транзакции.
    # Без него ошибка вставки ломает ВСЮ транзакцию: Postgres переводит её
    # в состояние «отменена», и любой следующий запрос отвечает
    # «current transaction is aborted». С савпоинтом откатывается только
    # неудачная вставка, и мы спокойно продолжаем — идём за той картой,
    # которую успел записать конкурент.
    try:
        async with session.begin_nested():
            session.add(chart)
        return chart
    except IntegrityError:
        existing = await _find_by_hash(session, user_id, input_hash)
        if existing is not None:
            return existing
        # Сюда попадаем, если IntegrityError был не про дубль карты
        # (например, user_id ссылается на несуществующего пользователя).
        # Глушить такое нельзя — это ошибка в коде вызывающего.
        raise


async def get_chart(
    session: AsyncSession, chart_id: int, *, user_id: int | None = None
) -> Chart | None:
    """Карта по идентификатору. Возвращает None, если её нет.

    user_id — проверка владения, и её нужно передавать ВСЕГДА, когда
    идентификатор пришёл снаружи (из URL, из callback-кнопки). Пропустив
    её, мы получаем классическую дыру: человек меняет /chart/41 на
    /chart/42 и читает чужую дату рождения.

    Без user_id функция вызывается только там, где владелец уже проверен
    выше или неважен — например, в админке.
    """
    stmt = select(Chart).where(Chart.id == chart_id)
    if user_id is not None:
        stmt = stmt.where(Chart.user_id == user_id)
    return await session.scalar(stmt)


async def list_charts(session: AsyncSession, user_id: int) -> list[Chart]:
    """Все карты пользователя, свежие первыми.

    Их обычно одна-две («своя» и «мужа»), поэтому ни постраничности,
    ни лимита здесь нет — и то и другое добавим, если такие пользователи
    появятся.
    """
    stmt = (
        select(Chart)
        .where(Chart.user_id == user_id)
        .order_by(Chart.created_at.desc())
    )
    return list(await session.scalars(stmt))
