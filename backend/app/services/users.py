"""Пользователи: найти по платформенному идентификатору или завести нового.

Регистрации в сервисе нет — ни логина, ни пароля, ни подтверждения почты.
Человека узнаёт платформа, а мы получаем от неё идентификатор:

* Telegram — числовой id из сообщения;
* ВКонтакте — vk_id из подписанных launch params;
* веб-стенд — случайный UUID, который мы сами положили в cookie на год.

Все три случая — это пара (platform, external_id), и уникальна именно ПАРА:
идентификатор 12345 в Telegram и 12345 во ВКонтакте принадлежат разным
людям. Отсюда и единственная функция модуля: get_or_create().

Про cookie в вебе честно: почистил куки или сменил браузер — для нас это
новый человек, со своим лимитом генераций и пустым списком карт. Для
тестового стенда это приемлемо (тестеров десяток, и они знакомые), для
продукта дырку закроет вход через VK.

Про Telegram, VK и HTTP здесь, как и в остальных сервисах, нет ни слова:
cookie читает веб-слой, сообщение разбирает бот, а сюда приходит уже
готовая пара строк. Поэтому один и тот же код обслуживает все каналы.
"""

from __future__ import annotations

from datetime import UTC, datetime

from sqlalchemy import select
from sqlalchemy.dialects.postgresql import insert as pg_insert
from sqlalchemy.ext.asyncio import AsyncSession

from app.models import Platform, User


async def _find(
    session: AsyncSession, platform: Platform, external_id: str
) -> User | None:
    stmt = select(User).where(
        User.platform == platform, User.external_id == external_id
    )
    return await session.scalar(stmt)


async def get_by_id(session: AsyncSession, user_id: int) -> User | None:
    """Пользователь по внутреннему id. None, если такого нет.

    Нужен там, где пользователь уже опознан раньше, а работа идёт в ДРУГОЙ
    сессии: фоновая задача генерации получает id, а не объект. Тащить объект
    между сессиями нельзя — он остаётся привязан к своей, уже закрытой, и
    обращение к нему выстреливает в самом неудобном месте.
    """
    return await session.get(User, user_id)


async def get_or_create(
    session: AsyncSession,
    *,
    platform: Platform,
    external_id: str,
    source: str | None = None,
) -> User:
    """Найти пользователя по паре (platform, external_id) или создать.

    Возвращает всегда: либо существующего, либо только что созданного.
    Вызывается в самом начале обработки любого запроса — это первое, что
    делает и веб-страница, и будущий обработчик сообщения бота.

    source — метка канала привлечения ("bot_old_base", "vk_ads_may").
    Проставляется ТОЛЬКО при создании: канал — свойство первого касания,
    и переписывать его при каждом визите значит потерять ответ на вопрос
    «откуда пришли те, кто платит». У существующего пользователя аргумент
    молча игнорируется, и это не забывчивость, а правило.

    Коммит не делаем: транзакцией управляет вызывающий (см. app/db.py).
    """
    # Шаг 1: быстрый путь. Подавляющее большинство запросов — от людей,
    # которые уже есть в базе, и для них всё заканчивается одним SELECT.
    user = await _find(session, platform, external_id)
    if user is not None:
        return _revive_if_deleted(user)

    # Шаг 2: вставка, устойчивая к гонке.
    #
    # Между SELECT выше и вставкой здесь проходит время, и в него легко
    # влезает второй запрос того же человека: браузер тянет страницу и
    # что-нибудь ещё параллельно, а бот получает два быстрых сообщения
    # подряд. Оба запроса не нашли пользователя, оба вставляют — и второй
    # падает на уникальности пары.
    #
    # Лечится не проверкой «а вдруг уже есть» (она и есть шаг 1, и от
    # гонки не спасает), а тем, что вставка и разрешение конфликта — одна
    # команда для базы: ON CONFLICT DO NOTHING. Postgres выполняет её
    # атомарно, влезть внутрь невозможно.
    #
    # RETURNING отдаёт строку, только если вставка ДЕЙСТВИТЕЛЬНО произошла.
    # При конфликте (DO NOTHING) результат пуст — это и есть сигнал
    # «меня опередили», а не ошибка.
    stmt = (
        pg_insert(User)
        .values(platform=platform, external_id=external_id, source=source)
        .on_conflict_do_nothing(index_elements=["platform", "external_id"])
        .returning(User)
    )
    created = (await session.scalars(stmt)).first()
    if created is not None:
        return created

    # Шаг 3: нас опередили — забираем строку, которую записал конкурент.
    #
    # None здесь означал бы, что строка пропала между конфликтом и этим
    # запросом, то есть кто-то удаляет пользователей физически. Мы так не
    # делаем (см. deleted_at в models.py), поэтому это не «редкий случай»,
    # а сломанное предположение — лучше упасть здесь, чем отдать наверх
    # None и получить непонятную ошибку страницей позже.
    user = await _find(session, platform, external_id)
    if user is None:  # pragma: no cover
        raise RuntimeError(
            f"Пользователь {platform.value}:{external_id} исчез сразу после "
            "конфликта вставки — кто-то удаляет строки users физически"
        )
    return _revive_if_deleted(user)


def mark_vk_messages_allowed(user: User) -> bool:
    """Запомнить, что человек разрешил сообществу писать; True — если впервые.

    Возвращаемое значение нужно вызывающему, чтобы записать событие воронки
    ровно один раз: экран подписки человек открывает много раз, а разрешение
    даёт однажды. Время уже стоит — не переписываем: первая дата и есть
    точка конверсии.

    Синхронная, в базу не ходит: правка уедет с ближайшим flush сессии.
    """
    if user.vk_messages_allowed_at is not None:
        return False
    user.vk_messages_allowed_at = datetime.now(UTC)
    return True


def _revive_if_deleted(user: User) -> User:
    """Снять отметку об удалении, если человек вернулся сам.

    deleted_at означает не «пользователя нет», а «его персональные данные
    стёрты по его просьбе»: имя обнулено, карты снесены каскадом, строка
    оставлена. Оставлена именно затем, чтобы вернувшийся не упёрся в
    конфликт по уникальной паре — регистрации нет, и отказать ему не в чем.

    Раз он снова пишет нам сам, отметку снимаем: сохранять её значило бы
    держать активного человека в статусе удалённого — он не попадёт ни в
    рассылку, ни в подсчёты живой базы. Данные при этом не воскресают:
    карты удалены физически, новую он заведёт заново.

    Функция синхронная и в базу не ходит: правка атрибута попадёт в базу
    при ближайшем flush той же сессии.
    """
    if user.deleted_at is not None:
        user.deleted_at = None
    return user
