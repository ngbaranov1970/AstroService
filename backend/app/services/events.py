async def log(
    session: AsyncSession,
    name: str,
    *,
    user_id: int | None = None,
    **props: Any,
) -> Event:
    """Записать факт. Возвращает объект события (обычно он не нужен).

    Подробности передаются именованными аргументами и складываются в props:

        await events.log(session, events.CHART_CREATED,
                         user_id=user.id, chart_id=chart.id)

    Так короче, чем собирать словарь на месте вызова, и заодно всё
    содержимое строки видно в одном выражении — а значит, видно и нарушение
    правила «никаких персональных данных», если кто-то попробует передать
    сюда город или дату рождения.

    Коммита нет — как и во всех сервисах, транзакцией правит вызывающий.
    Практическое следствие правильное: событие сохранится вместе с тем
    действием, которое описывает, или не сохранится вовсе. «Карта создана»
    без самой карты было бы враньём в отчётах.

    Про надёжность честно: аналитика не должна ронять запрос. Здесь она и не
    может — session.add() в базу не ходит, а падение на flush означает, что
    сломалась вся транзакция, то есть запрос всё равно не выполнен.
    Отдельного try/except поэтому нет: глушить ошибку, которая и так
    фатальна, — значит прятать причину.
    """
    event = Event(name=name, user_id=user_id, props=props)
    session.add(event)
    # DEBUG, а не INFO: событий по замыслу много, и поток строк «записал
    # событие» утопил бы в логе настоящие сообщения.
    logger.debug("Событие %s (пользователь %s): %s", name, user_id, props)
    return event


async def already_logged(
    session: AsyncSession,
    name: str,
    *,
    user_id: int,
    chart_id: int | None = None,
    pair_id: int | None = None,
) -> bool:
    """Писали ли уже такое событие про эту карту или про эту пару.

    Ровно один из chart_id и pair_id обязателен, иначе ValueError.

    Для событий-показов, которые иначе повторяются без действий человека:
    страница разбора перечитывает себя раз в пять секунд, и один показ цены
    давал бы десяток строк, завышая верхнюю ступень воронки покупки в разы.

    Смотрит незакоммиченные строки этой же сессии (autoflush), поэтому два
    вызова подряд в одном запросе второй строки не создадут.
    """
    # У парного отчёта chart_id тоже заполнен — это якорная карта инициатора,
    # общая у всех его пар. Ключ по ней посчитал бы показ цены на «я и Маша»
    # показом на «я и Лена», и воронка пары молча недосчитала бы верх.
    if (chart_id is None) == (pair_id is None):
        raise ValueError("pass exactly one of chart_id, pair_id")

    key, value = ("chart_id", chart_id) if chart_id is not None else ("pair_id", pair_id)
    stmt = (
        select(Event.id)
        .where(
            Event.name == name,
            Event.user_id == user_id,
            # ->> по JSONB: идентификатор лежит в props, своей колонки у него
            # нет. Индекса на это выражение нет, и он не нужен — запрос всегда
            # сужен по user_id, а событий на одного человека десятки.
            Event.props[key].astext == str(value),
        )
        .limit(1)
    )
    return await session.scalar(stmt) is not None
