"""Аналитика воронки: запись фактов в таблицу events.

Модуль крошечный по коду и важный по смыслу. Он отвечает на единственный
вопрос запуска — ГДЕ ЛЮДИ ОТВАЛИВАЮТСЯ: из ста открывших форму дату ввели
сорок, разбор дочитали двадцать, до полного дошли восемь. Без этих строк
известно только «выручка маленькая», и непонятно, что чинить.

Два правила, ради которых модуль вообще существует отдельным файлом.

ПЕРВОЕ: имена событий — константы отсюда, а не строки в месте вызова.
В базе `name` — обычный varchar (enum потребовал бы миграции на каждое новое
событие, и события просто перестали бы писать). Значит, от опечатки
«paywall_shown» / «paywall_show» защищает только дисциплина: единственный
список имён — тот, что ниже. Отчёт, который молча считает половину событий,
хуже отсутствующего.

ВТОРОЕ: в props НЕТ персональных данных. Ни имени, ни даты рождения,
ни города — только идентификаторы и служебные метки. Персональные данные
живут в `charts` именно затем, чтобы их можно было удалить одним DELETE по
просьбе человека; расползшись по миллиону строк аналитики, они станут
неудаляемыми. Это то же правило, что для логов (см. CLAUDE.md), и по той же
причине: и логи, и аналитика утекают целиком и незаметно.
"""

from __future__ import annotations

import logging
from typing import Any

from sqlalchemy.ext.asyncio import AsyncSession

from app.models import Event

logger = logging.getLogger(__name__)

# --- Имена событий ---------------------------------------------------------
# Глагол в прошедшем времени: событие — это случившийся факт, а не намерение.
# Порядок в файле — порядок в воронке, так список читается как сценарий.

# Открыл форму ввода данных рождения (стартовая страница стенда).
FORM_OPENED = "form_opened"

# Отправил форму и выбрал город — карта посчитана и записана.
CHART_CREATED = "chart_created"

# Нажал кнопку разбора. Пишется ДО генерации: между «попросил» и «получил»
# лежат 30–60 секунд и возможная авария, и разница между этими двумя
# счётчиками — это и есть доля неудач, которую иначе не увидеть.
REPORT_REQUESTED = "report_requested"

# Текст готов и записан в базу.
REPORT_READY = "report_ready"

# Генерация упала. Отдельное событие, а не только строчка в логе, потому что
# у отчёта намеренно нет колонки «статус»: по базе «идёт» и «упало»
# неразличимы, и это единственный способ посчитать аварии обычным запросом.
REPORT_FAILED = "report_failed"

# Отказ по правилам: лимит бесплатных или «только для тестеров».
# Не авария — штатный исход, но частота у него продуктовая: если в лимит
# упираются все подряд, значит лимит мал.
REPORT_DENIED = "report_denied"

# Оценка разбора тестером: 1–5 и необязательный комментарий.
FEEDBACK = "feedback"

# Прошёл по секретной ссылке /?t=... и стал тестером.
TESTER_ACTIVATED = "tester_activated"


async def log(
    session: AsyncSession,
    name: str,
    *,
    user_id: int | None = None,
    **props: Any,
) -> Event:
    """Записать факт. Возвращает объект события (обычно он не нужен).

    Подробности передаются именованными аргументами и складываются в props:

        await events.log(session, events.CHART_CREATED,
                         user_id=user.id, chart_id=chart.id)

    Так короче, чем собирать словарь на месте вызова, и заодно всё
    содержимое строки видно в одном выражении — а значит, видно и нарушение
    правила «никаких персональных данных», если кто-то попробует передать
    сюда город или дату рождения.

    Коммита нет — как и во всех сервисах, транзакцией правит вызывающий.
    Практическое следствие правильное: событие сохранится вместе с тем
    действием, которое описывает, или не сохранится вовсе. «Карта создана»
    без самой карты было бы враньём в отчётах.

    Про надёжность честно: аналитика не должна ронять запрос. Здесь она и не
    может — session.add() в базу не ходит, а падение на flush означает, что
    сломалась вся транзакция, то есть запрос всё равно не выполнен.
    Отдельного try/except поэтому нет: глушить ошибку, которая и так
    фатальна, — значит прятать причину.
    """
    event = Event(name=name, user_id=user_id, props=props)
    session.add(event)
    # DEBUG, а не INFO: событий по замыслу много, и поток строк «записал
    # событие» утопил бы в логе настоящие сообщения.
    logger.debug("Событие %s (пользователь %s): %s", name, user_id, props)
    return event
