"""Проверка того, что пришло из HTML-формы.

Ровно одна ответственность: строки от браузера → нормальные типы Python,
либо понятная человеку ошибка. Ни базы, ни расчётов, ни шаблонов — поэтому
файл целиком проверяется обычными тестами, без поднятого приложения.

Почему это не в router.py: маршрут должен читаться как сценарий («разобрал,
позвал сервис, отдал шаблон»), а половина проверок ввода — про частные
случаи форматов, и в теле обработчика они этот сценарий заслоняют.

Почему это не в app/services/charts.py: там граница «сервис знает про наши
данные, а не про то, откуда они пришли». `<input type="date">`, галочка
«время не помню» и пустая строка вместо None — это устройство HTML-формы,
и в сервисе, который обслуживает ещё и бота, ему делать нечего.

Общее правило файла: текст исключения FormError показывается пользователю
как есть. Значит формулировки — человеческие и без технических подробностей.
"""

from __future__ import annotations

from datetime import UTC, date, datetime, time

# Нижняя граница даты рождения. До унификации часовых поясов города жили по
# местному солнечному времени, и исторические зоны в tzdata там становятся
# приблизительными — а точность расчёта у нас первое требование.
MIN_BIRTH_YEAR = 1900

# Потолок длины имени: столько же, сколько в колонке charts.person_name.
MAX_NAME = 64


class FormError(ValueError):
    """Человек ввёл что-то не то. Текст исключения показывается ему же."""


def parse_birth(birth_date: str, birth_time: str, time_known: bool) -> datetime:
    """Поля формы → локальное время рождения (naive datetime).

    Поля `<input type="date">` и `type="time"` присылают ISO-формат
    («1990-05-11», «17:20»), но полагаться на это нельзя: ту же форму можно
    отправить curl'ом или старым браузером, который отдаёт обычный текст.

    Когда время неизвестно, ставим полночь-заглушку и НЕ пытаемся угадывать.
    Подстановкой полудня (и объяснением, почему именно полудня) занимается
    charts.create_chart — в одном месте для всех платформ, иначе бот и веб
    однажды подставят разное и одна и та же карта запишется дважды.
    """
    try:
        day = date.fromisoformat(birth_date.strip())
    except ValueError:
        raise FormError(
            "Дата рождения не распознана — ожидается вид 1990-05-11."
        ) from None

    if day.year < MIN_BIRTH_YEAR:
        raise FormError(f"Даты раньше {MIN_BIRTH_YEAR} года не поддерживаются.")
    # Сегодняшний день берём по UTC. Часовой пояс сервера тут ни при чём:
    # проверка отсекает опечатки в годе («2091»), а не разбирается, наступило
    # ли уже завтра во Владивостоке.
    if day > datetime.now(UTC).date():
        raise FormError("Дата рождения в будущем.")

    if not time_known:
        return datetime.combine(day, time(0, 0))

    raw = birth_time.strip()
    if not raw:
        raise FormError("Укажите время рождения или отметьте «время не помню».")
    try:
        # fromisoformat принимает и «17:20», и «17:20:00».
        hhmm = time.fromisoformat(raw)
    except ValueError:
        raise FormError(
            "Время рождения не распознано — ожидается вид 17:20."
        ) from None
    return datetime.combine(day, hhmm)


def clean_name(raw: str) -> str | None:
    """Имя человека, чья карта. Пустое поле — это None, а не пустая строка.

    Разница не косметическая: в базе колонка nullable, и NULL означает
    «не подписана», а пустая строка означала бы «подписана пустотой» —
    в списке карт и в админке это две разные ситуации, которые пришлось бы
    различать в каждом шаблоне.
    """
    name = raw.strip()[:MAX_NAME]
    return name or None


def parse_coords(lat: float, lon: float) -> tuple[float, float]:
    """Координаты выбранного города — с проверкой диапазона.

    Приходят скрытым полем, то есть от клиента, то есть могут быть любыми.
    Мусор здесь уронил бы расчёт где-то в недрах эфемерид, и понять по
    ошибке, что случилось, было бы нельзя.
    """
    if not (-90.0 <= lat <= 90.0 and -180.0 <= lon <= 180.0):
        raise FormError("Координаты города испорчены — выберите город заново.")
    return lat, lon
