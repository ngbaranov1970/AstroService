// Блок подписки на сообщество внутри VK Mini App.
// Показывается на странице разбора вместо вырезанного пейволла (продавать в
// VK нельзя). Делает три вещи: открывает окна VK «подписаться» и «разрешить
// сообщения», сообщает нам об успехе второго — список разрешивших VK через
// API не отдаёт, ведём его сами — и гасит этот флаг обратно по кнопке
// «Не присылать».
//
// Какими кнопки видны при загрузке, решает сервер (report.html): подписку он
// узнаёт у groups.isMember, разрешение — из своей базы. Скрипт лишь
// переключает их после нажатия, чтобы не перезагружать страницу.
//
// Консоли в мобильном приложении VK нет, поэтому каждый отказ пишется в
// подпись под кнопками: молчащая кнопка неотличима от сломанной страницы.

// Вся логика завёрнута в функцию, которая тут же себя и вызывает: так
// объявленные ниже имена не попадают в глобальную область и не сталкиваются
// с чужими. В Python роль такой обёртки играет модуль.
(function () {
  // Ищем секцию по классу. querySelector берёт первый элемент по
  // CSS-селектору; точка перед именем означает «класс», как в стилях.
  const offer = document.querySelector('.group-offer');

  // Секции на странице нет — мы не в VK или сообщество не настроено.
  // ! — логическое «не», как not в Python.
  if (!offer) {
    return;
  }

  // dataset даёт доступ к атрибутам data-* из разметки: data-group-id
  // становится dataset.groupId. Значение всегда строка, поэтому число для
  // VK получаем через Number().
  const groupId = Number(offer.dataset.groupId);
  const allowUrl = offer.dataset.allowUrl;
  const denyUrl = offer.dataset.denyUrl;

  // Ищем элементы внутри секции, а не по всей странице: offer.querySelector
  // смотрит только среди потомков.
  // Кнопки «Подписаться» может не быть вовсе: страница не рисует её тем, про
  // кого VK сказал, что они уже подписаны. Отсюда проверки на null ниже.
  const joinButton = offer.querySelector('.js-vk-join');
  const allowButton = offer.querySelector('.js-vk-allow');
  const denyButton = offer.querySelector('.js-vk-deny');
  const status = offer.querySelector('.js-vk-status');

  // Показать или спрятать кнопку. hidden — обычный атрибут HTML, браузер сам
  // не рисует элемент с ним; из JS он выглядит как свойство true/false.
  // Первый аргумент может оказаться null (см. выше) — тогда просто выходим.
  const show = (button, visible) => {
    if (button) {
      button.hidden = !visible;
    }
  };

  // Показать человеку короткую подпись под кнопками.
  // Стрелочная функция — это то же самое, что обычная функция, только
  // короче: (аргументы) => тело. Похоже на lambda в Python, но телом может
  // быть и блок в фигурных скобках.
  const say = (text) => {
    if (status) {
      // textContent, а не innerHTML: текст вставляется как текст, разметка из
      // него не выполняется.
      status.textContent = text;
    }
  };

  // Библиотека VK не загрузилась — дальше идти некуда, но сказать об этом
  // надо: раньше здесь стоял тихий выход, и кнопка выглядела просто мёртвой.
  if (!window.vkBridge) {
    say('Не загрузилась библиотека VK. Обновите страницу.');
    return;
  }

  // ID сообщества не число: в .env пусто или лежит мусор. Без него VK
  // отказывает молча, поэтому проверяем сами. Number('') даёт 0, а
  // Number('abc') — NaN, и NaN не равен даже самому себе: отсюда проверка
  // через Number.isNaN, сравнение === NaN не работает никогда.
  if (!groupId || Number.isNaN(groupId)) {
    say('Сообщество не настроено — обратитесь к нам в группе.');
    return;
  }

  // Обёртка над vkBridge.send с собственным ограничением по времени.
  // Зачем: клиент VK на отправленный метод может не ответить вовсе — тогда
  // промис не выполняется и не отклоняется, catch не срабатывает, и человек
  // видит кнопку, которая «не нажимается».
  // Promise.race берёт несколько промисов и отдаёт результат того, кто
  // финишировал первым; второй участник здесь — таймер, который через ms
  // миллисекунд отклоняет гонку.
  const sendWithTimeout = (method, params, ms = 15000) =>
    Promise.race([
      vkBridge.send(method, params),
      // Новый промис получает две функции: первой его завершают успехом,
      // второй — ошибкой. Успех этому таймеру не нужен, поэтому первая
      // названа и не используется — редактор об этом честно предупреждает.
      new Promise((resolve, reject) => {
        setTimeout(() => reject(new Error('VK не ответил')), ms);
      }),
    ]);

  // Ошибку VK — в короткую строку для подписи под кнопками.
  // Bridge кладёт подробности в error.error_data; там либо числовой
  // error_code от API, либо текстовый error_reason вроде 'User denied'.
  // ?. — «возьми свойство, только если слева не null»; ?? — «возьми правое
  // значение, если левое null или undefined».
  const describe = (error) => {
    const data = error?.error_data ?? {};
    const reason = data.error_reason ?? data.error_code ?? error?.message;
    // reason иногда приходит объектом — тогда показываем его как JSON,
    // иначе в подписи было бы бесполезное [object Object].
    if (reason && typeof reason === 'object') {
      return JSON.stringify(reason);
    }
    return reason ?? 'причина неизвестна';
  };

  // Обработчик кнопки «Подписаться».
  // async перед функцией означает, что внутри можно писать await — как
  // async def в Python. await ждёт результата, не блокируя страницу.
  // ?. — «позови метод, только если слева не null»: без этой проверки строка
  // упала бы у тех, кому кнопку не нарисовали.
  joinButton?.addEventListener('click', async () => {
    // Подпись меняем до вызова VK: она доказывает, что нажатие вообще дошло
    // до скрипта. Если после нажатия текст не появился — не работает сам
    // скрипт, а не метод VK.
    say('Открываем окно VK…');
    try {
      // VKWebAppJoinGroup открывает системное окно VK «Подписаться?».
      await sendWithTimeout('VKWebAppJoinGroup', { group_id: groupId });
      // Подписка состоялась — кнопка больше не нужна. Со следующего захода
      // её не будет и в разметке: groups.isMember ответит «да».
      show(joinButton, false);
      say('Готово, вы подписаны.');
    } catch (error) {
      // Сюда попадаем и когда человек нажал «Отмена» — это не поломка,
      // поэтому текст нейтральный.
      say('Не получилось подписаться (' + describe(error) + ').');
    }
  });

  // Обработчик кнопки «Разрешить сообщения» — ради него всё и затевалось.
  allowButton?.addEventListener('click', async () => {
    say('Открываем окно VK…');

    // Спрашиваем у клиента VK, знает ли он метод. Старое приложение на
    // телефоне незнакомый метод не отклоняет, а просто молчит — и без этой
    // проверки мы ждали бы ответа впустую все 15 секунд.
    try {
      const supported = await sendWithTimeout(
        'VKWebAppAllowMessagesFromGroup',
        { group_id: groupId },
      );
      // Ответ VK — объект вида { result: true }. Пришло что угодно другое —
      // считаем, что разрешения нет.
      if (!supported?.result) {
        say('VK не подтвердил разрешение. Попробуйте ещё раз.');
        return;
      }
    } catch (error) {
      say('Разрешение не выдано (' + describe(error) + ').');
      return;
    }

    // Разрешение получено — меняем кнопку на обратную. Делаем это до fetch:
    // для человека решает ответ VK, а наша запись — уже наша забота.
    show(allowButton, false);
    show(denyButton, true);

    // VK согласие получил — теперь запоминаем его у себя. fetch отправляет
    // запрос из браузера; POST, потому что запрос меняет наши данные.
    // Адрес уже содержит ?s=<токен сессии>: внутри VK личность едет в URL.
    try {
      await fetch(allowUrl, { method: 'POST' });
      say('Спасибо! Гороскоп дня будет приходить в личные сообщения.');
    } catch (error) {
      // Разрешение в VK выдано, а наша запись не прошла — сети не было или
      // сессия истекла. Человеку врать не о чем: для него всё сработало,
      // а восстановится это при следующем заходе.
      say('Спасибо! Разрешение получено.');
    }
  });

  // Обработчик кнопки «Не присылать». В VK ходить незачем: отменить выданное
  // разрешение Bridge не умеет вовсе, а рассылка берёт получателей по нашему
  // флагу — погасив его, мы писать перестаём.
  denyButton?.addEventListener('click', async () => {
    say('Отключаем…');
    try {
      const response = await fetch(denyUrl, { method: 'POST' });
      // fetch считает ошибкой только сетевой сбой: ответ 403 «сессия
      // истекла» дошёл бы сюда как успех. Поэтому код ответа проверяем
      // руками — ok означает 2xx.
      if (!response.ok) {
        throw new Error(response.status);
      }
    } catch (error) {
      // Единственный случай, когда кнопки НЕ переключаем: флаг остался
      // поднятым, и обещать человеку тишину было бы неправдой.
      say('Не получилось отключить. Попробуйте ещё раз.');
      return;
    }

    show(denyButton, false);
    show(allowButton, true);
    say('Больше не пишем. Включить обратно можно этой же кнопкой.');
  });
})();
